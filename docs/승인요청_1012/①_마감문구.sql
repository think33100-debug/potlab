/* ① 마감 문구 — 마감표시() 한 곳 (2026-10-12)
   ★ 아직 안 올렸습니다. 세중님 승인 뒤에 올립니다.
   지우는 문장이 한 줄도 없습니다 (표·함수를 없애는 낱말이 안 쓰였습니다) →
   승인 창이 안 뜰 것으로 봅니다. ⚠ 그 낱말은 **주석에 적어도** 창을 띄웁니다
   (지침 8-7) — 그래서 여기서도 일부러 안 적습니다.

   ═══ 무엇을 바꾸나 ═══════════════════════════════════════════

   지금                                      바꿀 것
     apply_to 있음      → ''                 그대로
     공공기관인가       → '마감일 공고문 확인'  그대로 (순서는 아래로 내려갑니다)
     채용시까지|상시|수시|충원시|결원시
                        → '수시채용'          **둘로 갈라** 글귀를 달리 합니다
     그밖               → '마감일 공고문 확인'  그대로

   바꾼 뒤
     ① 접수 자리에 「채용시까지」 류  → '채용시까지 · 공고문 확인'
     ② 공공기관인가                 → '마감일 공고문 확인'
     ③ 「수시」·「상시」             → '수시채용'
     ④ 그밖                         → '마감일 공고문 확인'

   ═══ 세중님이 짚으신 것을 고쳤습니다 ═════════════════════════

   (1) `적격자|결원\s*시|충원\s*시` 를 **뺐습니다.**
       공공 공고문에 거의 늘 있는 문장입니다 —
         「적격자가 없는 경우 채용하지 않을 수 있음」
         「결원 시 차순위자 충원」
       **지금 자료 2,372건 전체에서 이 셋에 걸리는 공고는 0건**이었습니다.
       즉 쓸모가 없고, 첨부를 읽어 접수문장이 길어지면 걸리기 시작합니다.

   (2) **제목을 안 봅니다.** `p_접수문장` 만 봅니다.
       제목까지 보면 한국원자력의학원 14건이 걸립니다 —
         「별정직 직원모집 공고(입원의학과)_채용완료시 공고종료」
       제목에 그 말이 있어도 접수 기간이 적혀 있으면 날짜가 셉니다.

   (3) **접수 자리 앵커 안에서만** 봅니다.
       통째로 보면 이런 것이 걸립니다 (거짓 양성) —
         부민병원 「합격자발표 1차 서류전형 ~ **채용시까지** 개별 유선연락」
       이것은 **발표** 이야기이고 접수 기간이 아닙니다.
       hs_dates 가 합격자 발표일을 마감으로 집던 버그와 같은 결입니다 (2026-10-07).

   ═══ 마른 실행 (마감일이 **있는** 공고 전체에) ═══════════════

   세중님 합격 기준 — 「마감일 있는 공고가 하나라도 걸리면 틀린 것」

     A 제목+접수문장 통째 (처음 안)        마감일 있는데 걸림 **20건**
     B 접수문장만                          마감일 있는데 걸림 **6건**
     C 접수문장 + 접수 자리 앵커 (이 안)    마감일 있는데 걸림 **5건**

   **C 의 5건은 거짓 양성이 아닙니다.** 다섯 다 진짜 「채용시까지」 이고
   `apply_to` 쪽이 틀렸습니다 —

     길병원        apply_to 2099-12-31  「채용시 마감」            메움값
     한도병원      apply_to 2023-12-31  「채용 시 까지」           옛 메움값
     성남시의료원  apply_to 2026-12-31  「채용 완료 시」           메움값
     더블유병원    apply_to 2026-02-13  「2026년 02월 13일 ~ 채용 시 마감」  **시작일을 마감일로**
     이화 서울병원 apply_to 2026-10-12  「2026.09.22 ~ 채용시까지」          **시작일 쪽**

   다섯 다 `deadline_src` 가 **null** 입니다 — 어디서 온 값인지 기록이 없습니다.
   그래서 합격 기준이 「규칙이 틀렸다」가 아니라 **「자료가 틀렸다」** 를 가리켰습니다.
   이 5건은 ③ 칸되메우기 차례에 고칠 목록에 넣습니다 (apply_to 를 비우고 다시 읽기).

   마감일이 **없는** 공고 중 걸리는 것 — A·B 30건 → C **23건**.

   ═══ 제 판단 하나 ═══════════════════════════════════════════

   「채용시까지」 를 **공공기관보다 먼저** 봅니다.
   지침 15절이 공공에 「수시채용」 을 금한 까닭은 「수시라고 적으면 회원이
   마감일을 안 찾아보기 때문」 입니다. 그런데 '채용시까지 · 공고문 확인' 은
   **공고문을 보라고 말합니다.** 그래서 공공이어도 이 글귀가 더 알려 줍니다.
   「수시채용」 은 지금처럼 **공공에는 안 씁니다** (③이 ②보다 아래입니다).
   순서를 바꾸시려면 아래 첫 두 when 을 맞바꾸면 됩니다.

   ═══ 권한 ═══════════════════════════════════════════════════

   인수가 그대로라 **같은 함수**이고 ACL 이 유지됩니다. **손대지 않습니다.**
   지금 ACL 이 PUBLIC 을 포함하는 까닭 — `job_list` · `job_one` 이
   **비회원 공고 화면**에서 부릅니다. `tools/공개허용목록.json` 에 적힌 결정입니다.
   여기서 revoke 를 걸면 비회원 화면이 죽습니다.

   ═══ 부르는 곳 — **두 곳**입니다 ═════════════════════════════

     job_list  3번 · job_one  1번
   `admin_jobs` 라는 DB 함수는 **없습니다** — 관리자 화면은
   `web/lib/admin-jobs.ts` 가 표·뷰를 직접 읽습니다.
   (`alive_mark` 에 '마감표시' 가 4번 나오지만 변수 이름 `v_마감표시` 입니다)
   ═══════════════════════════════════════════════════════════ */

create or replace function public."마감표시"(
  p_apply_to date,
  p_id text,
  p_tab text,
  p_org_name text,
  p_title text,
  "p_접수문장" text
) returns text
language sql
stable
as $$
  select case
    /* 마감일이 있으면 날짜를 그대로 보여줍니다 */
    when p_apply_to is not null then ''

    /* ① 공고문이 **접수 자리에** 「채용시까지」 라고 적은 것.
         앵커(접수·모집·원서·지원 + 기간·기한·마감·일자·일시) 뒤 40자 안에서만 봅니다.
         「마감일 : 채용시까지」 꼴은 따로 받습니다 (중앙병원).
         공공이어도 이 글귀를 씁니다 — 공고문을 보라고 말하므로 지침 15절의
         걱정(마감일을 안 찾아봄)이 없습니다 */
    when coalesce(p_접수문장, '') ~
           '(접수|모집|원서|지원)\s*(기간|기한|마감|일자|일시)[^가-힣]{0,8}.{0,40}?(채용\s*시\s*까지|채용\s*시\s*마감|채용\s*완료\s*시|채용\s*시([^가-힣]|$))'
      or coalesce(p_접수문장, '') ~ '마감일\s*[:：]?\s*(채용\s*시\s*까지|채용\s*완료\s*시)'
      then '채용시까지 · 공고문 확인'

    /* ② 공공·대학·상급종합은 「수시채용」 으로 안 보입니다 (지침 15절) */
    when 공공기관인가(p_id, p_tab, p_org_name) then '마감일 공고문 확인'

    /* ③ 공고문이 「수시」·「상시」 라고 적은 것.
         지금 자료에서 이 길로 가는 공고는 **0건**입니다 (글자가 있는 공고가 없습니다).
         글귀는 넣어 둡니다 — 앞으로 들어올 수 있습니다 */
    when (coalesce(p_title, '') || ' ' || coalesce(p_접수문장, '')) ~ '수시|상시'
      then '수시채용'

    /* ④ 그밖 — 못 읽은 것은 숨기지 않고 「공고문 확인」 으로 적습니다 (지침 15절) */
    else '마감일 공고문 확인'
  end
$$;

