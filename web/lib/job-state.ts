/* 공고가 마감됐는지 한 곳에서 판단합니다 (node lib/job-state.test.mjs).

   마감일이 비어 있으면 마감으로 안 칩니다.
   인수인계 원칙이 「마감일이 비어 있으면 잘못 읽은 것」입니다 —
   자료를 못 받아온 것뿐인데 멀쩡한 공고를 막으면 안 됩니다.

   날짜는 한국 시간 기준입니다. UTC 로 재면 한국에서 자정 넘긴 뒤 아홉 시간 동안
   어제 날짜로 판단합니다. 마감일 당일은 아직 열린 것으로 봅니다. */

/* 한국은 1988년 뒤로 서머타임이 없습니다. 그래서 +9시간이 언제나 정확합니다.
   Intl 로 시간대를 다루지 않는 이유 — 미리보기 그림을 그리는 edge 런타임은
   ICU 가 잘려 있는 곳이 있어 timeZone 을 못 믿습니다 */
export const KST_OFFSET_MIN = 9 * 60;

/* 오늘 (한국) — 'YYYY-MM-DD' */
export function todayKst(now: Date = new Date()): string {
  return new Date(now.getTime() + KST_OFFSET_MIN * 60_000).toISOString().slice(0, 10);
}

/* 지금 (한국) — 'HH:MM:SS' */
export function nowTimeKst(now: Date = new Date()): string {
  return new Date(now.getTime() + KST_OFFSET_MIN * 60_000).toISOString().slice(11, 19);
}

/* ★ 2026-10-08 — 마감 **시각**까지 봅니다.
   DB 의 마감지났나(apply_to, apply_to_time) 와 **글자 하나 다르지 않게** 유지하십시오.
   한쪽만 고치면 화면과 목록이 어긋납니다.

     마감일이 없으면            마감 아님
     마감일 < 오늘              마감
     마감일 > 오늘              마감 아님
     마감일 = 오늘 · 시각 없음    마감 아님 (그날 종일)
     마감일 = 오늘 · 시각 있음    지금 시각 > 그 시각 이면 마감

   왜 — 중앙보훈병원은 10.16(금) **09:00** 마감인데, 전에는 그날 저녁에도
   「오늘 마감 · D-0」 으로 떠 있었습니다. 회원이 저녁에 보고 들어가면 닫혀 있습니다 */
export function isClosed(
  applyTo: string | null | undefined,
  today = todayKst(),
  applyToTime?: string | null,
  nowTime = nowTimeKst(),
): boolean {
  if (!applyTo) return false;
  const d = applyTo.slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) return false;
  if (d < today) return true;
  if (d > today) return false;
  if (!applyToTime) return false;            // 그날 종일
  return nowTime > applyToTime.slice(0, 8);
}

/* 마감 배지에 쓸 말과 색 (2026-10-09).

   ★ 전에는 같은 이름의 dday() 가 **목록과 상세에 따로** 있었습니다.
     2026-10-08 에 마감 시각을 넣으면서 목록만 고쳐서, 시각이 지난 그날
     상세에는 빨간 「오늘 마감」 이 그대로 남았습니다 (근로복지공단안산병원
     17:30 마감 공고로 확인). 그래서 한 벌로 모읍니다 —
     **마감 배지를 그리는 곳은 이 함수만 부릅니다.**

     마감일 없음        마감표시() 가 정한 말 (「마감일 공고문 확인」 등) · 회색
     마감 (시각 포함)    「마감」 · 회색 · over
     오늘 마감          「오늘 마감」 또는 「오늘 오후 5시 30분 마감」 · 빨강
     그 밖              「D-n」 · 사흘 이하면 빨강

   urgent 는 빨강으로 칠할지, over 는 흐리게 둘지입니다. 둘은 같이 못 켜집니다. */
export type 마감배지모양 = { text: string; urgent: boolean; over: boolean };

export function 마감배지(
  to: string | null | undefined,
  표시?: string | null,
  시각?: string | null,
  now: Date = new Date(),
): 마감배지모양 {
  if (!to) {
    return { text: 표시 || '마감일 공고문 확인', urgent: false, over: false };
  }
  if (isClosed(to, todayKst(now), 시각, nowTimeKst(now))) {
    return { text: '마감', urgent: false, over: true };
  }
  /* ★ 2026-10-22 세중님 2번 — 포털 **상세** 칸에 기관이 적은 말이 있으면
     (「채용시까지」) 날수 대신 그 말을 씁니다. 마감표시() 가 날짜가 있어도 그 말을
     내도록 바뀌었습니다 (supabase/migrations/2026_10_22_마감표시_접수마감글.sql).
     ⚠ 날수(D-n)가 그 공고에서는 안 보입니다 — 그 날짜는 **게시 만료일**이고
       기관이 사람을 뽑으면 그날 닫습니다. 「D-12」는 없는 여유를 알려 주는 말입니다.
       숨김·정렬은 그대로 apply_to 를 봅니다 */
  if (표시) return { text: 표시, urgent: false, over: false };
  /* 날수는 **날짜끼리** 셉니다 (오늘 0시 ↔ 마감일 0시).
     지금 시각에서 재면 같은 날 낮에도 하루가 남은 것으로 올라갑니다 —
     목록의 옛 dday() 가 그렇게 세서, 마감 당일에 「D-1」, 내일 마감에
     「D-2」 를 찍고 있었습니다. 상세 쪽 셈이 맞았으므로 그것을 가져옵니다 */
  const left = Math.ceil(
    (new Date(to + 'T23:59:59+09:00').getTime()
     - new Date(todayKst(now) + 'T00:00:00+09:00').getTime()) / 86400000,
  ) - 1;
  if (left <= 0) {
    const t = 시각말(시각);
    return { text: t ? `오늘 ${t} 마감` : '오늘 마감', urgent: true, over: false };
  }
  return { text: 'D-' + left, urgent: left <= 3, over: false };
}

/* 「09:00:00」 → 「오전 9시」 · 「17:30:00」 → 「오후 5시 30분」 · 「23:59:59」 → 「밤 12시」 */
export function 시각말(t: string | null | undefined): string | null {
  if (!t) return null;
  const m = /^(\d{1,2}):(\d{2})/.exec(t);
  if (!m) return null;
  const h = Number(m[1]), mi = Number(m[2]);
  if (h >= 23 && mi >= 59) return '밤 12시';
  const 낮밤 = h < 12 ? '오전' : '오후';
  const h12 = h % 12 === 0 ? 12 : h % 12;
  return 낮밤 + ' ' + h12 + '시' + (mi ? ' ' + mi + '분' : '');
}

/* ★ 2026-10-14 세중님 확정 — 「예상 연봉」 표시를 한 자리에서 정합니다.

     공고에 금액이 있으면          공고의 금액 그대로 (지금처럼)
     금액이 없으면                 「내규에 따름」
                                   — 빈칸 · 「내규에 따름」 · 「보수규정에 따름」 ·
                                     「협의」 같은 글귀만 있는 것 전부

   **칸을 숨기지 않습니다.** 전에는 비면 칸을 아예 안 그려서, 회원이
   「우리가 못 받아온 것」인지 「공고에 없는 것」인지 알 수 없었습니다.
   **숫자를 만들지 않습니다** (작업지침 15절).
   「미공시」라는 말은 쓰지 않습니다 — 2026-10-14 에 그 결정을 바꿨습니다.

   금액을 가리는 자리는 여기 하나입니다. DB 쪽 짝은 네숫자() 의 ③ 예상연봉이고
   같은 꼴을 씁니다 — `[0-9][0-9,.[:space:]]*(만|천|억)?[[:space:]]*원` */
/* ★ 2026-10-22 — 「40백만원」 꼴을 더했습니다 (= 4,000만원). 공고문이 그렇게 적습니다
   (경기도의료원 수원병원 「年 40백만원 내외」). 짝은 tools/공고문읽기.mjs 의
   `금액꼴` 이고 **함께** 고쳤습니다 (지침 6절) */
const 금액꼴 = /[0-9][0-9,.\s]*(백만|십만|만|천|억)?\s*원/;

/* 금액이 적혀 있나 — 숫자 뒤에 「원」이 붙은 것만 금액으로 봅니다.
   「2년」 「9급」 「2026. 11월」 은 금액이 아닙니다 (공고문을 읽어 담은 값에
   보수 안내 문단이 통째로 들어온 것이 있습니다) */
export function 금액있나(연봉: string | null | undefined): boolean {
  return !!연봉 && 금액꼴.test(연봉);
}

export const 내규말 = '내규에 따름';
/* ★ 2026-11-19 세중님 「급여는 공고문 확인 가자」 — 금액도 「내규에 따름」 같은 말도 **원문에 없으면** 「공고문 확인」.
   전에는 빈칸까지 「내규에 따름」 으로 적었는데, 공고에 없는 말을 우리가 지어 붙인 셈이었습니다(외부 검토 지적) */
export const 보수확인말 = '공고문 확인';

/* ★ 2026-11-19 세중님 「오픈 뒤에 한다는 거 바로 하자」(외부 검토: 필수와 우대가 한 덩어리 「필수 자격」 으로 보이면
   우대 조건이 없는 신입이 지원을 포기할 수 있음) — 담긴 자격 글을 **필수 / 우대**로 가릅니다(화면만 · DB 원문은 그대로).
   가르는 자리: 「우대사항·우대조건·우대자격·우대 :」 표식(그 뒤는 우대) · 「필수사항·필수 :」 표식(그 뒤는 필수) ·
   「… 우대」 로 끝나는 토막(그 토막만 우대). 표식 글자는 떼고, 원문 낱말은 바꾸지 않습니다 */
export function 자격나누기(글: string | null | undefined): { 필수: string | null; 우대: string | null } {
  const 원 = String(글 || '').trim();
  if (!원) return { 필수: null, 우대: null };
  /* 표식 — 「우대사항」「[우대]」「(우대)」「우대 :」「필수 -」 … (괄호 안 「운전면허증(필수)」 처럼 앞에 빈칸 없이 붙은 것은 표식이 아님) */
  const 앞자르기 = /\s(?=[[(（]?(?:우대|필수|공통)\s*(?:사항|조건|자격|요건)?[\])）]?\s*[:：-]\s|[[(（](?:우대|필수)[\])）]|(?:우대|필수)\s*(?:사항|조건|자격|요건)(?:\s|$))/;
  /* ★ 2026-11-20 (Codex 검토 넷 + 운영에서 찾은 하나) —
     ① 표식을 **확인하는 꼴과 떼는 꼴이 같아야** 합니다. 전에는 확인은 「필수 」 로 통과하고 떼기는 「필수 자격」 까지 떼서
        「필수 자격증 소지자」 가 「증 소지자」 가 됐습니다. 이제 한 정규식이 확인도 하고 떼기도 합니다(끝에 경계가 있어야 표식)
     ② 표식은 **괄호 밖**에서만 — 「…(관련 경력 (우대) 1년 이상)」 을 괄호 가운데에서 자르지 않습니다
     ③ 「면허 필수, 경력자 우대」 — 끝이 우대라도 **필수라는 말이 같이 있으면** 통째로 우대 칸에 넣지 않습니다
     ④ 줄 머리 기호(○ ● • …)는 뗍니다 — 운영 공고 넷에서 「○ · 물리치료사 면허증 소지자」 로 보였습니다 */
  const 괄호표식 = /^[[(（](우대|필수|공통)\s*(?:사항|조건|자격|요건)?[\])）]\s*[:：-]?\s*/;
  const 맨표식 = /^(우대|필수|공통)\s*(?:사항|조건|자격|요건)?(?:\s*[:：-]\s*|\s+|$)/;
  const 머리기호 = /^[\s:：·\-–—○●◦•▪■□◆◇▶▷]+/;
  const 토막: string[] = [];
  /* 「 · 」·줄바꿈도 괄호 밖에서만 — 괄호 안 설명이 여러 줄이면 그 안의 「(우대)」 가 표식으로 읽혔습니다 (Codex 검토) */
  for (const t of 괄호밖자르기(원, /\s+·\s+|\n+/)) for (const u of 괄호밖자르기(t, 앞자르기)) if (u.trim()) 토막.push(u.trim());
  const 필수: string[] = []; const 우대: string[] = [];
  let 지금: '필수' | '우대' = '필수';
  for (let t of 토막) {
    t = t.replace(머리기호, '');
    /* 「필수사항」 처럼 표식 낱말이 있어야 표식입니다 — 「필수적으로 …」 같은 말은 아님 */
    const m = 괄호표식.exec(t) ?? 맨표식.exec(t);
    if (m) {
      /* 「우대 없음」·「우대사항: 해당 없음」 — 조건이 없다는 말입니다. 칸에 「없음」 을 적지 않고, 뒤 토막을 우대로 돌리지도 않습니다
         (Codex 검토 — 「○ 우대 없음」 뒤의 「○ 면허 소지자」 가 우대 칸으로 갔습니다) */
      if (/^(?:해당\s*(?:사항)?\s*)?(?:없음|없습니다|없슴|무관)\.?$/.test(t.slice(m[0].length).replace(머리기호, '').trim())) continue;
      지금 = m[1] === '우대' ? '우대' : '필수';
      t = t.slice(m[0].length);
    }
    t = t.replace(머리기호, '').trim();
    if (!t) continue;
    /* 「소아 작업치료 경력 우대」 처럼 **끝이 우대**인 토막만 그 토막을 우대로 — 「…(기타: … 우대)」 처럼 괄호 안은 아님 */
    if (지금 === '필수' && /우대\.?$/.test(t)) {
      const 갈림 = 필수우대갈림(t);
      if (갈림 === '우대') 우대.push(t);
      else if (갈림 === '모름') 필수.push(t);          /* 가를 자리가 또렷하지 않으면 원문 그대로 필수 칸에 — 필수가 선택처럼 보이면 안 됩니다 */
      else { 필수.push(갈림.필수); 우대.push(갈림.우대); }
      continue;
    }
    (지금 === '우대' ? 우대 : 필수).push(t);
  }
  return { 필수: 필수.length ? 필수.join(' · ') : null, 우대: 우대.length ? 우대.join(' · ') : null };
}

/* 글자마다 「그 글자 앞까지 열린 괄호 수」 — 닫는 괄호만 있는 「1)」 같은 꼴은 0 아래로 내려가지 않습니다 */
function 괄호깊이(t: string): number[] {
  const 깊이: number[] = []; let d = 0;
  for (let i = 0; i < t.length; i++) {
    깊이.push(d);
    if ('([（'.includes(t[i])) d++;
    else if (')]）'.includes(t[i])) d = Math.max(0, d - 1);
  }
  깊이.push(d);      /* 맨 끝 칸 = 다 읽고 난 뒤 열려 있는 괄호 수 (0 이면 짝이 맞음) */
  return 깊이;
}
/* 자를자리에 맞는 곳 가운데 **괄호 밖**인 곳에서만 자릅니다.
   괄호 짝이 안 맞는 글(여는 괄호만 있고 안 닫힘)은 깊이를 믿을 수 없으니 전처럼 맞는 곳마다 자릅니다 */
function 괄호밖자르기(t: string, 자를자리: RegExp): string[] {
  const 깊이 = 괄호깊이(t);
  const 짝맞음 = 깊이[t.length] === 0;
  const out: string[] = []; let 앞 = 0;
  for (const m of t.matchAll(new RegExp(자를자리.source, 'g'))) {
    if (짝맞음 && 깊이[m.index] !== 0) continue;
    out.push(t.slice(앞, m.index));
    앞 = m.index + m[0].length;
  }
  out.push(t.slice(앞));
  return out;
}
/* 끝이 「우대」 인 토막에 「필수」 조건이 같이 있을 때 — **쉼표 마디마다** 가릅니다 (Codex 검토 2026-11-20).
   「작업치료사 면허 필수, 경력자 우대, 운전면허 필수, 소아 경력자 우대」 → 필수 마디는 필수로, 우대 마디는 우대로.
   표식 없는 마디(「초대졸 이상, 면허 필수」 의 앞 마디)는 **뒤따르는 표식**을 따릅니다.
   한 마디 안에 둘이 섞였으면(「면허 필수 경력자 우대」) 가르지 않고 '모름' — 부르는 쪽이 원문 그대로 필수 칸에 둡니다.
   ★ 「필수」 글자가 있다고 다 필수 조건은 아닙니다 — 「필수과목 이수자 우대」·「필수는 아니나 …」·「경력 필수 아님」 은 필수로 안 칩니다 */
function 필수우대갈림(t: string): '우대' | '모름' | { 필수: string; 우대: string } {
  const 깊이 = 괄호깊이(t);
  const 마디: string[] = []; let 앞 = 0;
  for (let i = 0; i < t.length; i++) {
    if (깊이[i] === 0 && ',，、;'.includes(t[i])) { 마디.push(t.slice(앞, i).trim()); 앞 = i + 1; }
  }
  마디.push(t.slice(앞).trim());
  const 갈래 = 마디.map(마디갈래);
  if (갈래.includes('섞임')) return '모름';
  if (!갈래.includes('필수')) return '우대';
  const 필수: string[] = []; const 우대: string[] = []; let 밀린: string[] = [];
  마디.forEach((글, i) => {
    if (!글) return;
    if (갈래[i] === '없음') { 밀린.push(글); return; }
    (갈래[i] === '필수' ? 필수 : 우대).push(...밀린, 글); 밀린 = [];
  });
  if (밀린.length || !필수.length || !우대.length) return '모름';
  return { 필수: 필수.join(', '), 우대: 우대.join(', ') };
}
/* 쉼표 마디 하나의 갈래 — 끝이 「필수」(·필수이며·필수임)면 필수 · 끝이 「우대」 면 우대 ·
   우대로 끝나는데 「면허 필수 …」 처럼 면허·자격·경력 말 바로 뒤에 필수가 있으면 섞임 · 그 밖은 없음 */
function 마디갈래(s: string): '필수' | '우대' | '섞임' | '없음' {
  const 깊이 = 괄호깊이(s);
  /* 「불필수」·「비필수」 는 필수가 아니라는 말입니다 (Codex 검토) */
  const 끝필수 = /(?<![불비])필수(?:이며|이고|임|입니다|이나|이지만)?\.?$/.exec(s);
  if (끝필수 && 깊이[끝필수.index] === 0) return '필수';
  if (!/우대\.?$/.test(s)) return '없음';
  for (const m of s.matchAll(/(?<![불비])필수/g)) {
    if (깊이[m.index] !== 0) continue;
    const 앞말 = s.slice(0, m.index); const 뒷말 = s.slice(m.index + 2);
    if (/^\s*(?:은|는|이|가)?\s*(?:아님|아니|아닌|없)/.test(뒷말)) continue;      /* 「필수 아님」「필수는 아니나」 */
    if (/^\s*(?:과목|교과|교육|과정|학점|이수)/.test(뒷말)) continue;               /* 「자격 필수 과목 이수자 우대」 — 필수가 과목을 꾸미는 말 */
    if (/^\s/.test(뒷말) && /(?:면허|자격|증|소지|경력)\s*$/.test(앞말)) return '섞임';
  }
  return '우대';
}
