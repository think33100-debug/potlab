/* 공고가 마감됐는지 한 곳에서 판단합니다 (node lib/job-state.test.mjs).

   마감일이 비어 있으면 마감으로 안 칩니다.
   인수인계 원칙이 「마감일이 비어 있으면 잘못 읽은 것」입니다 —
   자료를 못 받아온 것뿐인데 멀쩡한 공고를 막으면 안 됩니다.

   날짜는 한국 시간 기준입니다. UTC 로 재면 한국에서 자정 넘긴 뒤 아홉 시간 동안
   어제 날짜로 판단합니다. 마감일 당일은 아직 열린 것으로 봅니다. */

/* 한국은 1988년 뒤로 서머타임이 없습니다. 그래서 +9시간이 언제나 정확합니다.
   Intl 로 시간대를 다루지 않는 이유 — 미리보기 그림을 그리는 edge 런타임은
   ICU 가 잘려 있는 곳이 있어 timeZone 을 못 믿습니다 */
export const KST_OFFSET_MIN = 9 * 60;

/* 오늘 (한국) — 'YYYY-MM-DD' */
export function todayKst(now: Date = new Date()): string {
  return new Date(now.getTime() + KST_OFFSET_MIN * 60_000).toISOString().slice(0, 10);
}

/* 지금 (한국) — 'HH:MM:SS' */
export function nowTimeKst(now: Date = new Date()): string {
  return new Date(now.getTime() + KST_OFFSET_MIN * 60_000).toISOString().slice(11, 19);
}

/* ★ 2026-10-08 — 마감 **시각**까지 봅니다.
   DB 의 마감지났나(apply_to, apply_to_time) 와 **글자 하나 다르지 않게** 유지하십시오.
   한쪽만 고치면 화면과 목록이 어긋납니다.

     마감일이 없으면            마감 아님
     마감일 < 오늘              마감
     마감일 > 오늘              마감 아님
     마감일 = 오늘 · 시각 없음    마감 아님 (그날 종일)
     마감일 = 오늘 · 시각 있음    지금 시각 > 그 시각 이면 마감

   왜 — 중앙보훈병원은 10.16(금) **09:00** 마감인데, 전에는 그날 저녁에도
   「오늘 마감 · D-0」 으로 떠 있었습니다. 회원이 저녁에 보고 들어가면 닫혀 있습니다 */
export function isClosed(
  applyTo: string | null | undefined,
  today = todayKst(),
  applyToTime?: string | null,
  nowTime = nowTimeKst(),
): boolean {
  if (!applyTo) return false;
  const d = applyTo.slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) return false;
  if (d < today) return true;
  if (d > today) return false;
  if (!applyToTime) return false;            // 그날 종일
  return nowTime > applyToTime.slice(0, 8);
}

/* 마감 배지에 쓸 말과 색 (2026-10-09).

   ★ 전에는 같은 이름의 dday() 가 **목록과 상세에 따로** 있었습니다.
     2026-10-08 에 마감 시각을 넣으면서 목록만 고쳐서, 시각이 지난 그날
     상세에는 빨간 「오늘 마감」 이 그대로 남았습니다 (근로복지공단안산병원
     17:30 마감 공고로 확인). 그래서 한 벌로 모읍니다 —
     **마감 배지를 그리는 곳은 이 함수만 부릅니다.**

     마감일 없음        마감표시() 가 정한 말 (「마감일 공고문 확인」 등) · 회색
     마감 (시각 포함)    「마감」 · 회색 · over
     오늘 마감          「오늘 마감」 또는 「오늘 오후 5시 30분 마감」 · 빨강
     그 밖              「D-n」 · 사흘 이하면 빨강

   urgent 는 빨강으로 칠할지, over 는 흐리게 둘지입니다. 둘은 같이 못 켜집니다. */
export type 마감배지모양 = { text: string; urgent: boolean; over: boolean };

export function 마감배지(
  to: string | null | undefined,
  표시?: string | null,
  시각?: string | null,
  now: Date = new Date(),
): 마감배지모양 {
  if (!to) {
    return { text: 표시 || '마감일 공고문 확인', urgent: false, over: false };
  }
  if (isClosed(to, todayKst(now), 시각, nowTimeKst(now))) {
    return { text: '마감', urgent: false, over: true };
  }
  /* ★ 2026-10-22 세중님 2번 — 포털 **상세** 칸에 기관이 적은 말이 있으면
     (「채용시까지」) 날수 대신 그 말을 씁니다. 마감표시() 가 날짜가 있어도 그 말을
     내도록 바뀌었습니다 (supabase/migrations/2026_10_22_마감표시_접수마감글.sql).
     ⚠ 날수(D-n)가 그 공고에서는 안 보입니다 — 그 날짜는 **게시 만료일**이고
       기관이 사람을 뽑으면 그날 닫습니다. 「D-12」는 없는 여유를 알려 주는 말입니다.
       숨김·정렬은 그대로 apply_to 를 봅니다 */
  if (표시) return { text: 표시, urgent: false, over: false };
  /* 날수는 **날짜끼리** 셉니다 (오늘 0시 ↔ 마감일 0시).
     지금 시각에서 재면 같은 날 낮에도 하루가 남은 것으로 올라갑니다 —
     목록의 옛 dday() 가 그렇게 세서, 마감 당일에 「D-1」, 내일 마감에
     「D-2」 를 찍고 있었습니다. 상세 쪽 셈이 맞았으므로 그것을 가져옵니다 */
  const left = Math.ceil(
    (new Date(to + 'T23:59:59+09:00').getTime()
     - new Date(todayKst(now) + 'T00:00:00+09:00').getTime()) / 86400000,
  ) - 1;
  if (left <= 0) {
    const t = 시각말(시각);
    return { text: t ? `오늘 ${t} 마감` : '오늘 마감', urgent: true, over: false };
  }
  return { text: 'D-' + left, urgent: left <= 3, over: false };
}

/* 「09:00:00」 → 「오전 9시」 · 「17:30:00」 → 「오후 5시 30분」 · 「23:59:59」 → 「밤 12시」 */
export function 시각말(t: string | null | undefined): string | null {
  if (!t) return null;
  const m = /^(\d{1,2}):(\d{2})/.exec(t);
  if (!m) return null;
  const h = Number(m[1]), mi = Number(m[2]);
  if (h >= 23 && mi >= 59) return '밤 12시';
  const 낮밤 = h < 12 ? '오전' : '오후';
  const h12 = h % 12 === 0 ? 12 : h % 12;
  return 낮밤 + ' ' + h12 + '시' + (mi ? ' ' + mi + '분' : '');
}

/* ★ 2026-10-14 세중님 확정 — 「예상 연봉」 표시를 한 자리에서 정합니다.

     공고에 금액이 있으면          공고의 금액 그대로 (지금처럼)
     금액이 없으면                 「내규에 따름」
                                   — 빈칸 · 「내규에 따름」 · 「보수규정에 따름」 ·
                                     「협의」 같은 글귀만 있는 것 전부

   **칸을 숨기지 않습니다.** 전에는 비면 칸을 아예 안 그려서, 회원이
   「우리가 못 받아온 것」인지 「공고에 없는 것」인지 알 수 없었습니다.
   **숫자를 만들지 않습니다** (작업지침 15절).
   「미공시」라는 말은 쓰지 않습니다 — 2026-10-14 에 그 결정을 바꿨습니다.

   금액을 가리는 자리는 여기 하나입니다. DB 쪽 짝은 네숫자() 의 ③ 예상연봉이고
   같은 꼴을 씁니다 — `[0-9][0-9,.[:space:]]*(만|천|억)?[[:space:]]*원` */
/* ★ 2026-10-22 — 「40백만원」 꼴을 더했습니다 (= 4,000만원). 공고문이 그렇게 적습니다
   (경기도의료원 수원병원 「年 40백만원 내외」). 짝은 tools/공고문읽기.mjs 의
   `금액꼴` 이고 **함께** 고쳤습니다 (지침 6절) */
const 금액꼴 = /[0-9][0-9,.\s]*(백만|십만|만|천|억)?\s*원/;

/* 금액이 적혀 있나 — 숫자 뒤에 「원」이 붙은 것만 금액으로 봅니다.
   「2년」 「9급」 「2026. 11월」 은 금액이 아닙니다 (공고문을 읽어 담은 값에
   보수 안내 문단이 통째로 들어온 것이 있습니다) */
export function 금액있나(연봉: string | null | undefined): boolean {
  return !!연봉 && 금액꼴.test(연봉);
}

export const 내규말 = '내규에 따름';

/* ★ 2026-10-28 세중님 1번 — **연봉 표기를 「0,000만원」으로 통일합니다.**
 *
 *   「23000000이상~」   → 「2,300만원 이상」
 *   「54,678천원」      → 「약 5,468만원」     (천원 단위는 반올림 + 「약」)
 *   「2300만원~2600만원」 → 「2,300~2,600만원」
 *   「시급 12,626원」    → 그대로 (시급·일급은 단위를 살립니다)
 *   「월 2,300,000원」   → 「월 230만원」
 *
 * ★ **숫자를 바꾸는 것이 아니라 보여주는 꼴만 바꿉니다.** `뽑은값` 원문은 그대로
 *   두고 이 한 자리에서만 고칩니다 (지침 6절 — 기준은 한 자리).
 * ★ **못 읽으면 null** 을 돌려주고, 화면은 **원문을 그대로** 그립니다. 반올림으로
 *   거짓을 만들지 않습니다 — 문단이 통째로 들어온 줄·단위를 모르는 줄이 그렇습니다
 *   (`tools/화면표시_점검.mjs` 가 그 줄들을 목록으로 냅니다).
 */
const 단위배수: Record<string, number> = {
  억: 100000000, 백만: 1000000, 십만: 100000, 만: 10000, 천: 1000, '': 1,
};
/** 숫자 + 단위 + 「원」 한 덩이. 단위나 「원」이 있으면 **돈이라고 적힌 것**입니다 */
const 돈토막 = /([0-9][0-9,]*(?:\.[0-9]+)?)\s*(억|백만|십만|만|천)?\s*(원)?/g;
/** 뒤에 붙는 말 — 원문에 있는 것만 살립니다 (지어내지 않습니다) */
const 꼬리말 = /(이상|이하|내외|부터|이내|정도|선)/g;
/** 세전·세후는 **금액의 뜻을 바꾸는 말**이라 함께 적습니다 */
const 세전후 = /(세전|세후)/;
/* ★ 금액 뒤에 붙는 **딴 이야기**를 떼어 냅니다 (2026-10-28).
   워크넷 값은 「월급2,400,000원 이상 ~ 2,400,000원 이하**, 면접 후 재조정 가능**」·
   「**, 상여금 : 10(미 포함)**」 꼴이 흔합니다 (회원 화면 57건). 그 글자를 그대로 두면
   금액 덩이가 셋이 넘어 못 읽습니다. **숫자가 아닌 글이 뒤따르는 쉼표**에서 자릅니다 —
   「2,400,000」 처럼 숫자 사이 쉼표는 자르지 않습니다.
   ⚠ 떼어 낸 말(상여금 비율·면접 후 재조정)은 **화면에서 사라집니다.** 금액 칸에
   섞여 있던 딴 값이고, 자세한 것은 원문 공고에 있습니다 */
function 금액머리(t: string): string {
  return t.split(/,\s*(?=[^\d\s])/)[0].trim();
}
/** 단위도 「원」도 없는 맨 숫자는 **백만 이상**일 때만 돈으로 봅니다 —
 *  「2026. 11월」·「2년」·「9급」·호봉을 돈으로 읽지 않으려는 울타리입니다 (지침 10-5) */
export const 맨숫자최소 = 1000000;

export function 쉼표(n: number): string {
  return Math.round(n).toLocaleString('en-US');
}

/** 한 금액을 「0,000만원」 꼴로. `약`은 만원 아래가 떨어질 때만 붙습니다 */
function 만원말(값: number): { 글: string; 약: boolean } {
  if (값 < 10000) return { 글: 쉼표(값) + '원', 약: false };
  const 만 = 값 / 10000;
  return { 글: 쉼표(만) + '만원', 약: Math.abs(만 - Math.round(만)) > 0.0001 };
}

export type 돈꼴값 = { 글: string; 갈래: '연' | '시급' | '일급' | '주급' | '월' };

export function 돈꼴(원문: string | null | undefined): 돈꼴값 | null {
  const 온글 = String(원문 || '').replace(/\s+/g, ' ').trim();
  if (!온글) return null;
  const t = 금액머리(온글);
  if (!t) return null;
  /* 문단이 통째로 들어온 줄은 손대지 않습니다 — 원문을 그대로 그립니다 */
  if (t.length > 40 || /[。\n]/.test(t)) return null;

  const 갈래: 돈꼴값['갈래'] = /시급|시간급/.test(t) ? '시급'
    : /일급/.test(t) ? '일급'
    : /주급/.test(t) ? '주급'
    /* 「급여 **월 3,152,600원**」 처럼 **월 뒤에 바로 숫자**가 오면 달마다 주는 돈입니다 */
    : /월\s*(급|지급|액|평균|기본|약)|월\s*[0-9]|^월/.test(t) ? '월' : '연';

  돈토막.lastIndex = 0;
  const 값들: number[] = [];
  let m: RegExpExecArray | null;
  while ((m = 돈토막.exec(t))) {
    if (!m[1]) continue;
    const 수 = Number(m[1].replace(/,/g, ''));
    if (!Number.isFinite(수) || 수 === 0) continue;
    const 적혔나 = !!(m[2] || m[3]);              /* 단위말이나 「원」이 붙었나 */
    if (!적혔나 && 수 < 맨숫자최소) continue;
    값들.push(수 * 단위배수[m[2] || '']);
  }
  if (!값들.length) return null;
  if (값들.length > 2) return null;                /* 세 덩이 넘으면 문단입니다 */

  /* 꼬리말이 둘이면(「이상 ~ 이하」) 범위가 이미 그 말을 하므로 안 붙입니다 */
  const 꼬리들 = t.match(꼬리말) || [];
  const 세 = (t.match(세전후) || [])[1] || '';
  const 꼬리 = [꼬리들.length === 1 ? 꼬리들[0] : '', 세].filter(Boolean).join(' ');
  /* ★ 「기본급」은 **그대로 살립니다** (2026-10-28) — 떼면 「기본급 2,266,000원」이
     「약 227만원」이 되어 **연봉 227만원**으로 읽힙니다. 원문의 뜻을 지웁니다 */
  const 라벨 = (t.match(/기본급/) || [])[0] || '';
  const 앞말 = 갈래 === '월' ? '월 ' : 갈래 !== '연' ? 갈래 + ' ' : 라벨 ? 라벨 + ' ' : '';
  /* ★ 울타리 — 연봉 칸인데 **1,000만원 미만**이고 무슨 돈인지 적혀 있지 않으면
     손대지 않습니다. 월급인지 연봉인지 **우리가 모르는 것**이고, 「약 227만원」으로
     적으면 회원이 연봉으로 읽습니다 (지침 10-3 — 짐작하지 않습니다) */
  if (갈래 === '연' && !라벨 && Math.max(...값들) < 10000000) return null;

  /* 시급·일급·주급은 **원 단위를 살립니다** (12,626원) */
  if (갈래 === '시급' || 갈래 === '일급' || 갈래 === '주급') {
    const 글 = 값들.map((v) => 쉼표(v) + '원').join('~');
    return { 글: (앞말 + 글 + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
  }

  if (값들.length === 2 && 값들[0] !== 값들[1]) {
    const a = 만원말(값들[0]);
    const b = 만원말(값들[1]);
    /* 둘 다 만원 꼴일 때만 뒤에 한 번 붙입니다 */
    if (a.글.endsWith('만원') && b.글.endsWith('만원')) {
      const 약 = a.약 || b.약 ? '약 ' : '';
      return { 글: (앞말 + 약 + a.글.replace('만원', '') + '~' + b.글
        + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
    }
    return { 글: (앞말 + a.글 + '~' + b.글 + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
  }

  const one = 만원말(값들[0]);
  return { 글: (앞말 + (one.약 ? '약 ' : '') + one.글 + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
}

/* 화면에 찍을 말. 언제나 글자를 돌려줍니다 — 칸을 숨기지 않습니다.
   ★ 2026-10-28 — 꼴을 통일합니다. 못 읽은 줄은 **원문 그대로** 그립니다 */
export function 연봉말(연봉: string | null | undefined): string {
  const d = 돈꼴(연봉);
  if (d) return d.글;
  /* 돈꼴이 못 읽은 줄 — 「원」이 적혀 있으면 **원문 그대로**, 아니면 내규에 따름.
     `금액있나` 는 DB 네숫자() 의 ③ 과 **같은 꼴**이라 고치지 않습니다 (지침 6절) */
  return 금액있나(연봉) ? String(연봉).trim() : 내규말;
}

/* ★ 2026-10-28 세중님 3번 — **기관 이름에서 법인 표기를 뗍니다** (화면 표시만).
 *
 *   「의료법인 인당의료재단 부민병원」 → 「인당의료재단 부민병원」
 *   「주식회사 더 행복」              → 「더 행복」
 *   「(주)강원랜드」                 → 「강원랜드」
 *
 * ★ **매칭 열쇠·DB 원문은 그대로입니다.** 이름으로 기관을 잇는 일은 `hira_name_key`
 *   가 하고, 여기는 **보여줄 글자만** 다듬습니다 (지침 10-3 · 6절).
 * ★ 떼고 나서 **두 글자 이하**가 되면 원문을 그대로 씁니다 — 「(주)이지」 처럼
 *   법인 표기를 떼면 이름이 사라지는 곳이 있습니다.
 */
/* ★ 「의료재단」·「복지재단」·「협동조합」은 **떼지 않습니다** — 이름의 일부입니다.
   심평원 공식 이름이 「의료법인 인당의료재단 부민병원」이고, 떼면 「인당 부민병원」이
   되어 **없는 이름**이 됩니다. 세중님이 적어 주신 목록(법인 표기)만 뗍니다 */
const 법인말 = /(\(\s*주\s*\)|\(\s*유\s*\)|\(\s*의\s*\)|\(\s*재\s*\)|\(\s*사\s*\)|주식회사|유한회사|유한책임회사|합자회사|의료법인|사회복지법인|사단법인|재단법인|학교법인|특수법인|영농조합법인)/g;

/* ★ 2026-10-28 세중님 C — **한자·기호도 뗍니다.**
   「삼성(杉晟)센텀정형외과의원」 → 「삼성센텀정형외과의원」 ·
   「계양효(孝)요양원」 → 「계양효요양원」 (그래야 산하 이름과 두 번 안 적힙니다).
   `㈜`·`㈑` 같은 한 글자 꼴도 법인 표기입니다 */
const 한자괄호 = /[(（]\s*[㐀-䶿一-鿿]+\s*[)）]/g;
const 한자 = /[㐀-䶿一-鿿]/g;
const 기호 = /[★※【】◇◆□■○●▲▼〔〕\[\]]/g;
const 한글자법인 = /[㈜㈐㈑㈒㈓㈔]/g;

export function 기관이름말(이름: string | null | undefined): string {
  const 원 = String(이름 || '').trim();
  if (!원) return '';
  const 떼 = 원
    .replace(한자괄호, '')           /* 괄호 속 한자부터 — **빈 글자로** 뗍니다.
                                        공백을 넣으면 「삼성 센텀정형외과의원」이 됩니다 */
    .replace(한글자법인, ' ')
    .replace(법인말, ' ')
    .replace(한자, '')               /* 괄호 없이 섞인 한자 */
    .replace(기호, ' ')
    .replace(/\s+/g, ' ')
    .replace(/^[·,\-\s]+|[·,\-\s]+$/g, '')
    .trim();
  return 떼.length > 2 ? 떼 : 원;
}

/* ★ 2026-10-28 세중님 A — **기관 이름은 근무처 이름**입니다 (법인 이름이 아닙니다).
 *
 *   기관 「주식회사 분당시니어」 · 원문 제목 「[행복한요양원 분당점]-물리치료사 추가 채용」
 *     → 보여 줄 이름 「행복한요양원 분당점」
 *
 * 워크넷 상세에는 **근무처·사업장명 칸이 없습니다** (담긴 열쇠 열여덜 개를 전부 셌습니다 ·
 * docs/표시규칙_1028.md A-1). 그래서 **원문 제목 앞머리 `[…]`** 에서 꺼냅니다 —
 * 그 자리에 근무처 이름을 적는 공고가 회원 화면에 여덜 건 있습니다.
 *
 * ★ **근무처 꼴일 때만** 씁니다 — 점·센터·병원·요양원·의원·주간보호·어린이집 꼴.
 *   지역(`[구포]`)·부서(`[건진팀]`)·법인(`[안동의료재단]`)·조건(`[주4.5일]`)·
 *   직군(`[물리치료사]`)은 **안 씁니다** (지침 10-3 — 짐작하지 않습니다).
 * ★ 법인명과 **같은 말이면** 안 씁니다 (두 번 적힙니다).
 */
/* 「본점3관」·「○○회관」 처럼 **관**으로 끝나는 지점 이름도 근무처입니다 */
const 근무처꼴 = /(점|센터|병원|의원|요양원|요양병원|한의원|치과|주간보호|어린이집|보건소|지점|분원|관)$/;
const 안쓸앞머리 = /^(온라인|물리치료사|작업치료사|신규|경력|모집|채용|재공고|긴급|마감)$/;

export function 근무처이름(원문제목: string | null | undefined,
  기관이름: string | null | undefined): string | null {
  const m = String(원문제목 || '').match(/^\s*[\[【〔]\s*([^\]】〕]{2,24})\s*[\]】〕]/);
  if (!m) return null;
  const 토막 = m[1].replace(/\s+/g, ' ').trim();
  if (!토막 || 안쓸앞머리.test(토막)) return null;
  /* 마지막 낱말이 근무처 꼴이어야 합니다 — 「행복한요양원 분당점」·「우림요양원」 */
  const 끝낱말 = 토막.split(' ').slice(-1)[0];
  if (!근무처꼴.test(끝낱말)) return null;
  /* 법인명에 이미 들어 있으면 안 씁니다 */
  const 기관 = 기관이름말(기관이름);
  const 글자만한 = (s: string) => s.replace(/[\s()（）]/g, '');
  if (글자만한(기관).includes(글자만한(토막))) return null;
  return 토막;
}

/** 화면에 적을 기관 이름 — **근무처 이름이 있으면 그것**, 없으면 법인 표기 뗀 이름 */
export function 보여줄기관이름(기관이름: string | null | undefined,
  원문제목?: string | null): string {
  return 근무처이름(원문제목, 기관이름) || 기관이름말(기관이름);
}

/* ★ 2026-10-28 세중님 2번 — 「지원하러 가기」가 **그 공고로** 가게 합니다.
 *
 *   ① 원문 공고 주소 (워크넷 dtlRecrContUrl · 알리오·나라일터 상세 · 긁기 원문)
 *   ② 없으면 접수방법의 **자사채용사이트(URL)**
 *   ③ 없으면 기관 홈페이지
 *   ④ 그것도 없으면 **단추를 숨기고** 「접수방법: ○○ · 공고문 확인」
 *
 * 비회원에게는 창구가 `url` 을 안 줍니다 — 그때는 ①이 비어 ②③으로 내려가지 않고
 * 「로그인하고 지원하러 가기」가 그대로 떠야 합니다. 그래서 **회원인지**를 함께 받습니다.
 */
export type 지원링크꼴 = { 주소: string | null; 갈래: '채용게시판' | '기관홈' | '원문' | '없음' };

/* ★ 2026-10-28 세중님 E — **차례를 바꿉니다.**
 *   ① 기관 **채용 게시판** (열어서 확인된 것 · `detail.채용게시판`)
 *   ② 기관 **홈페이지** (`detail.기관홈`·`기관홈페이지` · 기관 표)
 *   ③ **원문** (알리오·고용24·긁기 — `job_posts.url`)
 *   「원문 보기」 작은 줄은 **항상** 그립니다 (화면 쪽에서).
 *
 * ★ 지금 ①은 공고에 담긴 데가 **없습니다** — 채용게시판찾기 가 찾은 181곳은
 *   **사이트표**에만 있고 공고 `detail` 로 안 옵니다. ②도 기관 표 홈페이지 칸이
 *   비어 있습니다. 그래서 **차례만 세워 둡니다** — 주소가 이어지는 대로 앞섭니다
 *   (주소를 잇는 것은 창구·수집기 자리라 동결 뒤입니다 · docs/표시규칙_1028.md E).
 */
export function 지원링크(
  공고주소: string | null | undefined,
  접수방법: string | null | undefined,
  기관홈: string | null | undefined,
  채용게시판?: string | null,
): 지원링크꼴 {
  const 주소꼴 = (v: string | null | undefined) => {
    const s = String(v || '').trim();
    return /^https?:\/\//.test(s) ? s : null;
  };
  const 게시판 = 주소꼴(채용게시판) || 자사채용주소(접수방법);
  if (게시판) return { 주소: 게시판, 갈래: '채용게시판' };
  const h = 주소꼴(기관홈);
  if (h) return { 주소: h, 갈래: '기관홈' };
  const u = 주소꼴(공고주소);
  if (u) return { 주소: u, 갈래: '원문' };
  return { 주소: null, 갈래: '없음' };
}

/** 접수방법 글에서 `자사채용사이트(…)` 의 주소만 집습니다 */
export function 자사채용주소(접수방법: string | null | undefined): string | null {
  const t = String(접수방법 || '');
  const m = t.match(/자사채용사이트\s*[(（]\s*([^)）]+)\s*[)）]/);
  if (!m) return null;
  const 주소 = m[1].trim();
  return /^https?:\/\//.test(주소) ? 주소 : null;
}

/* ★ 2026-10-14 세중님 확정 — 「조교·연구」 배지에 **찍을 말 한 자리**.
 *
 * 무엇이 조교·연구인지 **가르는 일은 DB 의 조교연구갈래() 가 합니다.**
 * 여기는 그 값(`'조교'` · `'연구'` · null)을 **화면 글자로 바꾸는 것만** 합니다.
 * 화면 코드가 제목 글자를 보고 스스로 정하면 두 벌이 됩니다 (지침 6절).
 *
 * 왜 배지인가 — 물리치료·작업치료 **전공자를 받는 자리이지만 치료사 자리가
 * 아닌** 공고입니다. 안 보여주면 회원이 기회를 놓치고, 「○○치료사 채용공고」로
 * 적으면 거짓입니다. 그래서 **원문 제목 그대로 + 배지**입니다.
 *
 * ★ 2026-10-14 세중님 — **「조교」·「연구」 한 낱말만** 찍습니다.
 *   「치료사 채용이 아닙니다」 같은 말을 덧붙이지 않습니다. 제목이 원문
 *   그대로라 제목이 이미 그 말을 합니다.
 */
export function 조교연구말(갈래: string | null | undefined): string | null {
  if (갈래 === '조교') return '조교';
  if (갈래 === '연구') return '연구';
  return null;                       /* 모르는 값은 안 찍습니다 — 지어내지 않습니다 */
}

