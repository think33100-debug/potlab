/* ★ 2026-10-28 세중님 1번 — **연봉 표기를 「0,000만원」으로 통일합니다.**
 *
 *   「23000000이상~」   → 「2,300만원 이상」
 *   「54,678천원」      → 「약 5,468만원」     (천원 단위는 반올림 + 「약」)
 *   「2300만원~2600만원」 → 「2,300~2,600만원」
 *   「시급 12,626원」    → 그대로 (시급·일급은 단위를 살립니다)
 *   「월 2,300,000원」   → 「월 230만원」
 *
 * ★ **숫자를 바꾸는 것이 아니라 보여주는 꼴만 바꿉니다.** `뽑은값` 원문은 그대로
 *   두고 이 한 자리에서만 고칩니다 (지침 6절 — 기준은 한 자리).
 * ★ **못 읽으면 null** 을 돌려주고, 화면은 **원문을 그대로** 그립니다. 반올림으로
 *   거짓을 만들지 않습니다 — 문단이 통째로 들어온 줄·단위를 모르는 줄이 그렇습니다
 *   (`tools/화면표시_점검.mjs` 가 그 줄들을 목록으로 냅니다).
 */
const 단위배수: Record<string, number> = {
  억: 100000000, 백만: 1000000, 십만: 100000, 만: 10000, 천: 1000, '': 1,
};
/** 숫자 + 단위 + 「원」 한 덩이. 단위나 「원」이 있으면 **돈이라고 적힌 것**입니다 */
const 돈토막 = /([0-9][0-9,]*(?:\.[0-9]+)?)\s*(억|백만|십만|만|천)?\s*(원)?/g;
/** 뒤에 붙는 말 — 원문에 있는 것만 살립니다 (지어내지 않습니다) */
const 꼬리말 = /(이상|이하|내외|부터|이내|정도|선)/g;
/** 세전·세후는 **금액의 뜻을 바꾸는 말**이라 함께 적습니다 */
const 세전후 = /(세전|세후)/;
/* ★ 금액 뒤에 붙는 **딴 이야기**를 떼어 냅니다 (2026-10-28).
   워크넷 값은 「월급2,400,000원 이상 ~ 2,400,000원 이하**, 면접 후 재조정 가능**」·
   「**, 상여금 : 10(미 포함)**」 꼴이 흔합니다 (회원 화면 57건). 그 글자를 그대로 두면
   금액 덩이가 셋이 넘어 못 읽습니다. **숫자가 아닌 글이 뒤따르는 쉼표**에서 자릅니다 —
   「2,400,000」 처럼 숫자 사이 쉼표는 자르지 않습니다.
   ⚠ 떼어 낸 말(상여금 비율·면접 후 재조정)은 **화면에서 사라집니다.** 금액 칸에
   섞여 있던 딴 값이고, 자세한 것은 원문 공고에 있습니다 */
function 금액머리(t: string): string {
  return t.split(/,\s*(?=[^\d\s])/)[0].trim();
}
/** 단위도 「원」도 없는 맨 숫자는 **백만 이상**일 때만 돈으로 봅니다 —
 *  「2026. 11월」·「2년」·「9급」·호봉을 돈으로 읽지 않으려는 울타리입니다 (지침 10-5) */
export const 맨숫자최소 = 1000000;

export function 쉼표(n: number): string {
  return Math.round(n).toLocaleString('en-US');
}

/** 한 금액을 「0,000만원」 꼴로. `약`은 만원 아래가 떨어질 때만 붙습니다 */
function 만원말(값: number): { 글: string; 약: boolean } {
  if (값 < 10000) return { 글: 쉼표(값) + '원', 약: false };
  const 만 = 값 / 10000;
  return { 글: 쉼표(만) + '만원', 약: Math.abs(만 - Math.round(만)) > 0.0001 };
}

export type 돈꼴값 = { 글: string; 갈래: '연' | '시급' | '일급' | '주급' | '월' };

/** 금액 글을 **숫자로** 읽은 것 — 돈꼴() 과 릴스 고르기(tools/reels/reel-data.mjs 의 급여기준)가 함께 씁니다.
 *  읽는 규칙은 여기 한 자리입니다 (지침 6절). 못 읽으면 null — 숫자를 짐작하지 않습니다 */
export type 돈읽은값 = { t: string; 갈래: 돈꼴값['갈래']; 값들: number[]; 라벨: string };

export function 돈읽기(원문: string | null | undefined): 돈읽은값 | null {
  const 온글 = String(원문 || '').replace(/\s+/g, ' ').trim();
  if (!온글) return null;
  const t = 금액머리(온글);
  if (!t) return null;
  /* 문단이 통째로 들어온 줄은 손대지 않습니다 — 원문을 그대로 그립니다 */
  if (t.length > 40 || /[。\n]/.test(t)) return null;

  const 갈래: 돈꼴값['갈래'] = /시급|시간급/.test(t) ? '시급'
    : /일급/.test(t) ? '일급'
    : /주급/.test(t) ? '주급'
    /* 「급여 **월 3,152,600원**」 처럼 **월 뒤에 바로 숫자**가 오면 달마다 주는 돈입니다 */
    : /월\s*(급|지급|액|평균|기본|약)|월\s*[0-9]|^월/.test(t) ? '월' : '연';

  /* ★ 2026-11-19 — 「약 4,447 ~ 4,759만원」 처럼 **범위 앞 숫자에 단위가 없으면** 뒤 단위를 앞에도 물립니다.
     안 물리면 앞 숫자가 맨 숫자 울타리에 걸려 버려지고 화면에 **뒤 금액 하나**(「4,759만원」)만 보였습니다 (아주대 HS1196586464 · 외부 검토) */
  const 읽을글 = t.replace(/([0-9][0-9,]*)\s*([~∼～])\s*([0-9][0-9,]*)\s*(만|천|억)\s*원/g, '$1$4원 $2 $3$4원');
  돈토막.lastIndex = 0;
  const 값들: number[] = [];
  let m: RegExpExecArray | null;
  while ((m = 돈토막.exec(읽을글))) {
    if (!m[1]) continue;
    const 수 = Number(m[1].replace(/,/g, ''));
    if (!Number.isFinite(수) || 수 === 0) continue;
    const 적혔나 = !!(m[2] || m[3]);              /* 단위말이나 「원」이 붙었나 */
    if (!적혔나 && 수 < 맨숫자최소) continue;
    값들.push(수 * 단위배수[m[2] || '']);
  }
  if (!값들.length) return null;
  if (값들.length > 2) return null;                /* 세 덩이 넘으면 문단입니다 */

  /* ★ 「기본급」은 **그대로 살립니다** (2026-10-28) — 떼면 「기본급 2,266,000원」이
     「약 227만원」이 되어 **연봉 227만원**으로 읽힙니다. 원문의 뜻을 지웁니다 */
  const 라벨 = (t.match(/기본급/) || [])[0] || '';
  /* ★ 울타리 — 연봉 칸인데 **1,000만원 미만**이고 무슨 돈인지 적혀 있지 않으면
     손대지 않습니다. 월급인지 연봉인지 **우리가 모르는 것**이고, 「약 227만원」으로
     적으면 회원이 연봉으로 읽습니다 (지침 10-3 — 짐작하지 않습니다) */
  if (갈래 === '연' && !라벨 && Math.max(...값들) < 10000000) return null;
  return { t, 갈래, 값들, 라벨 };
}

export function 돈꼴(원문: string | null | undefined): 돈꼴값 | null {
  const r = 돈읽기(원문);
  if (!r) return null;
  const { t, 갈래, 값들, 라벨 } = r;

  /* 꼬리말이 둘이면(「이상 ~ 이하」) 범위가 이미 그 말을 하므로 안 붙입니다 */
  const 꼬리들 = t.match(꼬리말) || [];
  const 세 = (t.match(세전후) || [])[1] || '';
  const 꼬리 = [꼬리들.length === 1 ? 꼬리들[0] : '', 세].filter(Boolean).join(' ');
  const 앞말 = 갈래 === '월' ? '월 ' : 갈래 !== '연' ? 갈래 + ' ' : 라벨 ? 라벨 + ' ' : '';

  /* 시급·일급·주급은 **원 단위를 살립니다** (12,626원) */
  if (갈래 === '시급' || 갈래 === '일급' || 갈래 === '주급') {
    const 글 = 값들.map((v) => 쉼표(v) + '원').join('~');
    return { 글: (앞말 + 글 + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
  }

  if (값들.length === 2 && 값들[0] !== 값들[1]) {
    const a = 만원말(값들[0]);
    const b = 만원말(값들[1]);
    /* 둘 다 만원 꼴일 때만 뒤에 한 번 붙입니다 */
    if (a.글.endsWith('만원') && b.글.endsWith('만원')) {
      /* 원문에 「약」 이 적혀 있으면 살립니다 (2026-11-19) */
      const 약 = a.약 || b.약 || /약\s*[0-9]/.test(t) ? '약 ' : '';
      return { 글: (앞말 + 약 + a.글.replace('만원', '') + '~' + b.글
        + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
    }
    return { 글: (앞말 + a.글 + '~' + b.글 + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
  }

  const one = 만원말(값들[0]);
  return { 글: (앞말 + (one.약 ? '약 ' : '') + one.글 + (꼬리 ? ' ' + 꼬리 : '')).trim(), 갈래 };
}

/* 화면에 찍을 말. 언제나 글자를 돌려줍니다 — 칸을 숨기지 않습니다.
   ★ 2026-10-28 — 꼴을 통일합니다. 못 읽은 줄은 **원문 그대로** 그립니다 */
export function 연봉말(연봉: string | null | undefined): string {
  const d = 돈꼴(연봉);
  if (d) return d.글;
  /* 돈꼴이 못 읽은 줄 — 「원」이 적혀 있으면 **원문 그대로**.
     `금액있나` 는 DB 네숫자() 의 ③ 과 **같은 꼴**이라 고치지 않습니다 (지침 6절) */
  if (금액있나(연봉)) return String(연봉).trim();
  const 글 = String(연봉 || '').replace(/\s+/g, ' ').trim();
  /* ★ 2026-11-19 — 원문에 「내규·규정·지침·기준에 따름」 이 있을 때만 「내규에 따름」 */
  /* ★ 2026-11-20 (Codex 검토) — 「협의함」 의 끝 두 글자 「의함」 은 내규 말이 아닙니다(「면접 후 협의함」 이 「내규에 따름」 으로 바뀌었습니다) */
  if (/내규|규정|지침|기준\s*에\s*(?:따름|준함|의함)|따름|준함|(?<!협)의함/.test(글)) return 내규말;
  /* 「면접 후 협의」 처럼 짧은 원문 말은 그대로 */
  if (글 && 글.length <= 20 && /협의|면접|결정|상의|추후/.test(글)) return 글;
  return 보수확인말;
}

/* ★ 2026-11-13 세중님 — 보수 칸에 **문단이 통째로** 들어온 공고는 대표 금액 한 줄만 크게, 조건은 아래 작은 글로.
 *   (삼성서울병원 「처우 : 월정급여 410만 원 수준 (세전, 1년 만근 시 약 4,900만 원 수준) … 복리후생 … 계약기간 …」
 *    → 「약 4,900만원」 + 「1년 만근 시 급여 (세전) · 월 410만 원 수준」)
 *
 *   돈꼴() 이 읽는 한 줄짜리 값은 건드리지 않습니다(null). 숫자는 원문에 적힌 것만 씁니다 —
 *   ① 「1년 … 약 N만 원」처럼 **한 해 금액이 적힌 문단** → 그 금액 · 덧말에 원문의 조건(만근·세전·월 금액)
 *   ② 아니면 **금액이 적힌 첫 줄만** (이름표 「처우 :」는 뗌) — 문단 전체를 큰 글씨로 그리지 않습니다 */
export function 보수요약(원문: string | null | undefined): { 값: string; 덧말: string | null } | null {
  const 글 = String(원문 || '').trim();
  if (!글 || 돈꼴(글) || !금액있나(글)) return null;
  if (글.length <= 40 && !/\n/.test(글)) return null;      /* 짧은 한 줄은 연봉말() 이 원문 그대로 그립니다 */

  const 한해 = /(1\s*년|연간)\s*(만근|근무|기준)?\s*시?\s*(약)?\s*([0-9][0-9,]*)\s*만\s*원/.exec(글);
  if (한해) {
    const 수 = Number(한해[4].replace(/,/g, ''));
    if (Number.isFinite(수) && 수 >= 1000) {
      const 월 = /월\s*(?:정\s*)?(?:급여|급|보수)?\s*(약)?\s*([0-9][0-9,]*)\s*만\s*원/.exec(글);
      const 덧말 = [
        (한해[2] === '만근' ? '1년 만근 시 급여' : '1년 기준 급여') + (세전후.test(글) ? ` (${(글.match(세전후) || [])[1]})` : ''),
        월 ? `월 ${월[2]}만 원 수준` : null,
      ].filter(Boolean).join(' · ');
      return { 값: (한해[3] ? '약 ' : '') + 쉼표(수) + '만원', 덧말 };
    }
  }
  const 줄 = 글.split(/\n+/).map((l) => l.trim()).find((l) => 금액꼴.test(l));
  if (!줄) return null;
  const 알맹이 = 줄.replace(/^[^:：]{1,12}[:：]\s*/, '');
  const d = 돈꼴(알맹이);
  return { 값: d ? d.글 : 알맹이, 덧말: null };
}

/* ★ 2026-11-13 세중님 — 근무 조건의 「근무 기간」을 **월 단위**로 (「3개월」「6개월」).
 *   읽는 차례 — 지어내지 않고, 못 읽으면 null(화면은 「공고문 확인」).
 *   ① 뽑은값.근무기간            공고문에서 읽어 담은 달 수 (「6」·「6개월」)
 *   ② 워크넷 상세 empTpNm       「기간의 정함이 있는 근로계약12 개월」 → 12개월 · 「기간의 정함이 없는」 + 정규직 → 「정규직」
 *   ③ 본문 글의 「계약기간 : 1년」 「근무기간 : 임용일 ~ 6개월」
 *   ④ 정규직                    「정규직」 (2026-11-13 세중님 「정규직은 근무 기간에 정규직 이렇게 적자」) */
export const 기간없음말 = '정규직';
export function 근무기간말(p: {
  뽑은?: unknown; 워크넷고용형태?: string | null; 글?: (string | null | undefined)[]; 고용형태?: string | null;
}): string | null {
  const 달 = (n: number) => (Number.isFinite(n) && n > 0 && n <= 120 ? `${n}개월` : null);
  const 뽑 = String(p.뽑은 ?? '').trim();
  if (뽑) {
    const m = /^(\d{1,3})\s*(개월)?$/.exec(뽑);
    return m ? 달(Number(m[1])) : 뽑.slice(0, 20);
  }
  const 워 = String(p.워크넷고용형태 || '');
  const 워달 = /근로계약\s*(\d{1,3})\s*개월/.exec(워);
  if (워달) return 달(Number(워달[1]));
  if (/기간의 정함이 없는/.test(워)) return p.고용형태 === '정규직' ? 기간없음말 : null;
  for (const g of p.글 ?? []) {
    const m = /(?:계약|근무|채용|임용)\s*기간\s*[:：|]?\s*(?:[○ㅇ·\-]\s*)?(?:임용일\s*[~∼～\-]\s*)?(\d{1,3})\s*(년|개월)(?!\s*(?:이상|이내|미만))/.exec(String(g || ''));
    if (m) return 달(Number(m[1]) * (m[2] === '년' ? 12 : 1));
  }
  return p.고용형태 === '정규직' ? 기간없음말 : null;
}

