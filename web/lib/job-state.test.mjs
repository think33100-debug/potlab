/* ⑪ 연봉 표기 통일 — 「0,000만원」 (2026-10-28 세중님 1번)
      ★ 돈을 보여주는 자리입니다. 반올림이 틀리면 회원이 연봉을 잘못 읽습니다 */
{
  const 꼴 = (s) => 연봉말(s);
  /* 세중님이 적어 주신 보기 넷 */
  assert.equal(꼴('23000000이상~'), '2,300만원 이상');
  assert.equal(꼴('54,678천원'), '약 5,468만원');
  assert.equal(꼴('2300만원~2600만원'), '2,300~2,600만원');
  assert.equal(꼴('시급 12,626원'), '시급 12,626원');
  assert.equal(꼴('월 2,300,000원'), '월 230만원');
  /* 억·백만 꼴 */
  assert.equal(꼴('1억원'), '1만만원'.replace('만만', '0,000만'));   /* 1억 = 10,000만원 */
  assert.equal(꼴('年 40백만원 내외'), '4,000만원 내외');
  /* 꼬리말은 원문에 있는 것만 */
  assert.equal(꼴('3,000만원 이하'), '3,000만원 이하');
  assert.ok(!/이상|이하|내외/.test(꼴('3,000만원')));
  /* 금액이 아니면 내규에 따름 — 전과 같습니다 */
  assert.equal(꼴('내규에 따름'), 내규말);
  assert.equal(꼴(null), 내규말);
  assert.equal(꼴('9급 2호봉'), 내규말);
  /* 문단이 통째로 들어온 줄은 **원문 그대로** (지어서 줄이지 않습니다) */
  const 문단 = '보수는 공무원 보수규정에 따르며 2026년 기준 1호봉 월 2,100,000원 수준입니다';
  assert.equal(꼴(문단), 문단);
  /* 금액 뒤의 딴 이야기는 뗍니다 — 워크넷 값에 흔합니다 (회원 화면 57건) */
  assert.equal(꼴('월급2,400,000원 이상 ~ 2,400,000원 이하, 면접 후 재조정 가능'), '월 240만원');
  assert.equal(꼴('월급2,156,880원 이상, 상여금 : 60(미 포함) , 면접 후 재조정 가능'),
    '월 약 216만원 이상');
  /* 「월 + 숫자」는 달마다 주는 돈입니다. 세전·세후는 살립니다 */
  assert.equal(꼴('급여 월 3,152,600원 (세전) (설 명절상여금, 휴가비 별도)'), '월 약 315만원 세전');
  /* 「기본급」은 떼지 않습니다 — 떼면 연봉 227만원으로 읽힙니다 */
  assert.equal(꼴('기본급 2,266,000원)'), '기본급 약 227만원');
  /* 연봉 칸인데 1,000만원 미만이고 무슨 돈인지 안 적혀 있으면 **원문 그대로** */
  assert.equal(꼴('2,500,000원'), '2,500,000원');
  /* 시급은 만원으로 바꾸지 않습니다 */
  assert.ok(돈꼴('시급 12,626원').갈래 === '시급');
  assert.ok(!/만원/.test(꼴('시급 12,626원')));
}

