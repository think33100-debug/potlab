/* node web/lib/job-state.test.mjs

   마감 판단이 틀리면 둘 중 하나가 납니다 —
   멀쩡한 공고에 「마감」 띠가 붙거나, 끝난 공고를 계속 지원하러 보냅니다. */
import assert from 'node:assert/strict';
import { isClosed, todayKst, nowTimeKst, 마감배지, 시각말, 금액있나, 연봉말, 내규말, 조교연구말,
  돈꼴, 기관이름말, 지원링크, 자사채용주소, 근무처이름, 보여줄기관이름, 긁기공고인가 } from './job-state.ts';

/* ① 마감일이 빈 공고는 마감이 아닙니다.
      인수인계 원칙 — 「마감일이 비어 있으면 잘못 읽은 것」입니다.
      우리 자료에 81건 있습니다. 전부 막히면 큰일입니다 */
{
  assert.equal(isClosed(null, '2026-09-20'), false);
  assert.equal(isClosed(undefined, '2026-09-20'), false);
  assert.equal(isClosed('', '2026-09-20'), false);
  /* 날짜 모양이 아니면 판단하지 않습니다 */
  assert.equal(isClosed('상시채용', '2026-09-20'), false);
  assert.equal(isClosed('채용시 마감', '2026-09-20'), false);
}

/* ② 마감일 당일은 아직 열린 것입니다. 그날 자정까지 받는 곳이 많습니다 */
{
  assert.equal(isClosed('2026-09-20', '2026-09-20'), false);
  assert.equal(isClosed('2026-09-21', '2026-09-20'), false);
  assert.equal(isClosed('2026-09-19', '2026-09-20'), true);
  assert.equal(isClosed('2025-01-01', '2026-09-20'), true);
}

/* ③ 시각이 붙어 와도 앞의 날짜만 봅니다 */
assert.equal(isClosed('2026-09-19T23:59:00+09:00', '2026-09-20'), true);
assert.equal(isClosed('2026-09-20T00:00:00Z', '2026-09-20'), false);

/* ④ 한국 시간으로 셉니다.
      한국이 9월 20일 오전 8시일 때 UTC 는 아직 9월 19일입니다.
      UTC 로 재면 그 아홉 시간 동안 하루 늦게 판단합니다 */
{
  const 한국_20일_아침 = new Date('2026-09-19T23:00:00Z');   // KST 2026-09-20 08:00
  assert.equal(todayKst(한국_20일_아침), '2026-09-20');
  assert.notEqual(todayKst(한국_20일_아침), 한국_20일_아침.toISOString().slice(0, 10));

  /* 그 시각에 19일 마감 공고는 이미 끝난 것입니다 */
  assert.equal(isClosed('2026-09-19', todayKst(한국_20일_아침)), true);
}

/* ⑤ 오늘을 안 넘기면 진짜 오늘을 봅니다 */
assert.match(todayKst(), /^\d{4}-\d{2}-\d{2}$/);

/* ⑥ 마감 시각 (2026-10-08). DB 의 마감지났나() 와 같은 기준이어야 합니다 */
{
  const 오늘 = "2026-10-08";
  /* 시각이 없으면 그날 종일 — 밤 11시 59분에도 열려 있습니다 */
  assert.equal(isClosed("2026-10-08", 오늘, null, "23:59:00"), false);
  /* 17:30 마감 — 17:29 에는 열려 있고 17:31 에는 닫힙니다 */
  assert.equal(isClosed("2026-10-08", 오늘, "17:30:00", "17:29:00"), false);
  assert.equal(isClosed("2026-10-08", 오늘, "17:30:00", "17:30:00"), false);
  assert.equal(isClosed("2026-10-08", 오늘, "17:30:00", "17:31:00"), true);
  /* 어제·내일은 시각과 무관합니다 */
  assert.equal(isClosed("2026-10-07", 오늘, "23:59:59", "00:01:00"), true);
  assert.equal(isClosed("2026-10-09", 오늘, "00:00:01", "23:59:00"), false);
  /* 09:00 마감 (중앙보훈병원) — 저녁에는 닫혀 있어야 합니다 */
  assert.equal(isClosed("2026-10-08", 오늘, "09:00:00", "08:59:00"), false);
  assert.equal(isClosed("2026-10-08", 오늘, "09:00:00", "19:00:00"), true);
}

/* ⑦ 시각을 사람 말로 */
{
  assert.equal(시각말("09:00:00"), "오전 9시");
  assert.equal(시각말("17:30:00"), "오후 5시 30분");
  assert.equal(시각말("12:00:00"), "오후 12시");
  assert.equal(시각말("23:59:59"), "밤 12시");
  assert.equal(시각말(null), null);
  assert.match(nowTimeKst(), /^\d{2}:\d{2}:\d{2}$/);
}

/* ⑧ 마감 배지 — 목록과 상세가 **같은 함수**를 씁니다 (2026-10-09).

   2026-10-08 에 같은 이름의 dday() 가 두 벌이라 상세만 틀렸습니다.
   그 사고를 그대로 재현해 둡니다 — 근로복지공단안산병원 17:30 마감 공고 */
{
  const 그날저녁 = new Date('2026-10-08T08:39:00Z');   // 한국 10/8 17:39
  const 그날낮   = new Date('2026-10-08T05:00:00Z');   // 한국 10/8 14:00

  /* 시각이 지나면 그날이라도 회색 「마감」 — 빨강이면 안 됩니다 */
  const 지남 = 마감배지('2026-10-08', null, '17:30:00', 그날저녁);
  assert.equal(지남.text, '마감');
  assert.equal(지남.urgent, false);
  assert.equal(지남.over, true);

  /* 아직이면 시각을 붙여 빨강 */
  const 아직 = 마감배지('2026-10-08', null, '17:30:00', 그날낮);
  assert.equal(아직.text, '오늘 오후 5시 30분 마감');
  assert.equal(아직.urgent, true);
  assert.equal(아직.over, false);

  /* 시각이 없으면 그날 종일 열려 있습니다 */
  assert.equal(마감배지('2026-10-08', null, null, 그날저녁).text, '오늘 마감');

  /* 마감일이 없으면 마감표시() 가 정한 말을 그대로 씁니다 — 마감이 아닙니다 */
  const 없음 = 마감배지(null, '마감일 공고문 확인', null, 그날저녁);
  assert.equal(없음.text, '마감일 공고문 확인');
  assert.equal(없음.over, false);
  assert.equal(마감배지(null, null, null, 그날저녁).text, '마감일 공고문 확인');

  /* ★ 2026-10-22 — 날짜가 **있어도** 마감표시() 가 말을 내면 그 말을 씁니다
     (워크넷 상세 칸 「채용시까지」 · 회원 화면 160건). 마감 뒤에는 「마감」이 이깁니다 */
  assert.equal(마감배지('2026-12-08', '채용시까지', null, 그날낮).text, '채용시까지');
  assert.equal(마감배지('2026-12-08', '채용시까지', null, 그날낮).urgent, false);
  assert.equal(마감배지('2026-10-07', '채용시까지', null, 그날낮).text, '마감');
  assert.equal(마감배지('2026-10-11', '', null, 그날낮).text, 'D-3');

  /* 남은 날수 — 사흘 이하만 빨강 */
  assert.equal(마감배지('2026-10-11', null, null, 그날낮).text, 'D-3');
  assert.equal(마감배지('2026-10-11', null, null, 그날낮).urgent, true);
  assert.equal(마감배지('2026-10-12', null, null, 그날낮).text, 'D-4');
  assert.equal(마감배지('2026-10-12', null, null, 그날낮).urgent, false);

  /* 지난 날짜는 시각과 무관하게 회색 */
  assert.equal(마감배지('2026-10-07', null, null, 그날낮).over, true);
}


/* ⑨ 예상 연봉 표시 (2026-10-14 세중님 확정 · **꼴은 2026-10-28 에 통일**).
      금액이 있으면 보여 주고 · 없으면 「내규에 따름」 · 칸을 숨기지 않음.
      ★ 2026-10-28 세중님 1번 — 「0,000만원」 꼴로 **보여주는 글자만** 바꿥니다.
        전에는 원문을 그대로 찍었습니다 (아래 네 줄의 전 값이 그것입니다) */
{
  assert.equal(연봉말('3400만원 이상'), '3,400만원 이상');          /* 전 — 3400만원 이상 */
  assert.equal(연봉말('월급2,400,000원 이상'), '월 240만원 이상');   /* 전 — 월급2,400,000원 이상 */
  assert.equal(연봉말('월급 230만원~240만원'), '월 230~240만원');    /* 전 — 월급 230만원~240만원 */
  assert.equal(연봉말('연봉30,000,000원 이상'), '3,000만원 이상');   /* 전 — 연봉30,000,000원 이상 */
  assert.equal(금액있나('시급17,500원 이상 ~ 18,000원 이하'), true);

  /* 금액이 없으면 「내규에 따름」. 빈칸도 같습니다 */
  for (const v of [null, undefined, '', '   ', '내규에 따름', '보수규정에 따름', '협의', '면접 후 결정']) {
    assert.equal(연봉말(v), 내규말, '금액이 아닌 것: ' + v);
    assert.equal(금액있나(v), false);
  }

  /* 공고문을 읽어 담은 값에 보수 안내 문단이 통째로 들어온 일이 있었습니다.
     날짜·연수·급수는 금액이 아닙니다 */
  assert.equal(금액있나('보수 관련 사항 ● 임용 예정일 : 2026. 11월 중 · 임용기간 : 2년'), false);
  assert.equal(금액있나('보수는 연봉제로서 「지방공무원 보수규정」에 따라 책정함 (단위: 천원) 9급'), false);
}

