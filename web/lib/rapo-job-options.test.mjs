/* node --experimental-strip-types web/lib/rapo-job-options.test.mjs

   여러 개 고르는 칩(지역 · 기관 분류)을 눌렀을 때 — 2026-11-23 세중님 「뭘 눌러도 전국이 체크된다」 */
import assert from 'node:assert/strict';
import { 칩누름, 지역칩들, 기관분류들, 시도글, 지역칩읽기 } from './rapo-job-options.ts';

/* ① 다 켜진(전국) 채로 하나를 누르면 그것만 — 제보 화면: 대구·경북을 눌렀더니 15곳이 남았음 */
assert.deepEqual(칩누름(지역칩들, [...지역칩들], '대구·경북'), ['대구·경북']);
assert.equal(시도글(칩누름(지역칩들, [...지역칩들], '대구·경북')), '대구,경북');
/* ② 이어서 다른 지역을 누르면 더해집니다 (차례는 칩 차례) */
assert.deepEqual(칩누름(지역칩들, ['대구·경북'], '부산'), ['부산', '대구·경북']);
/* ③ 켜진 것을 다시 누르면 꺼집니다 */
assert.deepEqual(칩누름(지역칩들, ['부산', '대구·경북'], '부산'), ['대구·경북']);
assert.deepEqual(칩누름(지역칩들, ['부산'], '부산'), []);
/* ④ 다 꺼진 채(「전국」을 눌러 비운 뒤)에서 하나를 누르면 그것만 */
assert.deepEqual(칩누름(지역칩들, [], '서울'), ['서울']);
/* ⑤ 하나씩 다 켜면 다시 전국(거름 없음) */
const 하나빼고 = 지역칩들.filter((x) => x !== '제주');
assert.equal(칩누름(지역칩들, 하나빼고, '제주').length, 지역칩들.length);
/* ⑥ 주소로 되읽어도 같은 칩 */
assert.deepEqual(지역칩읽기(시도글(['부산', '대구·경북'])), ['부산', '대구·경북']);
/* ⑦ 기관 분류도 같은 규칙 */
assert.deepEqual(칩누름(기관분류들, [...기관분류들], '대학병원'), ['대학병원']);
assert.deepEqual(칩누름(기관분류들, ['대학병원'], '종합병원'), ['대학병원', '종합병원']);
console.log('칩 누름 자기점검 통과 (일곱 가지)');
