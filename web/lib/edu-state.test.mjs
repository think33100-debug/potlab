/* node web/lib/edu-state.test.mjs

   「지난 교육」을 잘못 가르면 둘 중 하나가 납니다 —
   지난 교육을 계속 보여 주거나, **멀쩡한 교육을 내립니다.** */
import assert from 'node:assert/strict';
import { 교육지났나, 지난까닭, 날더하기, 담은날유효일 } from './edu-state.ts';

const 오늘 = '2026-10-28';

/* ① 끝 날짜가 있으면 그것만 봅니다 */
assert.equal(교육지났나({ 끝: '2026-10-27', 시작: '2026-10-01' }, 오늘), true);
assert.equal(교육지났나({ 끝: '2026-10-28', 시작: '2026-10-01' }, 오늘), false);  /* 당일은 안 지남 */
assert.equal(교육지났나({ 끝: '2026-11-01', 시작: '2026-01-01' }, 오늘), false);

/* ② 끝이 없으면 시작을 봅니다 */
assert.equal(교육지났나({ 시작: '2026-10-27' }, 오늘), true);
assert.equal(교육지났나({ 시작: '2026-10-28' }, 오늘), false);
assert.equal(교육지났나({ 끝: null, 시작: '2026-12-01' }, 오늘), false);

/* ③ 둘 다 없으면 담은 날 + 30일 */
assert.equal(교육지났나({ 올린날: '2026-09-01' }, 오늘), true);
assert.equal(교육지났나({ 올린날: '2026-10-01' }, 오늘), false);   /* +30 = 10-31 */
assert.equal(교육지났나({ 올린날: '2026-09-27' }, 오늘), true);    /* +30 = 10-27 */
assert.equal(교육지났나({ 올린날: '2026-09-28' }, 오늘), false);   /* +30 = 10-28 */

/* ④ 셋 다 없으면 **안 내립니다** (모르면 그대로 둡니다) */
assert.equal(교육지났나({}, 오늘), false);
assert.equal(교육지났나({ 끝: null, 시작: null, 올린날: null }, 오늘), false);

/* 시각이 붙어 와도 날짜만 봅니다 (올린날은 timestamptz 입니다) */
assert.equal(교육지났나({ 올린날: '2026-09-01T05:30:00+00:00' }, 오늘), true);
assert.equal(교육지났나({ 끝: '2026-10-27T00:00:00Z' }, 오늘), true);

/* 날짜 꼴이 아니면 판단하지 않습니다 */
assert.equal(교육지났나({ 끝: '상시' }, 오늘), false);
assert.equal(교육지났나({ 끝: '' , 시작: '수시' }, 오늘), false);
assert.equal(교육지났나({ 끝: '2026-10-27' }, '모름'), false);

/* 까닭 글자 */
assert.equal(지난까닭({ 끝: '2026-10-01' }, 오늘), '끝 지남');
assert.equal(지난까닭({ 시작: '2026-10-01' }, 오늘), '시작 지남');
assert.equal(지난까닭({ 올린날: '2026-01-01' }, 오늘), '담은 날 +30일 지남');
assert.equal(지난까닭({ 끝: '2026-12-01' }, 오늘), null);

/* 날더하기 — 달을 넘어갑니다 */
assert.equal(날더하기('2026-10-28', 30), '2026-11-27');
assert.equal(날더하기('2026-12-20', 30), '2027-01-19');
assert.equal(담은날유효일, 30);

console.log('지난 교육 판단 통과 — 끝 → 시작 → 담은 날 +30일 · 모르면 안 내림');
