/** 원 → 「6,330」(만 원 단위 · 반올림) */
export const 만 = (원: number) => Math.round(원 / 10000).toLocaleString('ko-KR');
/** 가운데 값(중앙값) — 짝수 개면 가운데 둘의 평균 */
export const 가운데 = (xs: readonly number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
export const 셈 = (xs: readonly number[]) => ({ 낮: Math.min(...xs), 높: Math.max(...xs), 가운데: 가운데(xs) });
/** 높은 차례로 몇 번째인가 (1부터 · 같은 값이면 같은 차례) */
export const 차례 = (xs: readonly number[], v: number) => xs.filter((x) => x > v).length + 1;

