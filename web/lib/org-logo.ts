/* 기관 로고 — 공통 로고부터 (2026-11-13 세중님 「로고는 공통부터 올려보자 · 데이터베이스는 슈퍼베이스」).

   그림 바이트는 Supabase 「기관로고」 표에 있고 /api/org-logo/<열쇠> 가 내보냅니다 (RAPO노트/SQL_1113/X).
   공통 로고는 기관 종류로 고릅니다 — 보건소·보건의료원·보건지소 → health · 치매안심·광역·중앙치매센터 → dementia.
   치매요양병원은 치매센터가 아닙니다(코덱스 목록 「공통 치매센터 로고 매핑 금지」) — 병원·요양원 이름은 빼고 봅니다.
   공통 로고는 기관 이름과 같이 보여야 합니다(코덱스 조건) — 공고 행·상세 머리 모두 이름이 옆에 있습니다.
   로고가 없으면 null — 화면은 원래 「기관 기본 이미지」를 그립니다 */

const 판 = '1';   // 표의 그림을 바꾸면 올립니다 (브라우저가 오래 붙들고 있습니다)

export function 기관로고(이름: string | null | undefined): string | null {
  const n = (이름 ?? '').replace(/\s+/g, '');
  if (!n || /(병원|요양원|의원)$/.test(n) || /요양병원/.test(n)) return null;
  const 열쇠 = /치매(안심)?센터/.test(n) ? 'dementia' : /보건(소|의료원|지소)/.test(n) ? 'health' : null;
  return 열쇠 ? `/api/org-logo/${열쇠}?v=${판}` : null;
}
