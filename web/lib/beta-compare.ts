/** 연락처 모양 — 이메일 또는 휴대전화(01로 시작 · 숫자 10~11자리). 맞는지는 안 봅니다 */
export function 연락처꼴(글: string): boolean {
  const s = 글.trim();
  if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(s)) return true;
  return /^01\d{8,9}$/.test(s.replace(/[\s-]/g, ''));
}
