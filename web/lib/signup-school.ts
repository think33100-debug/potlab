/* 가입 때 학교 고르기와 관심 질문 (2026-11-15 세중님 「학교는 어디 학교인지도 · 작업치료학과·물리치료학과 모두 넣기 ·
   학교 누르면 경기 3년제 대구 4년제 이런 식으로 아래 부연 · 성인/소아 · 듣고 싶은 교육 · 관심 분야(물리·작업 학생에 맞게 예시)」).

   학교 목록은 학교 안내 글과 같은 자료입니다(lib/guide-schools.ts · 협회 공식 목록 그대로 · 손으로 고치지 않음).
   지역(시도)은 그 목록에 없어 lib/school-regions.ts 에 따로 둡니다 — 확인한 학교만 들어 있고, 없으면 지역 없이 학제만 보입니다. */

import { 물리치료학교들, 작업치료학교들 } from './guide-schools';
import { 학교지역 } from './school-regions';

export type 고를학교 = { 키: string; 이름: string; 학제: '3년제' | '4년제' | null; 시도: string | null; 학력: '전문대학' | '4년제 대학' | null };

export function 학교목록(직군: string | null | undefined): 고를학교[] {
  if (직군 === '물리치료사') {
    return 물리치료학교들.map((s) => {
      const 지 = 학교지역.pt[s.슬러그];
      const 학제 = 지?.학제 ?? (s.구분 === '대학교' ? '4년제' : null);
      return { 키: 'pt:' + s.슬러그, 이름: `${s.학교} ${s.학과}`, 학제, 시도: 지?.시도 ?? null,
        학력: s.구분 === '대학교' ? '4년제 대학' as const : '전문대학' as const };
    }).sort((a, b) => a.이름.localeCompare(b.이름, 'ko'));
  }
  return 작업치료학교들.map((s) => ({
    키: 'ot:' + s.슬러그, 이름: `${s.학교} ${s.학과 ?? '작업치료(학)과'}`, 학제: s.학제, 시도: 학교지역.ot[s.슬러그]?.시도 ?? null,
    학력: s.학제 === '4년제' ? '4년제 대학' as const : '전문대학' as const,
  })).sort((a, b) => a.이름.localeCompare(b.이름, 'ko'));
}

/** 「경기 · 3년제」 — 아는 것만 */
export const 학교부연 = (s: 고를학교) => [s.시도, s.학제].filter(Boolean).join(' · ');

