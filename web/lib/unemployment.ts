/* 실업급여(구직급여) 셈 — 2026-10-03
 *
 * ── 값을 코드에 안 박습니다 ──────────────────────────────────
 * 상한·하한·지급률·지급일수는 전부 `site_settings` 의 `실업급여_2026`
 * 한 줄에서 옵니다. 2027년이 되면 그 한 줄만 고치면 됩니다.
 * 이 파일에 기본값을 두는 것은 **설정을 못 읽었을 때 화면이 깨지지 않게**
 * 하려는 것뿐이고, 화면은 그때 「기준값을 못 읽었습니다」를 띄웁니다.
 *
 * ── 어디서 왔나 (2026년 값) ─────────────────────────────────
 *   최저임금 시간급 10,320원        고용노동부 고시 2025-08-05 · 적용 2026-01-01
 *   임금일액 상한 113,500원          고용보험법 시행령 개정 2025-12-16 국무회의
 *   구직급여 상한 하루 68,100원      같은 개정
 *   하한 = 시간급 × 80% × 8시간     고용보험법 (2019-10-01 이후)
 *   지급률 평균임금의 60%            같은 법
 *   소정급여일수                     고용보험법 별표1
 *
 * ── ★ 원 단위를 어느 단계에서 다듬나 ───────────────────────────
 * 셈은 **소수점을 그대로 들고 갑니다.** 중간에 다듬으면 끝값이 어긋납니다.
 *
 *   임금일액(화면에 보이는 것)   버림   Math.floor(3개월임금 ÷ 3개월일수)
 *   구직급여일액                 반올림 Math.round(다듬지 않은 몫 × 지급률)
 *                               ← **버림한 임금일액이 아니라 원래 몫**에 곱합니다
 *   상·하한 견주기               반올림한 일액으로
 *   모두 받는 돈                 일액(정수) × 일수(정수)
 *
 * 왜 이렇게 하나 — 월 280만 · 92일로 맞춰 보면
 *   8,400,000 ÷ 92 = 91,304.3478…
 *   임금일액  floor → 91,304
 *   일액      round(91,304.3478 × 0.6) → 54,783
 *   버림한 91,304 에 곱하면 54,782 가 되어 1원 어긋납니다.
 */

