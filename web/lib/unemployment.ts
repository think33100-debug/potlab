/** 퇴직 전 3개월의 실제 달력 일수 — 퇴직금과 같은 방식입니다 */
export function 삼개월일수(퇴사: Date = new Date()): number {
  const from = new Date(퇴사);
  from.setMonth(from.getMonth() - 3);
  return Math.round((퇴사.getTime() - from.getTime()) / 86_400_000);
}

export function 실업급여셈(input: {
  월급: number;                 // 퇴직 전 3개월 평균 월급 (원)
  가입기간: string;             // 설정의 소정급여일수 중 하나
  오십이상: boolean;
  일수기준?: number;            // 3개월 일수. 안 주면 오늘로 셉니다
  설정?: 실업급여설정;
}): 실업급여결과 {
  const s = input.설정 ?? 기본설정;
  const d3 = input.일수기준 ?? 삼개월일수();
  const 삼개월임금 = input.월급 * 3;

  /* ★ 다듬지 않은 몫을 들고 갑니다 */
  const 몫 = 삼개월임금 / d3;
  const 임금일액 = Math.floor(몫);
  const 셈한일액 = Math.round(몫 * s.지급률);

  let 일액 = 셈한일액;
  let 어디에걸렸나: 실업급여결과['어디에걸렸나'] = '그대로';
  if (셈한일액 > s.구직급여상한) { 일액 = s.구직급여상한; 어디에걸렸나 = '상한'; }
  else if (셈한일액 < s.구직급여하한) { 일액 = s.구직급여하한; 어디에걸렸나 = '하한'; }

  const 칸 = s.소정급여일수.find((x) => x.가입기간 === input.가입기간) ?? s.소정급여일수[0];
  const 일수 = input.오십이상 ? 칸.위 : 칸.아래;

  return {
    삼개월임금, 삼개월일수: d3, 임금일액, 지급률: s.지급률, 셈한일액,
    일액, 어디에걸렸나, 상한: s.구직급여상한, 하한: s.구직급여하한,
    일수, 가입기간: 칸.가입기간,
    나이칸: input.오십이상 ? '50세 이상·장애인' : '50세 미만',
    모두: 일액 * 일수,
  };
}
