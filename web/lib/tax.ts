/* 근로자 부담분 */
export const 국민연금 = 0.0475;
export const 건강보험 = 0.03595;
export const 장기요양_대_건강보험 = 0.1314;
export const 고용보험 = 0.009;

/* 국민연금은 소득에 상·하한이 있습니다. 2026년 값을 못 찾아 안 넣었습니다 —
   치료사 급여대에서는 상한(월 600만원대)에 거의 안 닿습니다.
   ponytail: 닿는 사람이 생기면 그때 넣습니다. 지금 넣으면 틀린 숫자만 늡니다 */

/* 국세청 근로소득공제 (한도 2,000만원) */
function 근로소득공제(총급여: number): number {
  let v: number;
  if (총급여 <= 5_000_000) v = 총급여 * 0.7;
  else if (총급여 <= 15_000_000) v = 3_500_000 + (총급여 - 5_000_000) * 0.4;
  else if (총급여 <= 45_000_000) v = 7_500_000 + (총급여 - 15_000_000) * 0.15;
  else if (총급여 <= 100_000_000) v = 12_000_000 + (총급여 - 45_000_000) * 0.05;
  else v = 14_750_000 + (총급여 - 100_000_000) * 0.02;
  return Math.min(v, 20_000_000);
}

/* 국세청 종합소득세율 (2023년 귀속부터) */
const 세율: [number, number, number][] = [   // [상한, 세율, 누진공제]
  [14_000_000, 0.06, 0],
  [50_000_000, 0.15, 1_260_000],
  [88_000_000, 0.24, 5_760_000],
  [150_000_000, 0.35, 15_440_000],
  [300_000_000, 0.38, 19_940_000],
  [500_000_000, 0.40, 25_940_000],
  [1_000_000_000, 0.42, 35_940_000],
  [Infinity, 0.45, 65_940_000],
];

function 산출세액(과세표준: number): number {
  if (과세표준 <= 0) return 0;
  for (const [상한, r, 누진] of 세율) {
    if (과세표준 <= 상한) return 과세표준 * r - 누진;
  }
  return 0;
}

/* 국세청 근로소득세액공제 */
function 세액공제(산출: number, 총급여: number): number {
  const v = 산출 <= 1_300_000 ? 산출 * 0.55 : 715_000 + (산출 - 1_300_000) * 0.3;
  let 한도: number;
  if (총급여 <= 33_000_000) 한도 = 740_000;
  else if (총급여 <= 70_000_000) 한도 = Math.max(660_000, 740_000 - (총급여 - 33_000_000) * 0.008);
  else if (총급여 <= 120_000_000) 한도 = Math.max(500_000, 660_000 - (총급여 - 70_000_000) * 0.5);
  else 한도 = Math.max(200_000, 500_000 - (총급여 - 120_000_000) * 0.5);
  return Math.min(v, 한도);
}

/* 보험료는 10원 미만을 버립니다 (공단 실무).
   round 를 먼저 하는 이유는 부동소수점 때문입니다 —
   300만원 × 0.9% 가 26,999.9999… 로 나와 그냥 버리면 26,990원이 됩니다 */
const won10 = (x: number) => Math.floor(Math.round(x) / 10) * 10;

export type Breakdown = {
  gross: number;        // 월 세전
  net: number;          // 월 세후
  국민연금: number; 건강보험: number; 장기요양: number; 고용보험: number;
  소득세: number; 지방소득세: number;
  공제합계: number;
};

/* 월 세전 → 월 세후. 금액은 전부 「원」 단위입니다.
   dependents = 부양가족 수 (본인 포함, 최소 1) */
export function netFromGross(grossMonthly: number, dependents = 1): Breakdown {
  const g = Math.max(0, Math.round(grossMonthly));
  const 연금 = won10(g * 국민연금);
  const 건강 = won10(g * 건강보험);
  const 요양 = won10(건강 * 장기요양_대_건강보험);
  const 고용 = won10(g * 고용보험);

  /* 연간으로 바꿔 소득세를 구합니다. 비과세는 안 넣었습니다 —
     식대 비과세는 회사마다 달라서 넣으면 오히려 틀립니다 */
  const 총급여 = g * 12;
  const 근로소득금액 = 총급여 - 근로소득공제(총급여);
  const 인적공제 = 1_500_000 * Math.max(1, Math.floor(dependents));
  const 보험료공제 = (연금 + 건강 + 요양 + 고용) * 12;   // 연금·건보는 소득공제 대상
  const 과세표준 = Math.max(0, 근로소득금액 - 인적공제 - 보험료공제);
  const 결정세액 = Math.max(0, 산출세액(과세표준) - 세액공제(산출세액(과세표준), 총급여));

  const 소득세 = won10(결정세액 / 12);
  const 지방 = won10(소득세 * 0.1);
  const 공제합계 = 연금 + 건강 + 요양 + 고용 + 소득세 + 지방;

  return {
    gross: g, net: g - 공제합계,
    국민연금: 연금, 건강보험: 건강, 장기요양: 요양, 고용보험: 고용,
    소득세, 지방소득세: 지방, 공제합계,
  };
}

/* 월 세후 → 월 세전. 공제가 세전에 물려 있어 바로 못 뒤집습니다.
   세전을 조금씩 올려가며 맞는 자리를 찾습니다 (이분법, 40번이면 1원까지 붙습니다) */
export function grossFromNet(netMonthly: number, dependents = 1): number {
  const target = Math.max(0, Math.round(netMonthly));
  if (target === 0) return 0;
  let lo = target, hi = target * 2 + 1_000_000;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    if (netFromGross(mid, dependents).net < target) lo = mid; else hi = mid;
  }
  return Math.round(hi);
}

/* 만원 단위로 주고받는 화면용 — 십원 단위까지 흔들리는 숫자를 안 보여줍니다 */
export const 만원 = (원: number) => Math.round(원 / 10_000);
