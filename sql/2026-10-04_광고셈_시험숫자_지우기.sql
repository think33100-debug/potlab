-- ═══════════════════════════════════════════════════════════════
--  승인이 필요한 줄 — **이것 한 줄뿐입니다**
--  2026-10-04. 올리지 않았습니다.
-- ═══════════════════════════════════════════════════════════════
--
--  이 줄이 무엇을 하나
--    제가 광고 세기가 도는지 시험하려고 배너를 잠깐 켜고 세 번 불렀습니다
--    (봄 2 · 누름 1). 배너는 바로 다시 껐지만 그 **숫자 한 줄**이 남았습니다.
--    광고주에게 보여줄 숫자가 아니니 치웁니다.
--
--  무엇을 지우나
--    광고셈 표의 **줄 하나** (자리='앱', 날=올린 날). 표를 지우지 않습니다.
--    공고·회원·교육 자료와 아무 관계가 없습니다.
--
--  안 돌려도 괜찮습니다
--    그냥 두면 「앱 배너가 10월 4일에 2번 보이고 1번 눌렸다」가 남습니다.
--    틀린 숫자이지만 해롭지는 않습니다. 광고를 처음 켜는 날 전에
--    치우면 됩니다.
--
--  확인하고 지우려면 — 먼저 무엇이 지워지는지 봅니다
--    select 자리, 날, 봄, 누름 from 광고셈;
--    → 2026-10-04 · 앱 · 봄 2 · 누름 1  한 줄만 나와야 합니다

delete from 광고셈
 where 자리 = '앱'
   and 날   = date '2026-10-04';

