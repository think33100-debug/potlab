-- alio-group.mjs 는 anon 열쇠로 부릅니다. 표는 service_role 만 닿으므로
-- SECURITY DEFINER 로 감싸고 수집 열쇠로 막습니다 (다른 수집 함수와 같은 틀).
create or replace function "알리오자리같음목록"(p_secret text, p_source text)
returns setof text
language plpgsql stable security definer set search_path to 'public'
as $function$
begin
  if not exists (select 1 from collect_secret s
                  where s.source = p_source and s.secret = p_secret
                    and length(p_secret) >= 24) then
    raise exception '열쇠가 맞지 않습니다' using errcode = '42501';
  end if;
  return query select "묶음키" from "알리오자리같음";
end $function$;

revoke all on function "알리오자리같음목록"(text, text) from public;
grant execute on function "알리오자리같음목록"(text, text) to anon, authenticated, service_role;


