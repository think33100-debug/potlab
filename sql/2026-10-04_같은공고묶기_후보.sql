-- ════════════════════════════════════════════════════════════════
--  같은 공고 묶기 — 묶을 쌍 **찾기만** 합니다 (2026-10-04)
--  ⚠ 올리지 않았습니다. 묶는 것은 세중님 승인 뒤입니다.
-- ════════════════════════════════════════════════════════════════
--
--  ── 세중님이 말씀하신 조건 ───────────────────────────────────
--  「기관 + 제목 속 공고번호」 에
--  「직군이나 진료과가 다르면 묶지 않는다」 를 더할 것.
--
--  ── 재 보니 **직군으로는 못 가립니다** ───────────────────────
--  오늘 자료로 두 방향 다 틀렸습니다.
--
--  ① 직군이 달라도 **같은 공고**인 것 — 묶어야 하는데 안 묶입니다
--
--     강진의료원 2026-18
--       HS  HS1485761166  직군 (없음)      제목 똑같음
--       HS3 HS82396933    직군 물리치료사   제목 똑같음
--     → 옛 수집기가 직군을 안 채웠을 뿐, 같은 글입니다.
--       「직군 다르면 안 묶음」 이면 이런 **진짜 중복 5쌍이 다 살아남습니다.**
--
--  ② 직군이 같아도 **다른 공고**인 것 — 안 묶어야 하는데 묶입니다
--
--     강릉의료원 2026-69
--       CE2 CE80111       직군 작업치료사   「보건직 8급 작업치료사」
--       HS3 HS1529593314  직군 작업치료사   「기간제 간호사, …, 보건직 8급 작업치료사, …」
--     → 직군이 **똑같습니다.** 「직군 다르면 안 묶음」 으로는 못 거릅니다.
--
--  ── 그래서 **제목**으로 가립니다 ─────────────────────────────
--  공고번호 부분만 떼어내고 나머지 제목이 같은지 봅니다.
--  세중님이 막고 싶어 하신 「진료과가 다른 것」(내과 전문의 ↔ 일반외과
--  전문의)도 제목이 다르므로 이것으로 함께 걸립니다.
--
--  재 본 결과 — 8쌍 중 **6쌍 묶임 · 강릉의료원 2쌍 빠짐** (뜻대로입니다)
-- ════════════════════════════════════════════════════════════════

-- ── 묶을 쌍 찾기 (읽기만 합니다) ────────────────────────────────
with x as (
  select id, source, org_name, title, job_group,
         (regexp_match(title, '(\d{4})\s*-\s*(\d{1,5})\s*호'))[1] || '-' ||
         (regexp_match(title, '(\d{4})\s*-\s*(\d{1,5})\s*호'))[2] as 공고번호,
         /* 공고번호 토막을 떼고 빈칸을 없앤 나머지 제목.
            여기가 다르면 **다른 자리**로 봅니다 */
         regexp_replace(
           regexp_replace(title, '\[?[^\]]*\d{4}\s*-\s*\d{1,5}\s*호\]?', '', 'g'),
           '\s+', '', 'g') as 번호뺀제목
  from job_posts
  where title ~ '\d{4}\s*-\s*\d{1,5}\s*호'
), 묶음 as (
  select org_name, 공고번호, 번호뺀제목,
         count(*) as 건수,
         array_agg(id order by id) as ids,
         array_agg(source order by id) as 출처들
  from x
  group by org_name, 공고번호, 번호뺀제목      -- ★ 제목까지 같아야 한 묶음
  having count(*) > 1
)
select org_name as 기관, 공고번호, 건수, 출처들, ids,
       (select left(title, 60) from job_posts where id = ids[1]) as 제목
from 묶음
order by org_name, 공고번호;

-- ── 묶기 (승인 뒤에만) ──────────────────────────────────────────
-- 이미 `공고연결()` · `공고연결풀기()` 함수와 `job_group` 칸이 있습니다.
-- **새 표가 필요 없습니다.** 위 쿼리로 나온 ids 를 짝지어 부르면 됩니다.
--
--   select 공고연결('HS1485761166', 'HS82396933');   -- 보기일 뿐입니다
--
-- 되돌리기 — select 공고연결풀기('…');
--
-- ⚠ 앞 다섯 쌍은 **HS ↔ HS3** 입니다. 옛 수집기(HS)를 끄면 저절로
--   사라지므로, 급하게 묶지 않아도 됩니다.
--   정말 묶을 값이 있는 것은 **한국생명존중희망재단 1쌍**
--   (알리오 AL2 ↔ 나라일터 GJ2) 뿐입니다 — 둘 다 살아 있는 수집기입니다.
