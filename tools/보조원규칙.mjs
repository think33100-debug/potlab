export const 보조말 = /물리\s*치료\s*보조|작업\s*치료\s*보조|치료\s*보조\s*원|보조\s*원|보조\s*인력/;
export const 우리직군말 = /(물리|작업|도수)\s*치료\s*(사|직|선생)/;

export function 보조원인가(제목) {
  const t = String(제목 || '');
  const 보조 = 보조말.test(t);
  const 우리 = 우리직군말.test(t);
  return { 됨: 보조 && !우리, 보조, 우리 };
}
