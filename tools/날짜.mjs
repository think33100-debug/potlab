/* 출처마다 다른 날짜 꼴을 한 가지로 풉니다 (2026-09-30).
 *
 *   import { 날짜풀기 } from './날짜.mjs';
 *   날짜풀기('26-10-08')              → '2026-10-08'
 *   날짜풀기('채용시까지  26-11-07')   → '2026-11-07'
 *   날짜풀기('20261008')              → '2026-10-08'
 *   날짜풀기('2026-10-08')            → '2026-10-08'
 *   날짜풀기('채용시까지')             → null
 *
 * ── 왜 한 곳에 모으나 ────────────────────────────────────────
 * 워크넷 `closeDt` 는 **66%가 「채용시까지  26-11-29」 처럼 한 칸에 섞여** 옵니다
 * (2026-09-30 에 235건 중 156건으로 확인). 치매센터는 `2026-09-29`,
 * 나라일터는 `20261011` 입니다. 출처마다 따로 풀면 한 곳만 고치고 나머지를 잊습니다.
 *
 * ── 두 자리 연도 ─────────────────────────────────────────────
 * `26-10-08` 의 `26` 은 2026 입니다. 2000 을 더합니다.
 * 채용공고라 1900년대가 올 일은 없습니다.
 */

/** 여러 꼴의 날짜를 `YYYY-MM-DD` 로. 못 풀면 null */
export function 날짜풀기(v) {
  const t = String(v == null ? '' : v).trim();
  if (!t) return null;

  /* ① 네 자리 연도 — 2026-10-08 · 2026.10.08 · 20261008 */
  let m = t.match(/(\d{4})[.\-/]?(\d{2})[.\-/]?(\d{2})(?!\d)/);
  if (m && Number(m[1]) >= 1990 && Number(m[1]) <= 2100) return m[1] + '-' + m[2] + '-' + m[3];

  /* ② 두 자리 연도 — 26-10-08 · 26.10.08 (앞에 다른 말이 붙어 있어도 됩니다) */
  m = t.match(/(?:^|[^\d])(\d{2})[.\-/](\d{2})[.\-/](\d{2})(?!\d)/);
  if (m) {
    const 달 = Number(m[2]), 날 = Number(m[3]);
    if (달 >= 1 && 달 <= 12 && 날 >= 1 && 날 <= 31) return '20' + m[1] + '-' + m[2] + '-' + m[3];
  }
  return null;
}

/** 「채용시까지」 처럼 날짜가 아닌 말이 섞여 있나 */
export function 채용시까지인가(v) {
  return /채용\s*시\s*까지|수시|상시|충원\s*시/.test(String(v || ''));
}

/* ── 스스로 하는 검사 ──────────────────────────────────────
 *   node tools/날짜.mjs
 * 워크넷·치매센터·나라일터에서 실제로 온 값으로 시험합니다 */
if (process.argv[1] && process.argv[1].endsWith('날짜.mjs')) {
  const 시험 = [
    ['26-10-08', '2026-10-08'],                 // 워크넷 목록
    ['채용시까지  26-11-07', '2026-11-07'],      // 워크넷 · 66%가 이 꼴
    ['채용시까지  26-10-24', '2026-10-24'],
    ['20261008', '2026-10-08'],                 // 워크넷 상세 receiptCloseDt
    ['20261011', '2026-10-11'],                 // 나라일터
    ['2026-09-29', '2026-09-29'],               // 치매센터
    ['2026.09.29', '2026-09-29'],
    ['채용시까지', null],                        // 날짜가 없습니다
    ['', null], [null, null], ['미정', null],
  ];
  let 틀림 = 0;
  for (const [넣은것, 바란것] of 시험) {
    const 나온것 = 날짜풀기(넣은것);
    const ok = 나온것 === 바란것;
    if (!ok) 틀림++;
    console.log((ok ? '○ ' : '★ ') + '「' + String(넣은것) + '」'.padEnd(22)
      + '→ ' + String(나온것) + (ok ? '' : '   (바란 것 ' + String(바란것) + ')'));
  }
  const 깃발 = [['채용시까지  26-11-07', true], ['26-10-08', false], ['상시채용', true]];
  for (const [넣은것, 바란것] of 깃발) {
    const 나온것 = 채용시까지인가(넣은것);
    const ok = 나온것 === 바란것;
    if (!ok) 틀림++;
    console.log((ok ? '○ ' : '★ ') + '채용시까지인가(「' + 넣은것 + '」) → ' + 나온것);
  }
  console.log(틀림 ? '\n★ ' + 틀림 + '개 틀렸습니다' : '\n○ 다 맞습니다');
  process.exit(틀림 ? 1 : 0);
}
