/* 창구로 보내기 전 **줄마다 보고**, 실패하면 **반씩 나눠** 문제 줄만 뺍니다
 * 2026-10-14 세중님 결정 (0번)
 *
 * ── 왜 ───────────────────────────────────────────────────────
 * 2026-10-14 22:00 에 병원 수집기가 **통째로** 죽었습니다 —
 *     400 22P05 unsupported Unicode escape sequence
 *         \u0000 cannot be converted to text
 * 담음 0. 한 바퀴가 **공고 한 건 때문에** 아무것도 못 담았습니다.
 * 줄 단위가 아니라 **200줄씩 한 번에** 보내기 때문입니다.
 *
 * 글자를 걷는 고침은 따로 했지만, 그것은 **아는 꼴 하나**를 막을 뿐입니다.
 * 모르는 꼴이 또 오면 똑같이 죽습니다. 그래서 **구조로** 막습니다 —
 *   ① 보내기 전에 줄마다 봅니다 (아는 꼴은 아예 안 보냅니다)
 *   ② 그래도 묶음이 실패하면 **반씩 나눠** 다시 보내 문제 줄만 가립니다
 *   ③ 뺀 줄은 **셈과 까닭**을 남깁니다 — 조용히 버리지 않습니다 (지침 2절)
 *
 * ── 쓰는 법 ──────────────────────────────────────────────────
 *   import { 반씩보내기 } from './보낼줄.mjs';
 *   const r = await 반씩보내기({
 *     줄들: 담을것, 묶음: 200, 이름: 'collect_put',
 *     보내기: (조각) => rpc(cfg, 'collect_put',
 *       { p_secret: …, p_source: SOURCE, p_rows: 조각 }),
 *   });
 *   r.담음 · r.뺀줄[{id, 까닭}] · r.건너뜀[{id, 까닭}]
 *
 * 자기 점검:  node tools/보낼줄.mjs
 */

/* PostgreSQL `text` 가 못 받는 글자. `\n`·`\t`·`\r` 은 받습니다 */
export const 못쓰는글자 = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/;

/** 한 줄이 보낼 만한가 — 안 되면 **까닭**을 돌려줍니다 (되면 null) */
export function 줄까닭(줄, 옵션 = {}) {
  const 최대 = 옵션.최대글자 ?? 2_000_000;      /* 한 줄이 2MB 를 넘으면 안 보냅니다 */
  if (줄 == null || typeof 줄 !== 'object') return '줄이 객체가 아닙니다';
  for (const [칸, v] of Object.entries(줄)) {
    if (typeof v !== 'string') continue;
    if (못쓰는글자.test(v)) {
      const i = v.search(못쓰는글자);
      const c = v.charCodeAt(i);
      return '못 쓰는 글자 U+' + c.toString(16).padStart(4, '0').toUpperCase()
        + ' (칸 ' + 칸 + ' · ' + i + '번째)';
    }
  }
  let 길이;
  try { 길이 = JSON.stringify(줄).length; } catch { return '글로 못 바꿉니다(고리 참조?)'; }
  if (길이 > 최대) return '너무 깁니다 ' + 길이 + '자';
  return null;
}

/**
 * 묶음으로 보내되, 실패하면 **반씩 나눠** 문제 줄만 뺍니다.
 *
 * `보내기(조각)` 는 창구를 부르고 창구가 돌려준 것을 그대로 주면 됩니다.
 * 돌려준 것에 `담음` 이 있으면 더합니다 (없으면 조각 길이로 셉니다).
 */
export async function 반씩보내기({ 줄들, 보내기, 묶음 = 200, 이름 = '', 로그 = console.log }) {
  const 뺀줄 = [];      /* 우리가 **보내기 전에** 뺀 것 */
  const 못담은줄 = [];  /* 보냈는데 창구가 **거절한** 것 (반씩 나눠 가린 것) */
  const 건너뜀 = [];    /* 창구가 「건너뛴것」 으로 돌려준 것 (맞는 동작) */
  let 담음 = 0;

  /* ① 보내기 전에 줄마다 봅니다 */
  const 보낼것 = [];
  for (const 줄 of (줄들 || [])) {
    const 까닭 = 줄까닭(줄);
    if (까닭) { 뺀줄.push({ id: 줄?.id ?? '(id 없음)', 까닭 }); continue; }
    보낼것.push(줄);
  }

  /* ② 묶음으로 보내고, 실패하면 반씩 나눕니다 */
  async function 보내보기(조각) {
    if (!조각.length) return;
    try {
      const r = await 보내기(조각);
      담음 += (r && r['담음'] != null) ? r['담음'] : 조각.length;
      for (const x of ((r && r['건너뛴것']) || [])) 건너뜀.push(x);
    } catch (e) {
      const 왜 = String(e?.message || e).slice(0, 200);
      if (조각.length === 1) {
        못담은줄.push({ id: 조각[0]?.id ?? '(id 없음)', 까닭: 왜 });
        return;
      }
      const 반 = Math.floor(조각.length / 2);
      await 보내보기(조각.slice(0, 반));
      await 보내보기(조각.slice(반));
    }
  }

  for (let i = 0; i < 보낼것.length; i += 묶음) {
    await 보내보기(보낼것.slice(i, i + 묶음));
  }

  /* ③ 조용히 버리지 않습니다 (지침 2절) */
  const 모두못담음 = [...뺀줄, ...못담은줄];
  if (모두못담음.length && 로그) {
    로그('  ⚠ 담지 못한 줄 ' + 모두못담음.length + '건' + (이름 ? ' (' + 이름 + ')' : '')
      + ' — 나머지는 담았습니다');
    모두못담음.slice(0, 8).forEach((x) => 로그('     ' + String(x.id).padEnd(16) + x.까닭));
    if (모두못담음.length > 8) 로그('     … 그리고 ' + (모두못담음.length - 8) + '건 더');
  }

  return { 담음, 뺀줄, 못담은줄, 건너뜀, 못담음: 모두못담음.length };
}

/* ── 자기 점검 ───────────────────────────────────────────────── */
if (import.meta.url === 'file://' + process.argv[1]
    || process.argv[1]?.endsWith('보낼줄.mjs')) {
  const 어겼나 = [];
  const 봐 = (말, 참) => { if (!참) 어겼나.push(말); };

  /* ① 줄까닭 */
  봐('멀쩡한 줄은 null', 줄까닭({ id: 'A', body: '물리치료사 1명\n접수 10:00' }) === null);
  봐('NUL 은 걸린다', /U\+0000/.test(줄까닭({ id: 'A', body: '앞\u0000뒤' }) || ''));
  봐('칸 이름을 적는다', /칸 body/.test(줄까닭({ id: 'A', body: '앞\u0000뒤' }) || ''));
  봐('줄바꿈·탭은 괜찮다', 줄까닭({ id: 'A', body: '가\n나\t다\r라' }) === null);
  봐('너무 긴 줄은 걸린다', /너무 깁니다/.test(줄까닭({ id: 'A', body: 'ㄱ'.repeat(40) }, { 최대글자: 20 }) || ''));

  /* ② 반씩보내기 — **NUL 넣은 가짜 줄 하나를 섞어** 나머지가 담기는지
        (세중님이 시키신 시험 그대로) */
  const 줄들 = [];
  for (let i = 0; i < 20; i++) 줄들.push({ id: 'OK' + i, body: '물리치료사 1명' });
  줄들.splice(7, 0, { id: '나쁜줄', body: '앞\u0000뒤' });     /* 보내기 전에 걸릴 것 */

  const 본것 = [];
  const r1 = await 반씩보내기({
    줄들, 묶음: 5, 이름: '시험', 로그: null,
    보내기: async (조각) => { 본것.push(조각.length); return { 담음: 조각.length }; },
  });
  봐('나쁜 줄 하나만 빠진다', r1.뺀줄.length === 1 && r1.뺀줄[0].id === '나쁜줄');
  봐('나머지 20줄은 담긴다', r1.담음 === 20);
  봐('못담음 셈이 1', r1.못담음 === 1);

  /* ③ 창구가 **보내 봐야** 거절하는 꼴 — 반씩 나눠 그 줄만 가립니다 */
  const 줄들2 = [];
  for (let i = 0; i < 16; i++) 줄들2.push({ id: 'B' + i, body: '가' });
  줄들2[11].body = '창구가싫어함';
  let 부른횟수 = 0;
  const r2 = await 반씩보내기({
    줄들: 줄들2, 묶음: 16, 이름: '시험2', 로그: null,
    보내기: async (조각) => {
      부른횟수++;
      if (조각.some((x) => x.body === '창구가싫어함')) throw new Error('400 22P05 …');
      return { 담음: 조각.length };
    },
  });
  봐('문제 줄 하나만 못 담는다', r2.못담은줄.length === 1 && r2.못담은줄[0].id === 'B11');
  봐('나머지 15줄은 담긴다', r2.담음 === 15);
  봐('까닭을 남긴다', /22P05/.test(r2.못담은줄[0].까닭));
  봐('반씩 나눈다(한 줄씩 다 보내지 않는다)', 부른횟수 < 16);

  if (어겼나.length) {
    console.error('✗ 자기 점검 실패 — ' + 어겼나.join(' · '));
    process.exit(1);
  }
  console.log('○ 자기 점검 통과 — 12가지 (NUL 줄 하나를 섞어도 나머지는 담깁니다)');
  console.log('   반씩 나누느라 창구를 부른 횟수 ' + 부른횟수 + '번 (16줄 · 한 줄씩이면 16번)');
}
