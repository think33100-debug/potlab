export const 눕 = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
export const 글자만 = (s) => String(s == null ? '' : s).replace(/[^0-9A-Za-z가-힣]/g, '');
export const 규칙말 = /^(?:내규|보수\s*규정|규정)에?\s*따름$|^협의$|^추후\s*협의$/;

/** 날짜는 **여러 꼴**로 찾습니다 — 원문은 「2026. 10. 28.」 처럼 적습니다 */
export const 날짜꼴들 = (v) => {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(눕(v));
  if (!m) return null;
  const [, y, mo, d] = m;
  return [`${y}${mo}${d}`, `${y}${String(Number(mo))}${String(Number(d))}`,
    `${mo}${d}`, `${String(Number(mo))}${String(Number(d))}`];
};
export const 시각꼴들 = (v) => {
  const m = /^(\d{1,2}):(\d{2})/.exec(눕(v));
  if (!m) return null;
  const [, h, mi] = m;
  return [`${h}${mi}`, `${String(Number(h))}${mi}`,
    `${String(Number(h))}시${Number(mi) ? mi + '분' : ''}`];
};

/* ★ **우리가 앞에 붙인 표식 낱말**을 떼고 봅니다.
   `칸뽑기()` 는 예상연봉을 「표식 + 값」으로 담습니다 —
     우리 값   「보수 월 2,323천원(세전) 수준」
     공고문    「보수**수준** : 월 2,323천원(세전) 수준」
   공고문의 표식은 「보수수준」인데 우리는 「보수」만 붙였으니, 첫 조각
   「보수 월 2」 가 공고문에 없는 글자가 되어 **멀쩡한 값이 틀림으로** 셌습니다
   (근로복지공단 305475 · 한림대동탄 3건). 표식은 우리가 붙인 말이라
   원문에 댈 것이 아닙니다 — 떼고 **값만** 댑니다. */
export const 표식뗀값 = (s) => 눕(s)
  .replace(/^(?:급\s*여|보\s*수|임\s*금|연\s*봉|처\s*우|기본급)\s*(?:수준|조건|기준)?\s*[:：]?\s*/, '');

export const 조각내기 = (s) => 표식뗀값(s).split(/[,，、·/|]|\s-\s/)
  .map((x) => x.replace(/^(?:자격|학력|면허|경력|근무지|지역)\s*[:：]?\s*/, '').trim())
  .filter((x) => 글자만(x).length >= 2);

/* 고용형태는 **같은 뜻의 다른 말**이 원문에 있으면 맞음입니다 —
   우리가 내는 값은 셋뿐입니다 (정규직·계약직·무기계약직 · 공고문읽기.mjs) */
export const 고용형태말 = { 정규직: /정규직|기간의?\s*정함이?\s*없|공무직|무기계약/,
  계약직: /계약직|기간제|임기제|한시|대체|임시직|인턴|촉탁|단기|비정규/,
  무기계약직: /무기계약|공무직|기간의?\s*정함이?\s*없/ };

/** 원문으로 쓸 만한 글인가 — 너무 짧으면 댈 수 없습니다 (포털이 준 줄인 글) */
export const 원문쓸만한가 = (원문) => 글자만(원문).length > 200;

/* ★ 2026-10-22 밤 — **금액은 글자가 아니라 돈으로 댑니다.**
   워크넷 공고 쪽은 「월급 **250만원** ~ 260만원」 이라 적고, 우리 칸에는 상세 API 가
   준 「월급**2,500,000원** 이상 ~ 2,600,000원 이하」 가 들어 있습니다. **같은 돈**인데
   글자가 달라서, 표본 20건의 예상연봉이 전부 「틀림」으로 나왔습니다 (0% · 2026-10-22).
   그래서 양쪽에서 **금액을 숫자로 뽑아** 견줍니다.
     250만원 → 2500000 · 2,500,000원 → 2500000 · 40백만원 → 40000000 · 3천만원 → 30000000
   ★ 십만 원보다 작은 수는 셈에서 뺍니다 — 「상여금 : 1」·「60」 같은 꼬리표입니다. */
const 곱 = { 억: 1e8, 백만: 1e6, 천만: 1e7, 만: 1e4, 천: 1e3 };
export function 금액들(s) {
  const t = String(s == null ? '' : s).replace(/\s+/g, '');
  const 모 = new Set();
  const re = /(\d[\d,.]*)\s*(억|백만|천만|만|천)?\s*원/g;
  let m;
  while ((m = re.exec(t))) {
    const n = Number(String(m[1]).replace(/[,\s]/g, ''));
    if (!Number.isFinite(n)) continue;
    const v = Math.round(n * (곱[m[2]] || 1));
    if (v >= 100000) 모.add(v);
  }
  return 모;
}

/**
 * 칸 하나를 원문에 댑니다.
 * @param {string} 칸  칸 이름 (칸들 가운데)
 * @param {{값:any, 어디서:string}|null} 우리것  {값, 어디서:'공고문'|'포털칸'}
 * @param {string} 원문
 * @returns {{판정:'맞음'|'틀림'|'빈칸'|'규칙말'|'포털칸'|'원문없음', 값:string|null, 까닭:string}}
 */
export function 칸판정(칸, 우리것, 원문) {
  if (!우리것) return { 판정: '빈칸', 값: null, 까닭: '' };
  const v = 눕(우리것.값);
  if (!v) return { 판정: '빈칸', 값: null, 까닭: '' };
  if (규칙말.test(v)) return { 판정: '규칙말', 값: v, 까닭: '우리가 고른 말 — 분모 밖' };
  if (우리것.어디서 === '포털칸') return { 판정: '포털칸', 값: v, 까닭: '포털이 준 값 — 분모 밖' };
  if (!원문쓸만한가(원문)) return { 판정: '원문없음', 값: v, 까닭: '댈 원문이 없습니다' };
  const 원문글자 = 글자만(원문);

  const 꼴 = 칸 === '접수마감' ? 날짜꼴들(v) : 칸 === '마감시각' ? 시각꼴들(v) : null;
  if (꼴) {
    return 꼴.some((x) => 원문글자.includes(글자만(x)))
      ? { 판정: '맞음', 값: v, 까닭: '원문에 그 날짜·시각이 있음' }
      : { 판정: '틀림', 값: v, 까닭: '원문에 그 날짜·시각이 없음' };
  }
  if (칸 === '고용형태') {
    const 말 = 고용형태말[v];
    return 말 && 말.test(원문)
      ? { 판정: '맞음', 값: v, 까닭: '원문에 그 말이 있음' }
      : { 판정: '틀림', 값: v, 까닭: '원문에 그 고용형태 말이 없음' };
  }
  /* 예상연봉은 **돈으로** 댑니다 (글자 꼴이 서로 다릅니다 — 위 금액들() 설명) */
  if (칸 === '예상연봉') {
    const 우리돈 = 금액들(v);
    if (우리돈.size) {
      const 원문돈 = 금액들(원문);
      /* ★ 2026-10-22 밤 — **원문이 만원 단위로 줄여 적으면 맞음입니다.**
         워크넷 쪽은 「월 **267만원**」 이라 적고 상세 API 는 「2,677,400원」 을 줍니다.
         우리 값이 더 정확한데 틀림으로 세고 있었습니다 (표본 3건 · 2026-10-22).
         그래서 **만원 아래를 버린 값·올린 값**도 맞는 것으로 봅니다. */
      const 만원꼴 = (x) => [x, Math.floor(x / 10000) * 10000, Math.round(x / 10000) * 10000,
        Math.ceil(x / 10000) * 10000];
      const 없는돈 = [...우리돈].filter((x) => !만원꼴(x).some((y) => 원문돈.has(y)));
      if (!없는돈.length) {
        return { 판정: '맞음', 값: v, 까닭: '금액 ' + [...우리돈].map((x) => x.toLocaleString()).join('·') + '원이 원문에 있음' };
      }
      return { 판정: '틀림', 값: v,
        까닭: '원문에 없는 금액 ' + 없는돈.map((x) => x.toLocaleString()).join('·') + '원'
          + (원문돈.size ? ' (원문은 ' + [...원문돈].map((x) => x.toLocaleString()).join('·') + '원)' : ' (원문에 금액이 없습니다)') };
    }
    /* 금액이 없는 글(「공고문 참조」 같은 것)은 아래 조각 대조로 */
  }
  const 조각 = 조각내기(v);
  const 남는것 = 조각.filter((x) => !원문글자.includes(글자만(x)));
  if (!조각.length || !남는것.length) {
    return { 판정: '맞음', 값: v, 까닭: '조각 ' + 조각.length + '개가 다 원문에 있음' };
  }
  return { 판정: '틀림', 값: v, 까닭: '원문에 없는 조각 「' + 남는것[0].slice(0, 22) + '」' };
}

