/* 「승인 기다리는 것」을 **문서에서 읽어** 아침 메일에 한 절로 (2026-10-27 세중님 3번)
 *
 *   node tools/승인대기읽기.mjs            지금 기다리는 것을 찍습니다
 *   node tools/승인대기읽기.mjs --자기점검
 *
 * ── 왜 ───────────────────────────────────────────────────────
 * 자율 운행으로 바꾸면서 **승인 자리는 멈추지 않고 문서에 쌓고 다음 일로** 갑니다
 * (CLAUDE.md 「지휘 절」 ⓑ). 그러면 세중님이 **메일 한 줄로** 무엇이 기다리는지
 * 봐야 합니다 — 안 보이면 영영 안 결정되고, 저는 「물어봤다」고 착각합니다.
 *
 * ── 읽는 꼴 (docs/승인대기_*.md) ───────────────────────────
 *   ## ㉠ [승인대기 · D] 보관 기간을 지키는 **지우는 크론** 셋
 *   위험  중간 — 크론 줄 추가 · 운영 자료 delete
 * 대괄호 안이 **상태**이고, `위험` 줄의 첫 낱말이 **낮음/중간/높음**입니다.
 * 상태에 「승인」·「넣었습니다」·「동결 뒤」가 있으면 **기다리는 것이 아닙니다.**
 * ★ 위험을 **짐작하지 않습니다** — `위험` 줄이 없으면 「미정」으로 적습니다 (지침 10-3).
 *
 * ── 세중님이 치는 말 ───────────────────────────────────────
 *   「㉠㉢ ㄱㄱ」  → 그 항목만 실행합니다. 적지 않은 것은 손대지 않습니다
 */
import fs from 'node:fs';
import path from 'node:path';

/* ★ 「승인대기」는 **기다리는 중**입니다 — 「승인」 두 글자로 거르면 그것까지 빠집니다 */
export const 기다리지않는말 = /넣었습니다|동결\s*뒤|접었|물렀|승인(?!대기)/;

/** 승인대기 문서 한 편을 읽습니다 → [{ 번호, 제목, 상태, 위험 }] */
export function 읽기(글) {
  const 줄들 = String(글 || '').split(/\r?\n/);
  const 낸것 = [];
  let 지금 = null;
  for (const l of 줄들) {
    const m = l.match(/^##\s+(\S+)\s*(?:\[([^\]]*)\])?\s*(.*)$/);
    if (m) {
      지금 = { 번호: m[1], 상태: (m[2] || '').trim(), 위험: '미정',
        제목: m[3].replace(/\*\*/g, '').replace(/`/g, '').trim() };
      낸것.push(지금);
      continue;
    }
    if (!지금) continue;
    const w = l.match(/^\s*(?:★\s*)?위험\s+(낮음|중간|높음)/);
    if (w && 지금.위험 === '미정') 지금.위험 = w[1];
  }
  /* ★ 2026-10-28 — **상태 칸도 「위험」 줄도 없으면 승인 항목이 아닙니다.**
     지휘 절 ⓑ 는 승인 항목에 `[승인대기]` 와 `위험 낮음|중간|높음` **둘 다**를
     요구합니다. 그래서 둘 다 없는 머리글(예: 「★ 2026-10-28 — 오늘 것은 다
     넣었습니다」 같은 맺음말)은 셈에서 뺍니다 — 안 빼면 아침 메일이
     「기다리는 것 1개」로 거짓을 찍습니다 (2026-10-28 에 그랬습니다).
     ★ 위험 줄이 있으면 **상태가 비어도 셉니다** — 못 세는 쪽이 더 위험합니다 */
  return 낸것.filter((x) => !기다리지않는말.test(x.상태)
    && !(!String(x.상태 || '').trim() && x.위험 === '미정'));
}

/** 가장 최근 `docs/승인대기_*.md` 를 찾아 읽습니다 */
export function 지금것(docs) {
  const 터 = docs || path.join(import.meta.dirname, '..', 'docs');
  if (!fs.existsSync(터)) return { 문서: null, 것들: [] };
  const 것 = fs.readdirSync(터).filter((n) => /^승인대기_.*\.md$/.test(n)).sort();
  if (!것.length) return { 문서: null, 것들: [] };
  const 문서 = 것[것.length - 1];
  return { 문서, 것들: 읽기(fs.readFileSync(path.join(터, 문서), 'utf8')) };
}

/** 메일에 넣을 줄 — 기다리는 것이 없으면 **빈 배열**입니다 (빈 절을 찍지 않습니다) */
export function 메일줄(docs) {
  const { 문서, 것들 } = 지금것(docs);
  if (!것들.length) return [];
  const 줄 = ['', '── 승인 기다리는 것 ' + 것들.length + '개 (' + 문서 + ') ──'];
  for (const x of 것들) {
    줄.push('  ' + x.번호 + ' [' + x.위험 + '] ' + x.제목.slice(0, 60));
  }
  줄.push('  → 하실 것만 「' + 것들.map((x) => x.번호).join('') + ' ㄱㄱ」 처럼 적어 주시면'
    + ' 그것만 합니다 (적지 않은 것은 손대지 않습니다)');
  return 줄;
}

