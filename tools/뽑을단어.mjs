/* 공백을 빼고 견줍니다 — 「물리 치료사」 도 같은 말입니다 */
const 붙 = (s) => String(s || '').replace(/\s+/g, '');

/** 글 안에서 ①을 찾습니다. 없으면 [] */
export function 확정찾기(글) {
  const t = 붙(글);
  return 확정.filter((w) => t.includes(붙(w)));
}
/** 글 안에서 ②를 찾습니다. `기존것도` 가 참이면 기존에만 있던 7개도 같이 봅니다 */
export function 가능성찾기(글, 기존것도 = true) {
  const t = 붙(글);
  const 볼것 = 기존것도 ? 가능성.concat(기존에만) : 가능성;
  return 볼것.filter((w) => t.includes(붙(w)));
}
/** 쌓아둘 직종이 적혀 있나 */
export function 쌓아둘것인가(글) {
  const t = 붙(글);
  return 쌓아둘직종.filter((w) => t.includes(붙(w)));
}
