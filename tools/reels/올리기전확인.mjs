const 붙 = (s) => String(s || '').replace(/[^0-9A-Za-z가-힣]/g, '');
const 직군들 = (g) => (/물리/.test(g || '') ? ['물리'] : []).concat(/작업/.test(g || '') ? ['작업'] : []).concat(!/물리|작업/.test(g || '') ? ['공통'] : []);
const 직군겹침 = (a, b) => { const A = 직군들(a), B = 직군들(b); return A.includes('공통') || B.includes('공통') || A.some((x) => B.includes(x)); };
/* 같은 기관인가 — 기관번호가 둘 다 있으면 그것만 · 없으면 이름(한쪽이 다른 쪽을 품으면 같은 곳: 「포항의료원 방문의료센터」) */
const 같은기관 = (a, b) => (a['기관번호'] && b['기관번호'] ? a['기관번호'] === b['기관번호']
  : !!붙(a.org_name) && (붙(a.org_name).includes(붙(b.org_name)) || 붙(b.org_name).includes(붙(a.org_name))));

/** 이미 올린 것과 겹치나 — 같은 기관 · 같은 마감일 · 직군이 겹침.
    내줄들·올린줄들: [{ id, 기관번호, org_name, job_group, apply_to }] → 겹친 올린 줄(없으면 null) */
export function 중복찾기(내줄들, 올린줄들) {
  const 내id = new Set(내줄들.map((x) => x.id));
  for (const 올 of 올린줄들) {
    if (내id.has(올.id)) continue;
    for (const 내 of 내줄들) if (내.apply_to && 내.apply_to === 올.apply_to && 같은기관(내, 올) && 직군겹침(내.job_group, 올.job_group)) return 올;
  }
  return null;
}

/** 만든 뒤 값이 바뀌었나 — 지금 회원 화면 값(job_posts_pub)과 만든 때의 기록·캡션을 견줍니다.
    → 바뀐 것 글 목록 (빈 목록이면 그대로) */
export function 값바뀜({ ids, 마감일, 캡션, 인원글안봄 = false }, 지금줄들) {
  const 틀림 = [];
  const 있는 = new Set(지금줄들.map((x) => x.id));
  for (const id of ids) if (!있는.has(id)) 틀림.push(`${id} 가 회원 화면에 없습니다 (내려갔거나 보류함)`);
  const 글 = String(캡션 || '');
  for (const x of 지금줄들) {
    if (x.apply_to !== 마감일) 틀림.push(`${x.id} 마감일이 바뀜 — 만든 때 ${마감일} · 지금 ${x.apply_to || '없음'}`);
    if (x.employ_type && !글.includes(x.employ_type)) 틀림.push(`${x.id} 고용형태가 바뀜 — 지금 「${x.employ_type}」이 글에 없음`);
    if (!인원글안봄 && x.headcount != null && !글.includes(`${x.headcount}명`)) 틀림.push(`${x.id} 모집인원이 바뀜 — 지금 「${x.headcount}명」이 글에 없음`);
  }
  return 틀림;
}

/** 원문 대조(Codex 가 원문 사진을 읽어 값과 견준 것 · job_posts.뽑은값.사진대조)를 통과했나 — 2026-11-26 세중님 「확실하지 않은 거 안 됨 · 코덱스가 오케이하면 올림」
    값을 고친 통과(고친칸수 > 0)는 통과가 만든 때보다 **앞**이어야 합니다(고친 값으로 그린 것). → 안 되는 까닭 목록 (빈 목록이면 통과) */
export function 대조안됨(ids, 줄들, 만든때) {
  const 까닭 = [];
  const 표 = new Map(줄들.map((x) => [x.id, x['뽑은값']?.['사진대조'] || null]));
  for (const id of ids) {
    const p = 표.get(id);
    if (!p) { 까닭.push(`${id} 원문 대조를 아직 안 받음`); continue; }
    if (p['통과'] !== true) { 까닭.push(`${id} 원문 대조 통과 못 함 — ${String(p['까닭'] || '까닭 없음').slice(0, 80)}`); continue; }
    if (Number(p['고친칸수'] || 0) > 0) {
      const 통과때 = Date.parse(p['때'] || ''), 만든 = Date.parse(만든때 || '');
      if (!(Number.isFinite(통과때) && Number.isFinite(만든) && 통과때 < 만든)) 까닭.push(`${id} 원문 대조가 값을 고친 뒤 다시 만들지 않음 — 「만들기」로 다시 만든 뒤 올리세요`);
    }
  }
  return 까닭;
}

