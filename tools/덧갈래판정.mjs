/* ═══════════════════════════════════════════════════════════════
 *  워크넷 덧갈래 판정 — 시설 설명에 속지 않게 (2026-10-03)
 * ═══════════════════════════════════════════════════════════════
 *
 *  왜 따로 있나
 *    덧갈래(면허·낱말 검색)로 온 줄은 **직종코드가 우리 것이 아닙니다.**
 *    그래서 지금 수집기는 그냥 버립니다 — 83건이 옛것만 읽은 까닭입니다.
 *
 *    그런데 새 앱의 판정을 그대로 쓰면 이런 것이 올라옵니다 —
 *      「물리치료실 완비 요양보호사 모집」   matchJob = 물리치료사
 *      「간호조무사 모집 (물리치료실 있음)」  matchJob = 물리치료사
 *    시설 설명인데 구인 직군으로 읽습니다. 세중님이 꼭 보라고 하신 자리입니다.
 *
 *  ── 판정은 새 앱 것을 **그대로** 씁니다 ──────────────────────
 *    matchJob · notOurs · titleOtherOnly  ← tools/gas-rules.mjs (구운 규칙)
 *    확정 · 가능성 낱말                    ← tools/뽑을단어.mjs
 *    옛 wnJudge_ 를 베끼지 않았습니다. 이 파일이 하는 일은
 *    **그 위에 「시설 설명인가」 한 겹을 얹는 것**뿐입니다.
 *
 *  ── 세 갈래 ─────────────────────────────────────────────────
 *    보이기   제목의 우리 직군 낱말이 **구인 대상**으로 읽힐 때만
 *    보류함   낱말은 있는데 시설 설명으로 읽히거나, 남의 직종이 주인일 때
 *             본문에서만 낱말이 나올 때도 보류함 — 본문은 약한 증거입니다
 *    버림     확정도 가능성도 없을 때
 *
 *    **애매하면 보류함입니다** (세중님 2026-10-03).
 *
 *  ponytail: 낱말 둘레를 보는 어림짐작입니다. 「물리치료실이 완비된
 *  병원에서 물리치료사를 모십니다」처럼 둘이 같이 나오면 보이기로 갑니다
 *  (뒤쪽이 구인 대상이라 맞는 판정입니다). 거꾸로 「물리치료사가 쓰는
 *  시설」처럼 꼬아 쓴 것은 못 가립니다 — 그건 보류함으로 떨어집니다.
 * ═══════════════════════════════════════════════════════════════ */
import { matchJob, notOurs, titleOtherOnly } from './gas-rules.mjs';
import { 확정, 가능성 } from './뽑을단어.mjs';

const 붙 = (s) => String(s || '').replace(/\s+/g, '');

/* 시설·공간을 가리키는 꼬리. 「물리치료실」 「작업치료팀」 「재활치료센터」 */
const 시설꼬리 = /(실|팀|센터|파트|과|부|부서|룸|코너)/;
/* 「있다·갖췄다」 쪽 말. 구인이 아니라 자랑입니다 */
const 갖춤말 = /(완비|구비|보유|있음|있습니다|있어요|운영|설치|갖춘|갖추|포함|내)/;
/* 구인 대상으로 읽히는 꼬리 */
const 구인말 = /(사|선생님|쌤|직|요원|인력|기사|치료사)/;

/* 괄호로 묶어 쓴 꼴을 펼칩니다 (2026-10-03 세중님 지시).

     「물리(작업)치료사」  →  물리치료사 · 작업치료사     둘 다 우리 것
     「재활(운동)치료사」  →  재활치료사 · 운동치료사     둘 다 우리 것 아님

   ★ 여기서 「우리 것이냐」를 **직접 가리지 않습니다.** 펼친 글자를 제목에
     붙여서 matchJob 이 가리게 둡니다. 그래야 판정이 한 군데(gas-rules)에만
     있습니다. 재활(운동)치료사는 펼쳐도 matchJob 이 안 잡아서 그대로
     보류함으로 갑니다 — 세중님이 그러라고 하신 그대로입니다. */
export function 괄호풀기(제목) {
  const 나온것 = [];
  /* 앞말(1~4자) + (가운뎃말) + 뒷말(2~5자) */
  for (const m of String(제목 || '').matchAll(/([가-힣]{1,4})\(([가-힣]{1,4})\)([가-힣]{2,5})/g)) {
    나온것.push(m[1] + m[3], m[2] + m[3]);
  }
  return [...new Set(나온것)];
}

/** 그 낱말이 **시설 설명**으로 쓰였나 */
export function 시설설명인가(글, 낱말) {
  const t = 붙(글);
  const w = 붙(낱말);
  let i = t.indexOf(w);
  let 시설로쓴것 = 0;
  let 구인으로쓴것 = 0;
  while (i > -1) {
    const 뒤 = t.slice(i + w.length, i + w.length + 8);
    if (시설꼬리.test(뒤.slice(0, 1)) && 갖춤말.test(뒤)) 시설로쓴것++;
    else if (구인말.test(뒤.slice(0, 3))) 구인으로쓴것++;
    else if (시설꼬리.test(뒤.slice(0, 1))) 시설로쓴것++;
    else 구인으로쓴것++;          // 「물리치료사 채용」처럼 낱말 자체가 직군
    i = t.indexOf(w, i + 1);
  }
  /* 구인으로 읽히는 자리가 하나라도 있으면 시설 설명이 아닙니다 */
  return 시설로쓴것 > 0 && 구인으로쓴것 === 0;
}

/**
 * 덧갈래로 온 한 줄을 가립니다.
 * @param {{제목:string, 본문?:string, 기관?:string}} v
 * @returns {{갈래:'보이기'|'보류함'|'버림', 직군:string, 왜:string}}
 */
export function 덧갈래가리기(v) {
  const 제목 = String(v.제목 || '');
  const 본문 = String(v.본문 || '');

  /* ① 제목에 남의 직종만 또렷하면 버립니다 (새 앱 규칙 그대로) */
  if (titleOtherOnly(제목)) {
    return { 갈래: '버림', 직군: '', 왜: '제목이 남의 직종만 가리킵니다' };
  }

  /* ② 제목의 우리 직군 낱말.
     괄호 꼴을 펼쳐 **붙인 제목**으로 봅니다 — 「물리(작업)치료사」 처럼
     붙여 쓰면 matchJob 이 못 읽기 때문입니다. 펼친 말을 뒤에 붙이면
     matchJob 이 둘 다 보고 「공통」까지 알아서 가립니다 */
  const 펼친말 = 괄호풀기(제목);
  const 펼친제목 = 펼친말.length ? 제목 + ' ' + 펼친말.join(' ') : 제목;
  const 제목직군 = matchJob(펼친제목);
  if (제목직군 && !notOurs(제목)) {
    const 걸린낱말 = 확정.filter((w) => 붙(펼친제목).includes(붙(w)));
    const 시설뿐 = 걸린낱말.length > 0 && 걸린낱말.every((w) => 시설설명인가(펼친제목, w));
    if (시설뿐) {
      return { 갈래: '보류함', 직군: '',
        왜: '제목의 「' + 걸린낱말.join('·') + '」가 시설 설명으로 읽힙니다 — 사람이 봅니다' };
    }
    return { 갈래: '보이기', 직군: 제목직군, 왜: '제목에 직군이 구인 대상으로 적혀 있습니다' };
  }

  /* ③ 제목에 없으면 본문을 봅니다. **본문은 약한 증거라 보이기로 안 올립니다** */
  if (본문) {
    const 본문확정 = 확정.filter((w) => 붙(본문).includes(붙(w)));
    const 쓸만한것 = 본문확정.filter((w) => !시설설명인가(본문, w));
    if (쓸만한것.length) {
      return { 갈래: '보류함', 직군: '',
        왜: '본문에 「' + 쓸만한것.join('·') + '」가 있습니다 (제목엔 없음) — 사람이 봅니다' };
    }
    if (본문확정.length) {
      return { 갈래: '보류함', 직군: '',
        왜: '본문의 「' + 본문확정.join('·') + '」가 시설 설명으로 읽힙니다 — 사람이 봅니다' };
    }
    const 본문가능 = 가능성.filter((w) => 붙(본문).includes(붙(w)));
    if (본문가능.length) {
      return { 갈래: '보류함', 직군: '',
        왜: '본문에 가능성 낱말 「' + 본문가능.slice(0, 3).join('·') + '」 — 사람이 봅니다' };
    }
  }

  /* ④ 제목에 가능성 낱말이라도 있으면 버리지 않습니다 */
  const 제목가능 = 가능성.filter((w) => 붙(제목).includes(붙(w)));
  if (제목가능.length) {
    return { 갈래: '보류함', 직군: '',
      왜: '제목에 가능성 낱말 「' + 제목가능.slice(0, 3).join('·') + '」 — 사람이 봅니다' };
  }

  /* ⑤ 제목이 「…」 로 **잘려 있으면** 버리지 않습니다 (2026-10-04).

     워크넷 목록은 제목을 잘라서 줍니다. 여기까지 왔다는 것은 **보이는
     데까지는** 직군 낱말이 하나도 없었다는 뜻인데, 잘린 뒤쪽에 있을 수
     있습니다. 실제로 걸렸습니다 —

       「전남권 넥슨 공공어린이재활의료센터(목포중앙병원) ...」

     공공어린이재활의료센터는 우리가 하나도 빠뜨리면 안 되는 1층입니다.
     보이는 글자만으로 버리면 이런 것이 소리 없이 사라집니다.

     ★ 남의 직종이 **보이는 곳에** 적힌 것은 위(①)에서 이미 버렸습니다.
       여기 오는 것은 「아무 직종도 안 보이는데 잘린」 것뿐입니다. */
  if (/(\.\.\.|…)\s*$/.test(제목.trim())) {
    return { 갈래: '보류함', 직군: '',
      왜: '제목이 잘려 있어 뒤를 못 봤습니다 — 사람이 봅니다' };
  }

  return { 갈래: '버림', 직군: '', 왜: '확정도 가능성도 없습니다' };
}

