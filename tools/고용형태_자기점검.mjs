const 어긴것 = [];
const 봐 = (이름, 제목, 글, 바란값) => {
  const r = 고용형태판정(제목, 글);
  if (r.값 !== 바란값) {
    어긴것.push(이름 + '\n      바란 것 「' + 바란값 + '」 · 나온 것 「' + r.값 + '」'
      + '\n      왜 — ' + r.왜);
  } else {
    console.log('  ○ ' + 이름.padEnd(26) + ' → 「' + (r.값 || '(비움)') + '」  ' + r.왜);
  }
};

