/* 네 갈래 규칙 검사 (2026-09-25).

   돌리는 법 —  node tools/check-sort.mjs
   깨지면 0 이 아닌 값으로 끝납니다.

   왜 있나 — 제목 단어 하나가 진짜 공고를 죽입니다. 규칙을 고칠 때마다
   손으로 눌러보면 「홍보팀 및 물리치료사 모집」 같은 칸을 빠뜨립니다.

   규칙은 tools/sort-rule.mjs 한 벌입니다. 여기서 다시 만들지 않습니다. */
import { sortJob, 확정단어, 보류보장단어, 받기예외, 버림단어 } from './sort-rule.mjs';

const 표 = [
  /* ── 1 직군 확정 → 회원 목록 ── */
  ['홍보팀 및 물리치료사 모집',              '회원목록', '버림(홍보)이 같이 있어도 확정이 이깁니다'],
  ['요양보호사 및 작업치료사 모집',           '회원목록', '버림(요양보호사)이 같이 있어도'],
  ['검진센터 물리치료사 채용',                '회원목록', '같음'],
  ['물리치료사, 언어치료사 모집',             '회원목록', '예외를 빼도 물리치료사가 남습니다'],
  ['물리 치료사님을 모십니다',                '회원목록', '공백 빼고 견줍니다'],
  ['작업 치료사 구함',                        '회원목록', '같음'],

  /* ── 2 관련 단어 → 보류함 ── */
  ['재활치료업무보조 (장애인 제한채용)',      '보류함',   '「재활치료」는 확정이 아닙니다'],
  ['행동발달증진센터 치료사 채용',            '보류함',   '「치료사」만으론 확정이 아닙니다'],
  ['특수체육 지도자 모집',                    '보류함',   '관련 단어'],
  ['○○요양원 직원 채용',                     '보류함',   '관련 단어(요양원)'],

  /* ── 3 아무 단어 없음 → 보류함 ── */
  ['서울대 2027년 직원 모집',                 '보류함',   '아무 단어도 없음'],
  ['2026년 제4차 정규직 공개채용 공고',       '보류함',   '같음'],

  /* ── 4 버림 단어만 → 쓰레기통 ── */
  ['당직전담사 채용 (장애인우선채용)',        '쓰레기통', '버림만'],
  ['요양보호사 모집합니다',                   '쓰레기통', '같음'],
  ['2026년 하반기 수련생(체험형 청년인턴) 모집공고', '쓰레기통', '꼴'],
  ['○○병원 원무과 직원 채용',                '쓰레기통', '부서'],
  ['보건소장 공개모집',                       '쓰레기통', '자리'],
  ['국립교통재활병원 계약직 언어치료사 채용공고', '쓰레기통', '받기 예외라 확정이 아닙니다'],
  ['미술치료사 모집',                         '쓰레기통', '같음'],

  /* ── 안전장치 — 괄호 안에 직군이 셋 이상 ── */
  ['2026년도 일반직(행정, 보건, 간호조무, 원무직) 신규직원 공개채용', '보류함',
   '본문에 물리치료사가 있을 수 있습니다'],
  ['일반직(행정, 원무) 채용',                 '쓰레기통', '쉼표 하나면 안전장치가 안 걸립니다'],
];

let 틀림 = 0;
console.log(`확정 ${확정단어.length}개 · 보류보장 ${보류보장단어.length}개 · 받기예외 ${받기예외.length}개 · 버림 `
  + Object.values(버림단어).reduce((n, a) => n + a.length, 0) + '개\n');

for (const [제목, 바람, 메모] of 표) {
  const g = sortJob(제목);
  const ok = g.갈래 === 바람;
  if (!ok) 틀림 += 1;
  console.log(`  ${ok ? '○' : '✗'} ${바람.padEnd(5)}${ok ? '' : ' ← 나온 것 ' + g.갈래}  ${제목.slice(0, 44)}`);
  if (!ok) console.log(`        (${메모}) 걸린 단어 ${g.걸린단어.join(', ') || '없음'}`);
}

/* 받기 예외는 버림 단어에도 있어야 합니다 — 안 그러면 보류함에 쌓입니다 */
for (const w of 받기예외) {
  if (w === '방사선치료사') continue;            // 이건 버림에 안 넣기로 했습니다
  if (!Object.values(버림단어).some((a) => a.includes(w))) {
    console.log(`  ✗ 받기 예외 「${w}」 가 버림 단어에 없습니다 — 보류함에 쌓입니다`);
    틀림 += 1;
  }
}
/* 확정 단어는 보류 보장에도 있어야 합니다 — 1번이 먼저라 해는 없지만, 빠지면 규칙이 어긋난 것입니다 */
for (const w of 확정단어) {
  if (!보류보장단어.includes(w)) { console.log(`  ✗ 확정 단어 「${w}」 가 보류 보장에 없습니다`); 틀림 += 1; }
}

/* ── 직군 칸을 정말 보나 ──────────────────────────────────────
   2026-09-26 에 여기서 크게 샜습니다. sortJob 이 제목만 받게 돼 있는데
   수집기가 sortJob(제목, 직군) 으로 불러서 **둘째 인자가 조용히 버려졌습니다.**
   자격요건·첨부에서 직군이 정해진 공고가 제목에 단어가 없다는 이유로
   보류함에 묻혔습니다 (강원대학교병원 대체근로자 공고).
   조용히 버려지는 인자는 시험으로만 잡힙니다. */
const 직군칸 = [
  ['2026-45(대체근로자) 채용 공고', '물리치료사', '회원목록'],
  ['일반직(행정, 원무) 채용',        '작업치료사', '회원목록'],   // 버림 단어가 있어도 직군이 이깁니다
  ['2026-45(대체근로자) 채용 공고', '',          '보류함'],
];
for (const [제목, 직군, 바람] of 직군칸) {
  const g = sortJob(제목, 직군);
  const ok = g.갈래 === 바람;
  if (!ok) 틀림 += 1;
  console.log(`  ${ok ? '○' : '✗'} 직군칸 ${JSON.stringify(직군 || '(빈칸)').padEnd(10)}`
    + `${바람.padEnd(5)}${ok ? '' : ' ← 나온 것 ' + g.갈래}  ${제목.slice(0, 32)}`);
}
if (sortJob.length < 2) {
  console.log('  ✗ sortJob 이 인자를 하나만 받습니다 — gas 는 (제목, 직군) 둘입니다');
  틀림 += 1;
}

console.log(틀림 ? `\n  ${틀림}칸이 틀립니다` : `\n  ${표.length + 직군칸.length}칸 다 맞습니다`);
process.exit(틀림 ? 1 : 0);
