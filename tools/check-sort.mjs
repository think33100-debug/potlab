/* 세 갈래 규칙 검사 — 받기 / 쓰레기통 / 보류함 (2026-09-25).

   돌리는 법 —  node tools/check-sort.mjs
   깨지면 0 이 아닌 값으로 끝납니다.

   왜 있나 — 제목 단어 하나가 진짜 공고를 죽입니다. 규칙을 고칠 때마다
   손으로 눌러보면 「홍보팀 및 물리치료사 모집」 같은 칸을 빠뜨립니다.
   그래서 **꼭 맞아야 하는 칸을 박아둡니다.**

   규칙은 tools/sort-rule.mjs 한 벌입니다. 여기서 다시 만들지 않습니다. */
import { sortJob, 받기단어, 받기예외, 버림단어 } from './sort-rule.mjs';

const 표 = [
  /* ── 안전장치 가 — 받기가 버림을 이깁니다 ── */
  ['홍보팀 및 물리치료사 모집',                    '받기',     '버림(홍보)이 같이 있어도 받기'],
  ['검진센터 물리치료사 채용',                     '받기',     '같음'],

  /* ── 받기 예외 — 「치료사」가 있어도 받기가 아닙니다 ── */
  ['국립교통재활병원 계약직 언어치료사 채용공고',    '쓰레기통', '언어치료사는 남의 직군'],
  ['<여수강남요양병원-언어치료사 계약직>구인',      '쓰레기통', '같음'],
  ['미술치료사 모집',                              '쓰레기통', '같음'],
  ['물리치료사, 언어치료사 모집',                   '받기',     '예외를 빼도 물리치료사가 남습니다'],

  /* ── 공백 빼고 견주기 ── */
  ['물리 치료사님을 모십니다',                     '받기',     '띄어쓴 꼴'],
  ['작업 치료사 구함',                             '받기',     '같음'],

  /* ── 안전장치 나 — 괄호 안에 직군이 셋 이상 ── */
  ['2026년도 일반직(행정, 보건, 간호조무, 원무직) 신규직원 공개채용', '보류함',
   '본문에 물리치료사가 있을 수 있습니다'],
  ['일반직(행정, 원무) 채용',                      '쓰레기통', '쉼표 하나면 안전장치가 안 걸립니다'],

  /* ── 버림 ── */
  ['요양보호사 모집합니다',                        '쓰레기통', '직군'],
  ['2026년 하반기 수련생(체험형 청년인턴) 모집공고', '쓰레기통', '꼴'],
  ['○○병원 원무과 직원 채용',                     '쓰레기통', '부서'],
  ['보건소장 공개모집',                            '쓰레기통', '자리'],

  /* ── 둘 다 없음 ── */
  ['2026년 제4차 정규직 공개채용 공고',            '보류함',   '받기도 버림도 없음'],
  ['[중앙보훈병원] 기간제 직원 채용 공고(9월)',     '보류함',   '같음'],
];

let 틀림 = 0;
console.log(`받기 ${받기단어.length}개 · 받기예외 ${받기예외.length}개 · 버림 `
  + Object.values(버림단어).reduce((n, a) => n + a.length, 0) + '개\n');

for (const [제목, 바람, 메모] of 표) {
  const g = sortJob(제목);
  const ok = g.갈래 === 바람;
  if (!ok) 틀림 += 1;
  console.log(`  ${ok ? '○' : '✗'} ${바람.padEnd(5)}${ok ? '' : ' ← 나온 것 ' + g.갈래}`
    + `  ${제목.slice(0, 44)}`);
  if (!ok) console.log(`        (${메모}) 걸린 단어 ${g.걸린단어.join(', ') || '없음'}`);
}

/* 받기 예외는 버림 단어에도 있어야 합니다 — 안 그러면 보류함에 쌓입니다 */
for (const w of 받기예외) {
  if (w === '방사선치료사') continue;            // 이건 버림에 안 넣기로 했습니다
  const 있나 = Object.values(버림단어).some((a) => a.includes(w));
  if (!있나) { console.log(`  ✗ 받기 예외 「${w}」 가 버림 단어에 없습니다 — 보류함에 쌓입니다`); 틀림 += 1; }
}

console.log(틀림 ? `\n  ${틀림}칸이 틀립니다` : `\n  ${표.length}칸 다 맞습니다`);
process.exit(틀림 ? 1 : 0);
