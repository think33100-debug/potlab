/* 확정 직군 낱말이 제 일을 하는지 봅니다 (2026-09-28).
 *
 *   node tools/check-jobwords.mjs
 *
 * ── 왜 있나 ────────────────────────────────────────────────
 * 「재활치료」 가 확정 낱말에 있어서 「재활치료업무보조」 가 공통으로 잡히고,
 * 회원 목록에 남의 자리가 올라갔습니다 (청주의료원 제26-9회 · 2026-09-28).
 * 낱말 하나를 빼는 일인데 `matchJob_` 을 부르는 곳이 50군데입니다.
 * 그래서 「빼면 어디로 가는가」 를 여기서 못 박아 둡니다.
 *
 * ── 무엇을 보나 ────────────────────────────────────────────
 * ① 확정: 물리치료 · 작업치료 두 낱말만
 * ② 「재활치료」 만 있는 공고는 **버려지지 않고 보류함**으로 (사람이 봅니다)
 * ③ gas 의 확정 낱말과 tools/sort-rule.mjs 의 확정단어가 같은지
 */
import { matchJob, hospVerdict } from './gas-rules.mjs';
import { 확정단어, sortJob } from './sort-rule.mjs';

const 칸 = [
  /* [제목, matchJob 이 내야 할 답, hospVerdict 가 내야 할 갈래] */
  ['물리치료사 채용 공고', '물리치료사', '담음'],
  ['작업치료사 모집', '작업치료사', '담음'],
  ['<제26-8회>직원채용 공고(조리원, 시설미화원, 작업치료사, 물리치료사 및 방사선사)', '공통', '담음'],

  /* ↓ 이 셋이 이 파일이 생긴 까닭입니다. 확정이 아니고, 버림도 아닙니다 */
  ['<제26-9회>직원채용 공고(조리사, 시설미화원, 재활치료업무보조, 방사선사)', '', '보류'],
  ['제26-10회 직원채용 공고(재활치료업무보조,간호업무보조_장애인 제한채용)', '', '보류'],
  ['경기도의료원 안성병원 360도 통합돌봄도시 간호사(재활치료실/수탁사업)채용 재공고', '', '보류'],

  /* 「재활치료사」 라는 자격은 없습니다. 그래도 보류로 남겨 사람이 봅니다 */
  ['재활치료사 채용 공고', '', '보류'],

  /* 남의 직군은 그대로 버립니다 */
  ['간호사 채용 공고', '', '버림'],
  /* 「언어재활사」 는 **보류**입니다. 버림이 아닙니다 —
     `HS_BROAD_RE` 의 `재활` 에 걸려 「통합 공고일 수 있다」 로 봅니다.
     이 고침과는 상관없는 예전 동작입니다 (「언어재활사」 에는 「재활치료」 가 없어
     확정 낱말과 무관). 보류함이 한 칸 늘 뿐 공고를 잃지 않으므로 그대로 둡니다. */
  ['언어재활사 채용 공고', '', '버림'],
];

let 틀림 = 0;
console.log('── matchJob · hospVerdict ──');
for (const [제목, 바란직군, 바란갈래] of 칸) {
  const 직군 = matchJob(제목) || '';
  const 판정 = hospVerdict(제목, '');
  const 갈래 = 판정.split('(')[0];
  const ok = 직군 === 바란직군 && 갈래 === 바란갈래;
  if (!ok) 틀림++;
  console.log((ok ? '○ ' : '✗ ') + 제목.slice(0, 46).padEnd(48)
    + '직군 ' + (직군 || '(없음)').padEnd(7) + ' → ' + 판정
    + (ok ? '' : '   ← 바란 것: 직군 ' + (바란직군 || '(없음)') + ' · ' + 바란갈래));
}

/* gas 와 sort-rule 의 확정 낱말이 같아야 합니다 — 한쪽만 고치면 또 어긋납니다 */
console.log('\n── gas ↔ sort-rule 확정 낱말 ──');
const gas확정 = ['작업치료', '물리치료'].filter((w) => matchJob(w + '사 채용'));
const 같나 = [...확정단어].sort().join('·') === [...gas확정].sort().join('·')
  && !matchJob('재활치료 담당 채용');
console.log((같나 ? '○ ' : '✗ ') + 'sort-rule 확정단어 [' + 확정단어.join(', ') + ']'
  + ' · gas 에서 「재활치료」 → ' + (matchJob('재활치료 담당 채용') || '(없음)'));
if (!같나) 틀림++;

/* sort-rule 도 같은 답을 내는지 — 여기까지 맞아야 두 길이 같습니다 */
console.log('\n── sort-rule ──');
for (const 제목 of ['<제26-9회>직원채용 공고(조리사, 시설미화원, 재활치료업무보조, 방사선사)',
  '<제26-8회>직원채용 공고(조리원, 시설미화원, 작업치료사, 물리치료사 및 방사선사)']) {
  const r = sortJob(제목, '', null);
  const 바람 = 제목.includes('작업치료사') ? '회원목록' : '보류함';
  const ok = r.갈래 === 바람;
  if (!ok) 틀림++;
  console.log((ok ? '○ ' : '✗ ') + 제목.slice(0, 46).padEnd(48) + r.갈래 + ' · ' + r.왜.slice(0, 50));
}

console.log(틀림 ? '\n' + 틀림 + '칸 틀립니다' : '\n다 맞습니다');
process.exit(틀림 ? 1 : 0);
