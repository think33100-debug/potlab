/* 한글 파일(.hwp · .hwpx) 에서 글자 뽑는 자리 (2026-09-26).
 *
 * 수집기는 **여기만** 부릅니다. 어느 방법으로 읽는지는 몰라도 됩니다.
 * `tools/ocr/` 과 같은 모양입니다.
 *
 * 나중에 정식 파서로 바꾸려면 —
 *   ① 같은 모양의 파일을 하나 만들고
 *        export const 이름표
 *        export const 이꼴인가 = (buf) => …
 *        export function 글자(buf) → { 글, 어떻게 }
 *   ② 아래 목록에서 앞자리에 넣습니다
 * 수집기는 한 줄도 안 고칩니다.
 *
 * **못 읽으면 던지지 않고 { 글: '', 왜 } 를 돌려줍니다.** 부르는 쪽이 보류함으로 보냅니다.
 */
import * as ole from './ole.mjs';
import * as hwpx from './hwpx.mjs';

const 후보 = [hwpx, ole];

/* 맨손 방법이라 「읽었다」 를 믿으면 안 됩니다. 확인한 4건은 2,234~4,588자였습니다.
   이보다 한참 적으면 못 읽은 것으로 봅니다 — 반쯤 깨진 글로 직군을 가리면 더 나쁩니다. */
export const 최소한글 = 100;

const 머리 = (buf) => [...buf.subarray(0, 8)].map((x) => x.toString(16).padStart(2, '0')).join(' ');

/** 알맹이 → { 글, 왜, 어떻게, 한글 }. 던지지 않습니다.
 *  글이 비어 있으면 `왜` 에 이유가 들어 있습니다. */
export function hwp글자(buf, 이름) {
  const nm = String(이름 || '(이름 없음)');
  if (!buf || !buf.length) return { 글: '', 왜: nm + ' — 알맹이가 비었습니다', 어떻게: '', 한글: 0 };

  const 꼴 = 후보.find((p) => p.이꼴인가(buf));
  if (!꼴) {
    /* 파일이 아니라 **안내 글**이 오는 일이 많습니다 — 429 「다운로드 요청이 많습니다」,
       로그인 화면, 오류 쪽. 앞 200자를 그대로 붙여야 무슨 일인지 압니다 (CLAUDE.md 2번) */
    const 글꼴 = buf.length < 20000 ? buf.subarray(0, 200).toString('utf8').replace(/\s+/g, ' ').trim() : '';
    const 보임 = 글꼴 && !/�/.test(글꼴.slice(0, 40)) ? ' · 받은 것 「' + 글꼴 + '」' : '';
    return { 글: '', 한글: 0, 어떻게: '',
      왜: nm + ' — 한글 파일이 아닙니다 (' + buf.length + '바이트 · 앞 8바이트 ' + 머리(buf) + ')' + 보임 };
  }

  let r;
  try { r = 꼴.글자(buf); }
  catch (e) { return { 글: '', 왜: nm + ' — ' + 꼴.이름표 + ' 읽다 멈춤 · ' + String(e && e.message || e), 어떻게: '', 한글: 0 }; }

  const 글 = String(r.글 || '');
  const 한글 = (글.match(/[가-힣]/g) || []).length;
  if (한글 < 최소한글) {
    return { 글: '', 한글, 어떻게: r.어떻게 || '',
      왜: nm + ' — ' + 꼴.이름표 + ' 로 한글이 ' + 한글 + '자밖에 안 나왔습니다'
        + ' (' + 최소한글 + '자 미만은 못 읽은 것으로 봅니다'
        + (r.어떻게 ? ' · ' + r.어떻게 : '') + ')'
        + (글 ? ' · 나온 것 앞 80자 「' + 글.slice(0, 80) + '」' : '') };
  }
  return { 글, 왜: '', 어떻게: 꼴.이름표 + ' · ' + (r.어떻게 || ''), 한글 };
}

/** 이름이 한글 파일인가 */
export const 한글파일인가 = (이름) => /\.hwpx?$/i.test(String(이름 || ''));
