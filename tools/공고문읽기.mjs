/* ── 접수마감 충돌 고르기 (2026-10-21 세중님 결정) ───────────────
 *
 * 쪽(또는 목록 API)이 준 날짜와 첨부 공고문이 준 날짜가 **다를 때** 어느 것을 믿나.
 * 실제로 본 꼴 — 제주대병원(305467) 쪽은 09-29(접수 **시작**)를 주고, 첨부 일정
 * 표에는 「온라인 지원서 접수 | 2026. 09. 29.(화) ~ 2026. 10. 06.(화) 12:00」 로
 * **마감 10-06** 이 적혀 있습니다. 쪽을 그대로 믿으면 마감일을 **일주일 이르게**
 * 잡아 공고가 먼저 내려갑니다.
 *
 *   ⓐ 쪽 이름표가 「시작·게시」 이거나 **없고**, 첨부에 마감이 명시 → **첨부**
 *   ⓑ 둘 다 「마감」 이름표인데 날짜가 다름 → **비우고 보류** (두 값을 적어서)
 *   ⓒ 그밖 → 쪽 (지금 꼴 그대로)
 */
export const 시작이름표 = /시\s*작|게\s*시|등\s*록|공고\s*일|접수\s*시작|부\s*터/;
export const 마감이름표 = /마\s*감|기\s*한|까\s*지|종\s*료|접수\s*끝/;

/** @returns { 값, 왜, 보류? , 두값? } */
export function 마감고르기({ 쪽값 = null, 쪽근거 = '', 첨값 = null, 첨근거 = '' } = {}) {
  if (!쪽값 && !첨값) return { 값: null, 왜: '둘 다 없습니다' };
  if (!첨값) return { 값: 쪽값, 왜: '첨부에 없어 쪽을 씁니다' };
  if (!쪽값) return { 값: 첨값, 왜: '쪽에 없어 첨부를 씁니다' };
  if (쪽값 === 첨값) return { 값: 쪽값, 왜: '쪽과 첨부가 같습니다' };

  const 쪽시작 = 시작이름표.test(String(쪽근거));
  const 쪽마감 = 마감이름표.test(String(쪽근거));
  const 첨마감 = 마감이름표.test(String(첨근거));

  /* ⓐ 쪽이 시작·게시이거나 이름표가 없고, 첨부가 마감이면 첨부 */
  if ((쪽시작 || !쪽마감) && 첨마감) {
    return { 값: 첨값,
      왜: '쪽 날짜는 ' + (쪽시작 ? '시작·게시' : '이름표 없음') + '(' + 쪽값
        + ') · 첨부에 마감이 적혀 있어 첨부를 씁니다 — ' + String(첨근거).slice(0, 70) };
  }
  /* ⓑ 둘 다 마감인데 다름 → 비우고 보류 */
  if (쪽마감 && 첨마감) {
    return { 값: null, 보류: true, 두값: { 쪽: 쪽값, 첨부: 첨값 },
      왜: '쪽과 첨부가 **둘 다 마감**이라는데 날짜가 다릅니다 — 쪽 ' + 쪽값
        + ' · 첨부 ' + 첨값 + ' → 값을 넣지 않고 보류합니다' };
  }
  /* ⓒ 그밖 */
  return { 값: 쪽값, 왜: '쪽을 씁니다 (첨부 이름표가 마감이 아닙니다)' };
}

