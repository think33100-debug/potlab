export function 자격요약(글조각, 최대 = 300) {
  const 토막 = String(글조각 || '')
    /* 표 뼈대·불릿·번호를 **토막 경계**로 봅니다 */
    .split(/\r?\n|<br\s*\/?>|[|]|•|●|○|◦|❍|▪|◇|☐|※|【|】|\[|\]|①|②|③|④|⑤|⑥|⑦|⑧|⑨|⑩|(?:^|\s)-\s|(?:^|\s)·\s|(?:^|\s)∘\s/)
    .map((t) => String(t).replace(/\s+/g, ' ').trim())
    .filter(Boolean);
  const 고른것 = [];
  for (let t of 토막) {
    t = t.replace(자격라벨, '')
      .replace(/^[\s:：,.·∘◦○❍●▪▸▶◇□☐*\-–—]+/, '')
      .replace(/[\s:：,]+$/, '').trim();
    if (t.length < 4 || t.length > 120) continue;
    if (!자격고를말.test(t)) continue;
    if (자격버릴말.test(t)) continue;
    /* 「없음」·「-」 같은 빈 칸 값은 버립니다 (표의 옆 칸) */
    if (/^(?:없음|해당\s*없음|무관|-|–)$/.test(t)) continue;
    /* ★ 2026-10-21 — **라벨만 든 토막**은 버립니다 — 「우대사항」·「필수사항」 처럼
       내용 없이 머리말만 남은 것입니다 (HS996159196 이 그 한 토막 때문에
       정답지와 글자가 어긋났습니다) */
    if (/^(?:필수|우대|공통|자격)\s*(?:사항|자격|조건|요건)?$/.test(t)) continue;
    /* ★ 2026-10-22 세중님 1번 — **라벨·머리말·번호를 뗍니다** (회원 화면 흠) */
    if (자격이름표만.test(t)) continue;          /* 「학력 및 자격조건」 처럼 이름표만 */
    if (자격머리말.test(t)) continue;            /* 「아래의 자격을 모두 충족하는 자」 */
    t = t.replace(자격앞머리, '');              /* 「물리치료사(계약직 6급 상당) :」 */
    t = t.replace(/^\d{1,2}\s*[.)]\s*/, '');   /* 앞의 번호 「1.」·「2)」 */
    t = t.replace(/^[\s:：,.·∘◦○❍●▪▸▶◇□☐*\-–—]+/, '').trim();
    if (t.length < 4 || t.length > 120) continue;
    if (!자격고를말.test(t)) continue;
    if (자격버릴말.test(t)) continue;
    if (!고른것.includes(t)) 고른것.push(t);
  }
  if (!고른것.length) return null;
  /* ★ 차례를 **원문 그대로** 둡니다. 우대를 뒤로 모아 「(우대 — …)」 로 묶는 것은
     제가 바꿔 쓰는 것입니다 — 세중님 ⓐ 규칙이 「지어내거나 바꿔 쓰지 않음
     (원문 낱말 그대로)」 입니다. 묶었을 때 정답지와 어긋났습니다 */
  const 글 = 고른것.join(' · ').replace(/\s{2,}/g, ' ').trim();
  return 글.length >= 4 ? 글.slice(0, 최대) : null;
}

export function 우리직군줄(글) {
  const 우리 = /(물리|작업|도수)\s*치료/;
  /* ★ 2026-10-22 — **옆 글 꼬리표·법령 정의 줄을 먼저 뗍니다.** 본문직군() 은
     이미 떼고 있었는데 여기가 안 떼서 기준이 두 자리였습니다 (지침 6절).
     충주의료원(HS258943039)에서 **이전글 제목**의 「육아휴직 대체자」 를
     우리 직군 줄로 보고 고용형태를 계약직으로 냈습니다 */
  const 고른것 = 이전다음글떼기(String(글 || '')).split('\n').filter((l) => 우리.test(l));
  if (!고른것.length) return null;
  return [...new Set(고른것)].join('\n');
}

