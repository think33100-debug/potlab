/** **남의 줄 고용형태를 빌려 오는 자리인가** (2026-10-22 세중님 3번 ⓒ)
 *
 *  줄마다 고용형태가 다른 표에서, **우리 줄의 그 칸에 다른 값이 적혀 있으면**
 *  글 전체로 내려가 남의 줄 값을 집지 않습니다 (강릉의료원 CE80111 —
 *  우리 줄 「보건직 8급」, 남의 줄 「기간제」 셋. 정답은 정규직입니다).
 *  @returns 빌리는 자리면 { 칸, 우리칸, 남의값 } · 아니면 null */
export function 남의줄빌리나(글) {
  const 우리인가 = (c) => Object.values(우리직군).some((re) => re.test(String(c || '')));
  /** **고용형태만 적힌 칸**인가 — 「기간제」·「무기계약직」 처럼 짧아야 합니다
   *  (「[채용사유] 육아휴직 대체 인력 …」 같은 설명 칸은 아닙니다) */
  const 고용형태칸인가 = (c) => {
    const t = String(c == null ? '' : c).trim();
    if (!t || t.length > 12) return false;
    const v = 고용형태판정('', t);
    return !!(v && v.값);
  };
  let 표목록 = [];
  try { 표목록 = 표들(글) || []; } catch { return null; }
  for (const 표 of 표목록) {
    if (!Array.isArray(표) || 표.length < 3) continue;
    const 우리줄 = 표.find((r) => Array.isArray(r) && 우리인가(r.join(' ')));
    if (!우리줄) continue;
    const 폭 = Math.max(...표.map((r) => (Array.isArray(r) ? r.length : 0)));
    for (let j = 0; j < 폭; j++) {
      /* ㉡ 같은 칸에 고용형태만 적힌 남의 줄이 둘 이상 */
      const 남 = 표.filter((r) => r !== 우리줄 && Array.isArray(r)
        && !우리인가(r.join(' ')) && 고용형태칸인가(r[j]));
      if (남.length < 2) continue;
      /* ㉢ 우리 줄의 그 칸이 비어 있지 않고 고용형태가 아니다 */
      const 우리칸 = String(우리줄[j] == null ? '' : 우리줄[j]).trim();
      if (!우리칸 || 고용형태칸인가(우리칸)) continue;
      return { 칸: j, 우리칸, 남의값: 고용형태판정('', String(남[0][j])).값 };
    }
  }
  return null;
}

