/* ── 쪼개진 글자를 되붙입니다 (2026-10-19) ─────────────────────
 *
 * HWP·PDF 에서 글을 뽑으면 **한 글자마다 공백**이 끼거나(자간 맞춤),
 * 표가 **세로쓰기**라 글자가 줄마다 하나씩 떨어져 나옵니다.
 *
 *   알리오 aplyQlfcCn   「① [ 참 고 2 ] 자 격 요 건 의 특 수 교 사 , 물 리 치 료 사」
 *   중앙보훈 10월 PDF   「기 / 간 / 제 / 보 / 건 / 직」 (줄마다 한 글자)
 *
 * 그대로 두면 회원 화면에 저렇게 보이고, `matchJob()`·`우리직군줄()` 도
 * 「물리치료사」를 못 찾습니다.
 *
 * ★ **함부로 붙이지 않습니다.** 멀쩡한 글의 띄어쓰기를 지우면 더 나쁩니다.
 *   그래서 「한 글자 토막이 **대부분**일 때만」 붙입니다 — 그 글은 이미
 *   사람이 읽을 수 없는 꼴입니다.
 */
export function 자간풀기(글) {
  const s = String(글 ?? '');
  if (!s.trim()) return s;
  return s.split('\n').map((줄) => {
    const 토막 = 줄.trim().split(/\s+/).filter(Boolean);
    if (토막.length < 6) return 줄;                  /* 짧은 줄은 안 건드립니다 */
    const 한글자 = 토막.filter((t) => [...t].length === 1).length;
    if (한글자 / 토막.length < 0.6) return 줄;        /* 자간 꼴이 아닙니다 */
    /* 한 글자 토막끼리만 붙입니다 — 두 글자 이상 토막 앞뒤 공백은 남깁니다.
       ★ **앞 토막이 한 글자였나**를 따로 들고 갑니다. 붙여 놓은 토막의
         길이를 보면 두 글자에서 멈춥니다 (2026-10-19 에 그렇게 틀렸습니다) */
    const 낸것 = [];
    let 앞홀 = false;
    for (const t of 토막) {
      const 홀 = [...t].length === 1;
      if (홀 && 앞홀) 낸것[낸것.length - 1] += t;
      else 낸것.push(t);
      앞홀 = 홀;
    }
    return 낸것.join(' ');
  }).join('\n');
}

/** 세로쓰기 표 — 줄마다 글자 하나씩 떨어진 토막을 한 줄로 모읍니다 */
export function 세로쓰기풀기(글) {
  const 줄들 = String(글 ?? '').split('\n');
  const 낸것 = [];
  let 모음 = [];
  const 쏟기 = () => {
    if (모음.length >= 3) 낸것.push(모음.join(''));     /* 세 글자 이상이어야 말이 됩니다 */
    else 낸것.push(...모음);
    모음 = [];
  };
  for (const 줄 of 줄들) {
    const t = 줄.trim();
    if ([...t].length === 1 && /[가-힣A-Za-z0-9]/.test(t)) 모음.push(t);
    else { 쏟기(); 낸것.push(줄); }
  }
  쏟기();
  return 낸것.join('\n');
}

