/* 첨부 공고문에서 직군을 찾되 **모집 부분에 있는 것만** 인정합니다 (2026-09-30).
 *
 *   import { 첨부직군 } from './첨부직군.mjs';
 *   const r = 첨부직군(공고문글자);
 *   //  { 직군:'물리치료사', 어디:'모집', 줄:'…', 낱말:'물리치료사' }
 *   //  { 직군:'',          어디:'가산점', 줄:'…' }      ← 인정 안 함
 *   //  { 직군:'',          어디:'모름',  후보:'물리치료사' } ← 사람이 봐야 함
 *
 * ── 왜 만드나 ────────────────────────────────────────────────
 * 부산교도소 「한시임기제공무원(8호, 간호직)」 공고가 물리치료사로 잡혔습니다.
 * 첨부(28,911자)를 열어 보니 여기 있었습니다 —
 *
 *   "… 임상병리사, 보건의료정보관리사(구 의무기록사), 물리치료사  C급
 *      보건교육사 3급, 임상심리사 2급, 응급구조사 2급  다. 정보화 관련 자격증 …"
 *
 * **채용 직종이 아니라 가산점 자격증 목록**이었습니다.
 *
 * 처음에는 「제목에 직군이 없으면 첨부만 보고는 안 올린다」 로 막았는데,
 * 세중님이 그건 너무 넓다고 하셨습니다 — 공공기관 공고는 제목이 「직원 채용」
 * 뿐이고 첨부에만 직군이 있는 경우가 많아, 그러면 보류함이 넘치고 회원 화면에
 * 늦게 뜹니다. 첨부 판정은 그대로 쓰되 **어느 부분에 있느냐**로 좁힙니다.
 *
 * ── 어떻게 가르나 ────────────────────────────────────────────
 * 걸린 낱말에서 **뒤로 거슬러 올라가** 가장 가까운 구간 머리말을 찾습니다.
 *   모집 쪽이 가까우면   → 인정
 *   가산점 쪽이 가까우면 → 인정 안 함
 *   둘 다 멀면(600자 밖) → 모름. 보류함으로 보내 사람이 봅니다
 *
 * 같은 줄에 머리말이 있으면 그것이 이깁니다 (표 한 칸에 둘 다 있는 경우).
 */
import { matchJob } from './gas-rules.mjs';

/* 모집을 말하는 머리말 — 이 뒤에 나오는 직군은 진짜 뽑는 자리입니다 */
export const 모집말 = [
  '채용분야', '모집분야', '모집직종', '채용직종', '채용직렬', '모집직렬',
  '채용인원', '모집인원', '선발예정인원', '채용예정인원', '선발인원', '채용예정',
  '모집구분', '채용구분', '직종', '직군', '직렬', '모집개요', '채용개요',
  '채용직급', '임용예정직', '근무예정', '담당업무', '직무내용',
];

/* 가산점·우대를 말하는 머리말 — 여기 나오는 직군은 자격증 목록일 뿐입니다 */
export const 가산말 = [
  '가산점', '가점', '우대사항', '우대조건', '우대자격', '우대', '참고사항',
  '자격증', '소지자', '관련자격', '관련 자격', '취득', '면허 소지',
  '가산비율', '가산특전', '자격요건 외', '기타사항',
];

/** 글에서 낱말이 나오는 자리를 모두 (겹치지 않게) */
function 자리들(글, 낱말) {
  const out = [];
  let i = 글.indexOf(낱말);
  while (i > -1) { out.push(i); i = 글.indexOf(낱말, i + 낱말.length); }
  return out;
}

/** 그 자리가 속한 줄 */
function 그줄(글, i) {
  const a = 글.lastIndexOf('\n', i) + 1;
  let b = 글.indexOf('\n', i);
  if (b < 0) b = 글.length;
  return 글.slice(a, b).replace(/\s+/g, ' ').trim();
}

/** 뒤로 거슬러 가장 가까운 머리말이 어느 쪽인지 */
function 어느구간(글, i, 창 = 600) {
  const 줄 = 그줄(글, i);
  /* ① 같은 줄에 있으면 그것이 이깁니다 (표 한 칸) */
  const 줄모집 = 모집말.some((w) => 줄.includes(w));
  const 줄가산 = 가산말.some((w) => 줄.includes(w));
  if (줄모집 && !줄가산) return { 어디: '모집', 까닭: '같은 줄에 모집 머리말' };
  if (줄가산 && !줄모집) return { 어디: '가산점', 까닭: '같은 줄에 가산점 머리말' };

  /* ② 뒤로 창 만큼 거슬러 올라가 더 가까운 쪽 */
  const 앞 = 글.slice(Math.max(0, i - 창), i);
  const 가까운것 = (말들) => {
    let best = -1;
    for (const w of 말들) { const at = 앞.lastIndexOf(w); if (at > best) best = at; }
    return best;                       // 클수록 가깝습니다 (끝에 붙어 있을수록)
  };
  const m = 가까운것(모집말);
  const g = 가까운것(가산말);
  if (m < 0 && g < 0) return { 어디: '모름', 까닭: '가까이에 머리말이 없습니다' };
  if (m > g) return { 어디: '모집', 까닭: '앞쪽 ' + (앞.length - m) + '자에 모집 머리말' };
  if (g > m) return { 어디: '가산점', 까닭: '앞쪽 ' + (앞.length - g) + '자에 가산점 머리말' };
  return { 어디: '모름', 까닭: '두 머리말이 같은 자리' };
}

/**
 * 첨부 글에서 직군을 가립니다.
 * @param {string} 글 공고문 글자
 * @returns {{직군:string, 어디:string, 줄:string, 까닭:string, 낱말:string}}
 */
export function 첨부직군(글) {
  const t = String(글 || '');
  if (!t.trim()) return { 직군: '', 어디: '없음', 줄: '', 까닭: '글이 비었습니다', 낱말: '' };

  /* 어떤 낱말이 우리 직군으로 걸리는지는 **공통 규칙**이 정합니다.
     여기서 낱말 목록을 새로 만들지 않습니다 (규칙은 한 벌) */
  const 후보낱말 = ['물리치료사', '작업치료사', '물리치료', '작업치료', '치료사'];

  const 본것 = [];
  for (const w of 후보낱말) {
    for (const i of 자리들(t, w)) {
      const 줄 = 그줄(t, i);
      const j = matchJob(줄) || matchJob(w);
      if (!j) continue;
      본것.push({ 낱말: w, i, 줄, 직군: j, ...어느구간(t, i) });
    }
  }
  if (!본것.length) return { 직군: '', 어디: '없음', 줄: '', 까닭: '우리 직군 낱말이 없습니다', 낱말: '' };

  /* 모집 > 모름 > 가산점 순으로 봅니다 — 하나라도 모집이면 진짜 뽑는 자리입니다 */
  const 모집 = 본것.find((x) => x.어디 === '모집');
  if (모집) return { 직군: 모집.직군, 어디: '모집', 줄: 모집.줄, 까닭: 모집.까닭, 낱말: 모집.낱말 };

  const 모름 = 본것.find((x) => x.어디 === '모름');
  if (모름) return { 직군: '', 어디: '모름', 줄: 모름.줄, 까닭: 모름.까닭, 낱말: 모름.낱말, 후보: 모름.직군 };

  const 가산 = 본것[0];
  return { 직군: '', 어디: '가산점', 줄: 가산.줄, 까닭: 가산.까닭, 낱말: 가산.낱말, 후보: 가산.직군 };
}

