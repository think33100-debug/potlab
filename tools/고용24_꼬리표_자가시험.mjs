/* 고용24 꼬리표 가르기 자가시험 — 2026-10-05.
 *  열쇠도 그물도 안 씁니다. node tools/고용24_꼬리표_자가시험.mjs
 *
 *  시험에 쓰는 값은 전부 **DB 에 실제로 담긴 꼬리표**거나
 *  응답 원문에서 본 값입니다. 지어낸 것이 없습니다. */
import { 꼬리표가르기, 경력조건, 시도이름, 고용형태낱말 } from './hosp/jobflex.mjs';

let 참 = 0, 거짓 = 0;
const 봐 = (이름, 된것, 바란것) => {
  const ok = JSON.stringify(된것) === JSON.stringify(바란것);
  console.log((ok ? '  ○ ' : '  ★ ') + 이름
    + (ok ? '' : '\n      된것 ' + JSON.stringify(된것)
              + '\n      바란것 ' + JSON.stringify(바란것)));
  ok ? 참++ : 거짓++;
};

console.log('꼬리표 가르기');
봐('지역 하나 — 대전 (충남대병원 83건)',
  꼬리표가르기('대전'), { 근무지: '대전', 고용형태: '', 남은꼬리표: '' });
봐('지역 하나 — 세종 (59건)',
  꼬리표가르기('세종'), { 근무지: '세종', 고용형태: '', 남은꼬리표: '' });
봐('고용형태 — 비정규직 (일산병원 9건)',
  꼬리표가르기('비정규직'), { 근무지: '', 고용형태: '비정규직', 남은꼬리표: '' });
봐('고용형태 — 정규직 (성가롤로 4건)',
  꼬리표가르기('정규직'), { 근무지: '', 고용형태: '정규직', 남은꼬리표: '' });
봐('고용형태 — 계약직',
  꼬리표가르기('계약직'), { 근무지: '', 고용형태: '계약직', 남은꼬리표: '' });

console.log('\n★ 지역도 고용형태도 아닌 것 — 근무지에 안 들어가야 합니다');
봐('수시 (국제성모 5건)',
  꼬리표가르기('수시'), { 근무지: '', 고용형태: '', 남은꼬리표: '수시' });
봐('공채 (32건)',
  꼬리표가르기('공채'), { 근무지: '', 고용형태: '', 남은꼬리표: '공채' });
봐('업무지원직 (직렬입니다)',
  꼬리표가르기('업무지원직'), { 근무지: '', 고용형태: '', 남은꼬리표: '업무지원직' });
봐('수련생 (고용형태 낱말에 안 넣었습니다)',
  꼬리표가르기('수련생'), { 근무지: '', 고용형태: '', 남은꼬리표: '수련생' });
봐('보건직 · 간호직 · 서무직 · 의료직 · 교수직',
  꼬리표가르기('보건직').남은꼬리표, '보건직');
봐('산하 병원 이름 — 광명병원',
  꼬리표가르기('광명병원'), { 근무지: '', 고용형태: '', 남은꼬리표: '광명병원' });
봐('산하 병원 이름 — 서울병원',
  꼬리표가르기('서울병원').근무지, '');

console.log('\n여럿이 섞인 것 (DB 에 실제로 있던 값)');
봐('정규직, 무기계약직, 별정직 · 경영기획 · 지원 · 연구 · 개발 · 의료 · 보건',
  꼬리표가르기('정규직, 무기계약직, 별정직 · 경영기획 · 지원 · 연구 · 개발 · 의료 · 보건'),
  { 근무지: '', 고용형태: '',
    남은꼬리표: '정규직, 무기계약직, 별정직 · 경영기획 · 지원 · 연구 · 개발 · 의료 · 보건' });
봐('별정직 · 의료 · 보건',
  꼬리표가르기('별정직 · 의료 · 보건'),
  { 근무지: '', 고용형태: '', 남은꼬리표: '별정직 · 의료 · 보건' });
봐('지역과 고용형태가 같이 오면 갈라집니다',
  꼬리표가르기('대전 · 정규직'), { 근무지: '대전', 고용형태: '정규직', 남은꼬리표: '' });
봐('빈 값', 꼬리표가르기(''), { 근무지: '', 고용형태: '', 남은꼬리표: '' });
봐('null', 꼬리표가르기(null), { 근무지: '', 고용형태: '', 남은꼬리표: '' });

console.log('\n경력 조건 (careerType — 응답 원문에서 본 값만)');
봐('NEW', 경력조건('NEW'), '신입');
봐('CAREER', 경력조건('CAREER'), '경력');
봐('ANY', 경력조건('ANY'), '관계없음');
봐('NEW_CAREER', 경력조건('NEW_CAREER'), '신입/경력');
봐('이미 바뀐 신입/경력', 경력조건('신입/경력'), '신입/경력');
/* ⚠ FIELD_DIFFERENCE 는 응답에서 못 봤습니다. 지어내지 않고 그대로 둡니다 */
봐('모르는 값은 그대로 (지어내지 않습니다)',
  경력조건('FIELD_DIFFERENCE'), 'FIELD_DIFFERENCE');
봐('빈 값', 경력조건(''), '');

console.log('\n목록이 겹치지 않는지');
봐('시도이름과 고용형태낱말이 안 겹침',
  시도이름.filter((s) => 고용형태낱말.includes(s)), []);
봐('전남광주가 들어 있음 (2026-07-01 출범)',
  시도이름.includes('전남광주'), true);

console.log('\n' + (거짓 ? '★ ' + 거짓 + '개 틀렸습니다' : '○ ' + 참 + '개 다 맞았습니다'));
process.exit(거짓 ? 1 : 0);
