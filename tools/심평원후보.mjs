/** 이름키를 만드는 식 — 법인·행정구역 말을 뗀 뒤 그대로 (DB 의 `hira_name_key` 를 씁니다) */
export const 뗄말 = '(의료법인|재단법인|학교법인|사회복지법인|사단법인|주식회사|유한회사'
  + '|의료재단|복지재단|특별시|광역시|특별자치도)';

/** 2층 꼴 낱말 — 이 말이 있고 심평원에 이름이 **없으면** 1층 기관이 아닙니다 */
export const 이층말 = /(요양원|요양센터|방문요양|재가|주간보호|데이케어|노인복지|실버|그룹홈|케어|복지회|복지법인|주식회사|유한회사|\(주\)|\(유\)|협동조합|어린이집)/;
/** 1층 꼴 낱말 — 하나라도 있으면 **자동으로 빼지 않습니다** (세중님이 봅니다) */
export const 일층말 = /(병원|의원|한의원|치과|의료원|보건소|보건지소|보건의료원|대학교|시립|도립|군립|공단|공사|진흥원|연구원|센터)/;

/** 그 줄을 세중님 목록에서 빼고 「기관 없음(2층)」으로 둘 것인가
 *  @param 이름   공고의 기관 이름 원문
 *  @param 딱맞는곳  심평원에 **이름키가 딱 같은** 곳 수 (0 이면 붙일 기관이 없습니다) */
export function 이층인가(이름, 딱맞는곳) {
  if (Number(딱맞는곳) > 0) return false;        /* 심평원에 있으면 1층 자리일 수 있습니다 */
  if (일층말.test(String(이름))) return false;    /* 병원·보건소 꼴은 세중님이 봅니다 */
  return 이층말.test(String(이름));
}

/** 후보를 ' ## ' 로 이어 내는 **SQL 조각** — `이름키식` 은 이름키를 내는 SQL 입니다
 *  내는 꼴 — `이름 · 종별 · 시군구 · HIRA:번호`
 *  @param 어떻게  `'품음'`(기본 · 그 글자를 품은 이름) 또는 `'같음'`(이름키가 딱 같은 것만) */
export function 후보SQL(이름키식, 몇 = 4, 어떻게 = '품음') {
  const 재기 = 어떻게 === '같음'
    ? 'h.name_key = (' + 이름키식 + ')'
    : "h.name_key like '%' || (" + 이름키식 + ") || '%'";
  return "coalesce((select string_agg(x.s, ' ## ') from ("
    + "select h.yadm_nm || ' · ' || coalesce(h.cl_cd_nm,'종별 모름') || ' · '"
    + " || coalesce(h.sido_nm,'') || ' ' || coalesce(h.sggu_nm,'')"
    + " || ' · HIRA:' || h.ykiho as s"
    + ' from hira_org h where ' + 재기
    + ' order by h.yadm_nm limit ' + Number(몇) + ') x), ' + "'(심평원에 비슷한 이름이 없습니다)')";
}

/** 그 이름키를 품은 곳이 **몇 곳**인지 내는 SQL 조각 */
export function 후보수SQL(이름키식) {
  return '(select count(*) from hira_org h where h.name_key like '
    + "'%' || (" + 이름키식 + ") || '%')";
}

/** 이름키가 **딱 같은** 곳이 몇 곳인지 (2층 가리기에 씁니다) */
export function 딱맞는곳SQL(이름키식) {
  return '(select count(*) from hira_org h where h.name_key = (' + 이름키식 + '))';
}

/** 문서 칸에 넣을 꼴 — ' ## ' 로 온 것을 `<code>` 줄로 */
export function 후보칸(후보글) {
  return String(후보글 || '').split(' ## ').map((s) => s.trim()).filter(Boolean)
    .map((s) => {
      const m = s.match(/^(.*) · (HIRA:[^ ]+)$/);
      return m ? m[1] + ' <br><code>' + m[2] + '</code>' : s;
    }).join(' <br>') || '(없음)';
}

