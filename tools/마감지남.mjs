  봐('날짜 꼴이 아니면 안 지났다', !지났나('수시', null, 이제));
  봐('어제 23:59 는 지났다', 지났나('2026-10-16', '23:59:00', 이제));
  /* ★ 2026-10-22 에 샌 그 꼴 — 「마감일이 오늘, 시각 없음」은 밤 11:59 까지 삽니다 */
