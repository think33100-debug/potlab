export const 올린날말 = /(작성일|등록일|게시일|올린날|작성날짜|등록날짜|게시날짜|작성|등록)/;
export const 기간말 = /(마감|접수|기간|까지|부터|~|시험|면접|발표|모집일|채용일|일정)/;
export function 날뜻보기(글, 날) {
  const t = String(글 || '');
  const 창들 = [];
  for (let i = t.indexOf(날); i >= 0; i = t.indexOf(날, i + 1)) {
    창들.push(t.slice(Math.max(0, i - 40), i + String(날).length + 40));
    if (창들.length >= 5) break;
  }
  if (!창들.length) return { 갈래: '모름', 앞뒤: '', 왜: '그 날짜를 글에서 못 찾았습니다' };
  const 올 = 창들.some((c) => 올린날말.test(c));
  const 기 = 창들.some((c) => 기간말.test(c));
  const 앞뒤 = 창들[0].replace(/\s+/g, ' ').trim();
  if (올 && !기) return { 갈래: '올린날', 앞뒤, 왜: '앞뒤 40자에 올린날 말이 있습니다' };
  if (기 && !올) return { 갈래: '마감·기간', 앞뒤, 왜: '앞뒤 40자에 마감·기간 말이 있습니다' };
  if (올 && 기) return { 갈래: '모름', 앞뒤, 왜: '올린날 말과 마감·기간 말이 **둘 다** 있습니다' };
  return { 갈래: '모름', 앞뒤, 왜: '앞뒤 40자에 아무 표식도 없습니다' };
}
