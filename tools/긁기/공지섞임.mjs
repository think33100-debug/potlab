export const 기간꼴 = /((?:20)?\d{2})[-.\/](\d{1,2})[-.\/](\d{1,2})\s*(?:~|∼|-{1,2}|–|—|부터)\s*((?:20)?\d{2})[-.\/](\d{1,2})[-.\/](\d{1,2})/;
