/* 단계 이름 읽기 시험 — node tools/alio-group.test.mjs
 *
 * 2026-09-29 에 「면접|구술」 을 괄호로 안 묶어 「면접전형(2차)」 를 못 읽었습니다.
 * 그 자리를 지키는 시험입니다. */
import assert from 'node:assert';
import { 절차읽기, 단계이름표, 지역가리기, 자리이름내기 } from './alio-group.mjs';

const 것 = [
  ['○ 전형방법: 서류전형(1차) → 면접전형 및 직업성격검사(2차) - 1차 * 1~3명: 채용예정인원의 5배수 - 2차: 직업성격검사 및 개별 또는 집단 면접',
    ['서류', '면접']],
  ['1차 서류전형, 2차 필기시험, 3차 면접전형', ['서류', '필기', '면접']],
  ['서류접수->면접진행->신체검사', ['서류', '면접', '신체검사']],
  ['', []],
];
for (const [글, 바람] of 것) {
  const 났 = 절차읽기(글);
  assert.deepStrictEqual(났, 바람, '절차읽기: ' + 글.slice(0, 40) + '\n  났: ' + JSON.stringify(났));
}

/* 단계 수와 안 맞으면 억지로 안 씁니다 */
assert.deepStrictEqual(단계이름표(['1차', '최종'], '1차 서류전형, 2차 필기시험, 3차 면접전형').출처, '기본값');
assert.deepStrictEqual(단계이름표(['1차', '최종'], '○ 전형방법: 서류전형(1차) → 면접전형(2차)'),
  { 이름: ['서류', '면접'], 출처: '공고설명' });
/* 절차가 없으면 세중님이 정한 기본값 */
assert.deepStrictEqual(단계이름표(['1차', '최종'], null), { 이름: ['서류', '최종'], 출처: '기본값' });
assert.deepStrictEqual(단계이름표(['1차', '2차', '최종'], null), { 이름: ['서류', '면접', '최종'], 출처: '기본값' });

/* 지역 — 이름에 있으면 그것, 없고 근무지가 한 곳이면 그것, 여럿이면 모름 */
assert.strictEqual(지역가리기('의료직(물리치료사)_대구병원', '인천,대구'), '대구');
assert.strictEqual(지역가리기('공무직(물리치료사)', '인천'), '인천');
assert.strictEqual(지역가리기('공무직(물리치료사)', '인천,대구'), null);

/* 자리이름 = 직군을 뺀 나머지 */
assert.strictEqual(자리이름내기('공무직(물리치료사)'), '공무직');
assert.strictEqual(자리이름내기('의료직(물리치료사)_인천'), '의료직 인천');

console.log('○ 단계 이름·지역·자리이름 다 맞습니다');

/* ── 고용형태 짝짓기 (2026-09-29) ──
   공고에 고용형태가 여럿일 때 제목이 어느 자리가 어느 것인지 적어 줍니다. */
const { 고용형태가리기, 제목토막 } = await import('./alio-group.mjs');

/* 「기능직(단시간)」 의 단시간은 앞말을 꾸미는 것 — 토막의 머리가 아닙니다 */
assert.deepStrictEqual(
  제목토막('[중앙보훈병원] 기간제 보건직,기능직(단시간) 및 업무지원직 직원 공개채용').map((x) => x.말),
  ['기간제'], '괄호가 바로 닫히는 말은 토막 머리가 아닙니다');

const 것들 = [
  /* [이름, 공고고용형태, 제목, 바라는값] */
  ['물리치료사', '무기계약직,비정규직',
   '[태백병원] 공무직(방사선사) 및 기간제근로자(물리치료사) 채용 공고', '기간제'],
  ['방사선사', '무기계약직,비정규직',
   '[태백병원] 공무직(방사선사) 및 기간제근로자(물리치료사) 채용 공고', '공무직'],
  ['보건직(물리치료사)(1)', '비정규직,청년인턴(체험형)',
   '[광주보훈병원][긴급] 계약직 보건직(물리치료사), 체험형 청년인턴(언어치료사) 공개채용', '계약직'],
  /* 「물리작업치료사」 는 둘 다입니다 */
  ['작업치료사', '무기계약직,비정규직',
   '[인천병원] 공무직(물리작업치료사, 산업위생사) 및 기간제근로자(사무원) 채용 공고', '공무직'],
  /* 「보건직」 이 두 토막에 다 나오면 — 어느 쪽인지 모릅니다. 붙이지 않습니다 */
  ['보건직(물리치료사)', '비정규직,정규직',
   '[대전보훈병원] 정규직(기능직,보건직), 계약직(보건직)직원 공개채용', null],
  /* 제목에 고용형태 말이 아예 없으면 붙이지 않습니다 */
  ['보건직(물리치료사) 휴직대체', '무기계약직,비정규직',
   '[광주보훈병원] 보건직(물리치료사) 휴직대체 및 업무지원직(급식) 공개채용', null],
  /* 공고 고용형태가 한 가지면 그대로 */
  ['물리치료사', '정규직', '아무 제목', '정규직'],
  /* 묶음 이름에 적혀 있으면 그것이 먼저 */
  ['공무직(물리치료사)', '무기계약직,비정규직', '아무 제목', '공무직'],
];
for (const [이름, 공고, 제목, 바람] of 것들) {
  const 났 = 고용형태가리기(이름, 공고, 제목).값;
  assert.strictEqual(났, 바람,
    '고용형태: 「' + 이름 + '」 · ' + 제목.slice(0, 40) + '\n  났: ' + 났 + ' / 바람: ' + 바람);
}
console.log('○ 고용형태 짝짓기도 다 맞습니다');
