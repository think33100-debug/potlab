/* 단계 이름 읽기 시험 — node tools/alio-group.test.mjs
 *
 * 2026-09-29 에 「면접|구술」 을 괄호로 안 묶어 「면접전형(2차)」 를 못 읽었습니다.
 * 그 자리를 지키는 시험입니다. */
import assert from 'node:assert';
import { 절차읽기, 단계이름표, 지역가리기, 자리이름내기 } from './alio-group.mjs';

const 것 = [
  ['○ 전형방법: 서류전형(1차) → 면접전형 및 직업성격검사(2차) - 1차 * 1~3명: 채용예정인원의 5배수 - 2차: 직업성격검사 및 개별 또는 집단 면접',
    ['서류', '면접']],
  ['1차 서류전형, 2차 필기시험, 3차 면접전형', ['서류', '필기', '면접']],
  ['서류접수->면접진행->신체검사', ['서류', '면접', '신체검사']],
  ['', []],
];
for (const [글, 바람] of 것) {
  const 났 = 절차읽기(글);
  assert.deepStrictEqual(났, 바람, '절차읽기: ' + 글.slice(0, 40) + '\n  났: ' + JSON.stringify(났));
}

/* 단계 수와 안 맞으면 억지로 안 씁니다 */
assert.deepStrictEqual(단계이름표(['1차', '최종'], '1차 서류전형, 2차 필기시험, 3차 면접전형').출처, '기본값');
assert.deepStrictEqual(단계이름표(['1차', '최종'], '○ 전형방법: 서류전형(1차) → 면접전형(2차)'),
  { 이름: ['서류', '면접'], 출처: '공고설명' });
/* 절차가 없으면 세중님이 정한 기본값 */
assert.deepStrictEqual(단계이름표(['1차', '최종'], null), { 이름: ['서류', '최종'], 출처: '기본값' });
assert.deepStrictEqual(단계이름표(['1차', '2차', '최종'], null), { 이름: ['서류', '면접', '최종'], 출처: '기본값' });

/* 지역 — 이름에 있으면 그것, 없고 근무지가 한 곳이면 그것, 여럿이면 모름 */
assert.strictEqual(지역가리기('의료직(물리치료사)_대구병원', '인천,대구'), '대구');
assert.strictEqual(지역가리기('공무직(물리치료사)', '인천'), '인천');
assert.strictEqual(지역가리기('공무직(물리치료사)', '인천,대구'), null);

/* 자리이름 = 직군을 뺀 나머지 */
assert.strictEqual(자리이름내기('공무직(물리치료사)'), '공무직');
assert.strictEqual(자리이름내기('의료직(물리치료사)_인천'), '의료직 인천');

console.log('○ 단계 이름·지역·자리이름 다 맞습니다');
