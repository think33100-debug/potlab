/** **표 칸 이름** 한 줄 — 「모집 부서」·「모집 직종」·「지원 자격」·「비고」 …
 *  공고문읽기.mjs 도 이것을 씁니다 (지원자격 뽑기에서 칸 이름 줄 건너뛰기 · 2026-11-19 서울아산) */
export const 표머리말 = /^(?:모집|채용|지원|응시|근무|접수|고용|필수|우대|담당|주요|전형)?\s*(?:부서|직종|분야|부문|자격|조건|인원|형태|기간|요건|사항|직무|업무|직급|직렬|장소|지역|시간|급여|보수|단계|절차|방법|내용)$|^(?:비\s*고|구\s*분|연\s*번|순\s*번)$/;

/** 줄마다 표 칸 이름뿐인가 (「모집 부서 / 모집 직종 / 지원 자격」) */
export function 칸이름만인가(글) {
  const 줄들 = String(글 || '').split(/\n|\s{2,}|\s\/\s/).map((x) => x.replace(/\s+/g, ' ').trim()).filter(Boolean);
  return 줄들.length >= 2 && 줄들.every((x) => 표머리말.test(x));
}

/* 값이 **다른 칸의 이름**으로 시작하면 그 칸 값이 아닙니다 (삼성서울 「응시자격 → 근무지역 : …」) */
const 남의칸머리 = {
  지원자격: /^\s*(?:근무\s*(?:지|지역|장소|부서|조건|시간|형태)|보수|급여|연봉|임금|전형|접수|제출\s*서류|모집\s*(?:인원|분야|부문)|채용\s*(?:인원|형태)|고용\s*형태|문의)\s*[:：]/,
  근무지: /^\s*(?:모집\s*인원|채용\s*인원|접수|전형|제출\s*서류|보수|급여|지원\s*자격|응시\s*자격|자격\s*요건)\s*[:：]?/,
  예상연봉: /^\s*(?:모집\s*인원|접수|전형|제출\s*서류|근무\s*(?:지|지역|장소)|지원\s*자격|응시\s*자격)\s*[:：]?/,
};

/* 한 칸 값에 **다른 꼭지가 통째로** 들어온 꼴 — 접수·전형·제출서류 안내 */
const 남의꼭지 = /접수\s*(?:기간|방법|처)\s*[:：]|전형\s*(?:방법|절차|일정)\s*[:：]|제출\s*서류\s*[:：]/;

/** 값 하나를 봅니다 — 걸리면 까닭, 아니면 null */
export function 값까닭(칸, v) {
  if (v == null) return null;
  const t = String(v);
  if (!t.trim()) return null;
  if (칸이름만인가(t)) return '표 칸 이름 줄만 있음';
  const 머리 = 남의칸머리[칸 === '연봉' ? '예상연봉' : 칸];
  if (머리 && 머리.test(t)) return '다른 칸 이름으로 시작함';
  if ((칸 === '근무지' || 칸 === '예상연봉' || 칸 === '연봉') && 남의꼭지.test(t)) return '접수·전형·제출서류 안내가 섞임';
  if (칸 === '근무지' && t.length > 120) return '근무지가 너무 김(' + t.length + '자)';
  if (칸 === '근무기간' && !/\d|까지|정함|기간\s*없|무기/.test(t)) return '근무기간에 숫자·기한이 없음';
  if (/^[\s:：,.·\-–—•○◯※()]+$/.test(t)) return '기호만 있음';
  return null;
}

const 볼칸 = ['지원자격', '근무지', '예상연봉', '연봉', '근무기간'];

/** 줄 하나를 검사해 **그 자리에서** 걸린 칸을 뺍니다. 걸린 것 목록을 돌려줍니다 */
export function 칸검사(줄) {
  const 걸림 = [];
  for (const 자리 of ['뽑은값', 'detail']) {
    const o = 줄 && 줄[자리];
    if (!o || typeof o !== 'object') continue;
    for (const 칸 of 볼칸) {
      if (!(칸 in o)) continue;
      const 까닭 = 값까닭(칸, o[칸]);
      if (!까닭) continue;
      걸림.push({ 칸: 자리 + '.' + 칸, 까닭, 값: String(o[칸]).replace(/\s+/g, ' ').slice(0, 80) });
      delete o[칸];
    }
  }
  /* 모집인원 — 51 이상은 우리 직군 몫이 아닙니다 (공고문읽기 ②-2 와 같은 기준) */
  if (줄 && typeof 줄.headcount === 'number' && 줄.headcount > 50) {
    걸림.push({ 칸: 'headcount', 까닭: '모집인원 50 넘음(우리 직군 몫이 아님)', 값: String(줄.headcount) });
    delete 줄.headcount;
  }
  if (걸림.length && 줄) {
    줄.evidence = { ...(줄.evidence || {}), 검사걸림: 걸림, 검사때: new Date().toISOString() };
  }
  return 걸림;
}

/** 줄들을 모두 검사합니다 — 셈을 찍고 돌려줍니다 */
export function 칸검사들(줄들, 출처 = '', 로그 = console.log) {
  let 걸린줄 = 0, 걸린칸 = 0;
  const 본보기 = [];
  for (const 줄 of (줄들 || [])) {
    const 걸림 = 칸검사(줄);
    if (!걸림.length) continue;
    걸린줄++; 걸린칸 += 걸림.length;
    if (본보기.length < 5) 본보기.push((줄.id || '?') + ' ' + 걸림.map((x) => x.칸 + '(' + x.까닭 + ')').join(', '));
  }
  if (걸린줄 && 로그) {
    로그('  ⚑ 칸 검사 ' + (출처 ? '[' + 출처 + '] ' : '') + '걸린 공고 ' + 걸린줄 + '건 · 칸 ' + 걸린칸
      + '개 — 그 칸만 빼고 담습니다 (evidence.검사걸림)');
    본보기.forEach((x) => 로그('     ' + x));
  }
  return { 걸린줄, 걸린칸 };
}

