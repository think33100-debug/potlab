/** 근무처를 뽑습니다. 못 뽑으면 null — **짐작하지 않습니다.**
 *
 *  ⑤ 는 2026-09-30 에 세중님이 정한 것입니다 —
 *    「의료직(물리치료사)**_인천**」 처럼 지역만 적힌 것을,
 *    **그 기관의 알리오 자료 안에 「인천병원」이 실제로 있을 때만** 붙입니다.
 *    없으면 그대로 둡니다. 「인천 → 인천병원」 을 그냥 짐작하지 않습니다.
 *  @param 있는근무처 그 기관의 자료에서 실제로 나온 근무처 이름들 (Set)
 */
export function 근무처내기(묶음이름, 공고제목, 첨부이름들, 있는근무처) {
  const 찾기 = (s, re) => (String(s || '').match(re) || [])[1] || null;
  const 곧바로 = 찾기(묶음이름, 근무처꼴)
    || 찾기(공고제목, 대괄호꼴)
    || (첨부이름들 || []).map((x) => 찾기(x, 대괄호꼴)).find(Boolean)
    || 찾기(공고제목, 근무처꼴);
  if (곧바로) return { 값: 곧바로, 근거: '이름에 그대로 적혀 있음' };

  /* ⑤ 지역만 적힌 꼬리 — 「_인천」 「_대구」 */
  const 꼬리 = (String(묶음이름).match(/[_\-·]\s*([가-힣]{2,4})\s*$/) || [])[1];
  if (꼬리 && 있는근무처) {
    for (const 끝 of ['병원', '의원', '요양원', '분원']) {
      if (있는근무처.has(꼬리 + 끝)) {
        return { 값: 꼬리 + 끝,
          근거: '이름 끝이 「' + 꼬리 + '」 이고, 이 기관 알리오 자료에 「'
            + 꼬리 + 끝 + '」 이 실제로 있습니다' };
      }
    }
  }
  return { 값: null, 근거: null };
}

