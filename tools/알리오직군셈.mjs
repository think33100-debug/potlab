/* 알리오 전형단계(`steps`) 에서 **우리 직군 인원**을 셉니다 — 한 자리에만 둡니다.
 *
 * 쓰는 곳 — tools/collect-alio.mjs · tools/알리오직군인원.mjs
 * (작업지침 6절 — 같은 기준이 두 곳에 있으면 반드시 어긋납니다)
 *
 * ── 왜 따로 떼나 (2026-10-11) ───────────────────────────────
 * `collect-alio.mjs:285` 의 셈에 **겹쳐 세는 탈**이 있었습니다.
 * `steps` 는 **전형 단계마다 한 줄**이라 같은 직군이 서류·필기·면접으로
 * 두세 번 나옵니다.
 *
 *   보건직(물리치료사)   1차 서류    ┐
 *   보건직(물리치료사)   2차 필기    ├ 같은 자리인데 세 줄
 *   보건직(물리치료사)   3차 면접    ┘   → 3명으로 셌습니다
 *
 * 세종충남대병원 공고가 실제로 「물 3 · 작 3」으로 나왔습니다.
 * **같은 글자는 한 번만 셉니다.**
 */

/** 「의료기술직(물리치료사)」 「일반(작업치료사)-(1)」 「청년인턴직(물리치료사) (2)」 */
export function 직군인원(이름들, 전체인원 = null) {
  const 셈 = { 물리치료사: 0, 작업치료사: 0 };
  const 근거 = [];
  /* ★ 같은 글자는 한 번만 — steps 는 전형 단계마다 한 줄입니다 */
  const 한번씩 = [...new Set(이름들.map((t) => String(t || '').replace(/\s+/g, ' ').trim()).filter(Boolean))];
  /* ★ 2026-11-20 세중님 「수정해」 (근로복지공단 대구병원 307294) — steps 가 「기간제_물리치료사」 **하나뿐**이고
     수가 안 적혀 있으면, 그 단계가 곧 공고 전체입니다. 「한 자리」(1)로 세면 틀립니다 —
     알리오 쪽 「채용인원 2명」 · 공고문 「대구병원 | 기간제 | 물리치료사 | 2명」 인데 1명으로 담겼습니다.
     **단계 이름이 딱 하나**일 때만 공고 전체 인원(recrutNope)을 씁니다. 다른 직군 단계가 하나라도 있으면 전처럼 셉니다
     (경기요양병원 307191 「청년(체험형)인턴_물리치료사 · 청년(체험형)인턴_사무원」 전체 2명 → 물리치료사 1) */
  const 전체 = Number(전체인원);
  const 혼자 = 한번씩.length === 1 && Number.isInteger(전체) && 전체 >= 1 && 전체 <= 50 && 인원뽑기(한번씩[0], null) == null;

  for (const t of 한번씩) {
    const 물 = /물리치료/.test(t);
    const 작 = /작업치료/.test(t);
    if (!물 && !작) continue;
    const n = (혼자 && !(물 && 작)) ? 전체 : 인원뽑기(t);
    if (혼자 && !(물 && 작)) 근거.push(`단계가 하나뿐 → 공고 전체 인원 ${전체}`);
    if (물 && 작) {
      /* 한 줄에 둘 다 — 몇 대 몇인지 알 수 없습니다. 나눠 적지 않고
         둘 다에 올린 뒤 「둘다」로 표시해 사람이 보게 합니다 */
      셈.물리치료사 += n; 셈.작업치료사 += n;
      근거.push(`${t} → 물리·작업 둘 다 ${n}`);
    } else if (물) { 셈.물리치료사 += n; 근거.push(`${t} → 물리치료사 ${n}`); }
    else { 셈.작업치료사 += n; 근거.push(`${t} → 작업치료사 ${n}`); }
  }
  return {
    셈, 근거, 한번씩,
    합: 셈.물리치료사 + 셈.작업치료사,
    둘다: 근거.some((x) => x.includes('둘 다')),
  };
}

/* 인원이 적히는 꼴 — 실제로 본 것만 넣습니다 (지어내지 않습니다)
     「일반(작업치료사)-(1)」   「청년인턴직(물리치료사) (2)」
     「물리치료사(2명)」        「물리치료사 2명」        「물리치료사 : 2」
   아무 수도 없으면 **한 자리**로 봅니다 — 공고에 자리가 있다는 뜻입니다 */
function 인원뽑기(t, 없으면 = 1) {
  const m = t.match(/[-–]\s*\((\d{1,3})\)\s*$/)
    || t.match(/\((\d{1,3})\s*명\)/)
    || t.match(/\((\d{1,3})\)\s*$/)
    || t.match(/(\d{1,3})\s*명/)
    || t.match(/[:：]\s*(\d{1,3})\s*$/);
  return m ? Number(m[1]) : 없으면;
}
