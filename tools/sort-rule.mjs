const 붙이기 = (s) => String(s || '').replace(/\s+/g, '');

/* 괄호 안에 쉼표가 둘 이상 — 직군을 여럿 나열한 통합 공고입니다.
   본문에 물리치료사가 있을 수 있어 버리지 않고 사람이 봅니다. */
export function 여럿나열(제목) {
  const t = String(제목 || '');
  for (const m of t.matchAll(/[(（]([^)）]*)[)）]/g)) {
    if ((m[1].match(/[,，]/g) || []).length >= 2) return m[1];
  }
  return null;
}

/** 제목 하나를 갈라냅니다. { 갈래, 왜, 걸린단어 } */
export function sortJob(제목) {
  const 원래 = 붙이기(제목);

  /* ① 받기 예외를 지웁니다 */
  let 지운것 = 원래;
  const 지운말 = [];
  for (const w of 받기예외) {
    const k = 붙이기(w);
    if (지운것.includes(k)) { 지운말.push(w); 지운것 = 지운것.split(k).join(''); }
  }
  const 메모 = 지운말.length ? `받기 예외 ${지운말.join('·')} 를 빼고 봤습니다` : '';

  /* ② 직군 확정 → 회원 목록 */
  const 확정 = 확정단어.filter((w) => 지운것.includes(붙이기(w)));
  if (확정.length) return { 갈래: '회원목록', 왜: '제목에 직군이 적혀 있음', 걸린단어: 확정, 메모 };

  /* ③ 괄호 안 여럿 나열 → 보류함 (버림보다 먼저) */
  const 나열 = 여럿나열(제목);
  if (나열) return { 갈래: '보류함', 왜: '괄호 안에 직군이 여럿', 걸린단어: [나열.trim()], 메모 };

  /* ④ 보류 보장 단어 → 보류함 */
  const 보장 = 보류보장단어.filter((w) => 지운것.includes(붙이기(w)));
  if (보장.length) return { 갈래: '보류함', 왜: '관련 단어가 있음', 걸린단어: 보장, 메모 };

  /* ⑤ **원래 제목**에 버림 단어 → 쓰레기통 */
  for (const [갈래이름, 말들] of Object.entries(버림단어)) {
    const 걸림 = 말들.filter((w) => 원래.includes(붙이기(w)));
    if (걸림.length) return { 갈래: '쓰레기통', 왜: `버림 단어(${갈래이름})`, 걸린단어: 걸림, 메모 };
  }

  /* ⑥ 아무 단어도 없음 → 보류함 */
  return { 갈래: '보류함', 왜: '아무 단어도 없음', 걸린단어: [], 메모 };
}
