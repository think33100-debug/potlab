/* 5단계가 「첨부에 무슨 직군이 있었나」 를 적을 때 씁니다.
   gas 에서 떼어 온 한 벌입니다 — 여기서 새로 만들지 않습니다 */
import { OTHER_JOBS, OTHER_PROF_RE } from './gas-rules.mjs';

const 붙이기 = (s) => String(s || '').replace(/\s+/g, '');

/* 괄호 안에 쉼표가 둘 이상 — 직군을 여럿 나열한 통합 공고입니다.
   본문에 물리치료사가 있을 수 있어 버리지 않고 사람이 봅니다. */
export function 여럿나열(제목) {
  const t = String(제목 || '');
  for (const m of t.matchAll(/[(（]([^)）]*)[)）]/g)) {
    if ((m[1].match(/[,，]/g) || []).length >= 2) return m[1];
  }
  return null;
}

/** 제목 하나를 갈라냅니다. { 갈래, 왜, 걸린단어 } */
/* 제목과 **직군**으로 갈래를 정합니다 — gas 의 sortJob_(title, job) 과 같습니다.
 *
 * ── 직군 칸이 왜 필요한가 (2026-09-26 에 겪은 것) ────────────
 * 처음에는 제목만 받았습니다. 「이 파일은 제목만 다룹니다(시험용)」 라고
 * 적어 두고 시험에만 썼기 때문입니다.
 * 그런데 새 수집기(collect-alio.mjs)가 `sortJob(title, job)` 으로 부르는 바람에
 * **둘째 인자가 조용히 버려졌습니다.** 그래서 자격요건·본문·첨부에서 직군이
 * 정해진 공고도, 제목에 직군 단어가 없으면 보류함으로 갔습니다 —
 * 강원대학교병원 「2026-45(대체근로자) 채용 공고」(자격요건에 물리치료사)가
 * 그렇게 보류함에 묻혔습니다.
 *
 * gas 와 같게 **직군 칸이 차 있으면 그것이 1번**입니다.
 */
export function sortJob(제목, 직군, 첨부) {
  /* ⓪ 직군이 이미 정해졌으면 회원 목록입니다 (본문·자격·첨부로 정해진 것) */
  if (String(직군 ?? '').trim()) {
    return { 갈래: '회원목록', 단계: 1, 왜: '1단계 · 직군이 정해짐', 걸린단어: [], 메모: '' };
  }
  /* ⓪-2 첨부를 읽었으면 **5단계가 제목보다 셉니다** — 아래 5단계 설명 참고 */
  const 다섯 = 첨부단계(제목, 첨부);
  if (다섯) return 다섯;

  const 원래 = 붙이기(제목);

  /* ① 받기 예외를 지웁니다 */
  let 지운것 = 원래;
  const 지운말 = [];
  for (const w of 받기예외) {
    const k = 붙이기(w);
    if (지운것.includes(k)) { 지운말.push(w); 지운것 = 지운것.split(k).join(''); }
  }
  const 메모 = 지운말.length ? `받기 예외 ${지운말.join('·')} 를 빼고 봤습니다` : '';

  /* ② 직군 확정 → 회원 목록 */
  const 확정 = 확정단어.filter((w) => 지운것.includes(붙이기(w)));
  if (확정.length) return { 갈래: '회원목록', 단계: 1, 왜: '1단계 · 제목에 직군이 적혀 있음', 걸린단어: 확정, 메모 };

  /* ③ 괄호 안 여럿 나열 → 보류함 (버림보다 먼저) */
  const 나열 = 여럿나열(제목);
  if (나열) return { 갈래: '보류함', 단계: 2, 왜: '2단계 · 괄호 안에 직군이 여럿', 걸린단어: [나열.trim()], 메모 };

  /* ④ 보류 보장 단어 → 보류함 */
  const 보장 = 보류보장단어.filter((w) => 지운것.includes(붙이기(w)));
  if (보장.length) return { 갈래: '보류함', 단계: 2, 왜: '2단계 · 관련 단어가 있음', 걸린단어: 보장, 메모 };

  /* ⑤ **원래 제목**에 버림 단어 → 쓰레기통 */
  for (const [갈래이름, 말들] of Object.entries(버림단어)) {
    const 걸림 = 말들.filter((w) => 원래.includes(붙이기(w)));
    if (걸림.length) {
      return { 갈래: '쓰레기통', 단계: 4, 왜: `4단계 · 버림 단어(${갈래이름})`, 걸린단어: 걸림, 메모 };
    }
  }

  /* ⑥ 아무 단어도 없음 → 보류함 */
  return { 갈래: '보류함', 단계: 3, 왜: '3단계 · 아무 단어도 없음', 걸린단어: [], 메모 };
}

/* ═══ 5단계 — 첨부를 읽고 나서 (2026-09-26 · 세중님이 정하신 것) ═══
 *
 * 네 갈래는 **제목만** 봅니다. 그런데 공공기관 공고는 제목이 「의료기술직
 * 채용」 처럼 뭉뚱그려져 있고 진짜 직군은 첨부 공고문에 있습니다.
 * 클린아이 의료 공고 95건은 제목·자격증·직무 어디에서도 갈린 것이 **0건**
 * 이었습니다. 답이 전부 첨부에 있습니다.
 *
 *   첨부 읽음 + 물리/작업치료 있음  → 회원 목록
 *   첨부 읽음 + 우리 직군 없음      → 쓰레기통
 *        **제목에 보류 보장 단어가 있어도 버립니다.**
 *        읽어서 아는 것이, 제목만 보고 「모르겠다」 하는 것보다 셉니다.
 *        대신 **첨부에서 실제로 찾은 직군을 사유에 적습니다** —
 *        「제목: 의료기사 → 첨부: 방사선사·임상병리사」
 *        하나도 못 찾았으면 「첨부 읽음·직군 없음」
 *   첨부 못 읽음                    → 보류함 + 「다음에 다시」
 *        429·다운로드 실패·hwp 실패는 **실패로 세지 않습니다.**
 *        우리가 아직 못 본 것일 뿐입니다.
 *
 * 첨부 = { 읽음: true/false, 글: '…', 왜: '못 읽은 까닭' }
 * 안 넘기면(undefined) 5단계는 아예 안 돕니다 — 네 갈래 그대로입니다.
 */
export function 첨부단계(제목, 첨부) {
  if (!첨부) return null;

  /* 못 읽었으면 보류함. 「모르는 것」 이지 「아닌 것」 이 아닙니다 */
  if (!첨부.읽음) {
    return { 갈래: '보류함', 단계: 5, 다시: true,
      왜: '5단계 · 첨부를 못 읽었습니다 — 다음에 다시 · ' + (첨부.왜 || '까닭 모름'),
      걸린단어: [], 메모: '' };
  }

  const 글 = String(첨부.글 || '');
  /* 첨부에 우리 직군이 있나 — 제목과 같은 잣대(확정단어) */
  const 우리 = 확정단어.filter((w) => 붙이기(글).includes(붙이기(w)));
  if (우리.length) {
    return { 갈래: '회원목록', 단계: 5, 왜: '5단계 · 첨부에 직군이 적혀 있음',
      걸린단어: 우리, 메모: '' };
  }

  /* 우리 직군이 없습니다 → 버립니다. **무엇이 있었는지는 적어 둡니다** */
  const 남의것 = 첨부에서남의직군(글);
  const 제목걸림 = 보류보장단어.filter((w) => 붙이기(제목).includes(붙이기(w)));
  const 왜 = 남의것.length
    ? `5단계 · 제목: ${제목걸림.join('·') || '(직군 말 없음)'} → 첨부: ${남의것.join('·')}`
    : '5단계 · 첨부 읽음·직군 없음';
  return { 갈래: '쓰레기통', 단계: 5, 왜, 걸린단어: 남의것, 메모: 제목걸림.length
    ? `제목의 「${제목걸림.join('·')}」 는 보류 보장 단어지만, 첨부를 읽어 확인했습니다` : '' };
}

/* 첨부 글에서 **남의 직군 이름**을 찾아 적습니다. 관리자가 사유만 보고
   「의료기사인데 왜 버렸지」 를 알 수 있게 하려는 것입니다.
   규칙은 gas 의 OTHER_JOBS·OTHER_PROF_RE 한 벌을 씁니다 — 여기서 새로 안 만듭니다. */
export function 첨부에서남의직군(글) {
  const t = String(글 || '');
  const 찾음 = new Set();
  for (const w of OTHER_JOBS) if (t.includes(w)) 찾음.add(w);
  if (!찾음.size) {
    /* OTHER_JOBS 에 없으면 정규식으로 한 번 더 — 「방사선직」 같은 꼴 */
    const re = new RegExp(OTHER_PROF_RE.source, 'g');
    let m; let n = 0;
    while ((m = re.exec(t)) && n++ < 40) 찾음.add(m[0]);
  }
  /* 많이 나오면 앞 6개만. 사유 칸이 길어지면 아무도 안 읽습니다 */
  return [...찾음].slice(0, 6);
}
