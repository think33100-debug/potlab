/* `homePg` 는 「기관 홈페이지」 칸인데 **아무 글이나 들어옵니다** (2026-10-24).
   메일 주소를 적은 기관이 있었고(`silverhp@naver.com`), 그것이 회원 화면까지
   갔습니다. **주소 꼴만** 담습니다 —
     ○ http://a.or.kr · https://a.co.kr/b · www.mabokgi.com · a.or.kr/recruit
     ✗ 메일(@ 가 든 것) · 전화번호 · 「없음」 · 「2026.10.28」 (글자 TLD 가 없습니다) */
export const 홈페이지손질 = (v) => {
  const t = String(v || '').trim();
  if (!t || t.includes('@')) return '';
  const 집 = t.replace(/^[A-Za-z][A-Za-z0-9+.-]*:\/\//, '').split(/[/?#]/)[0].replace(/:\d+$/, '');
  return /\.[A-Za-z]{2,}$/.test(집) ? t : '';
};

export const 접수방법손질 = (v) => {
  const t = String(v || '');
  let 낸것 = '';
  for (let i = 0; i < t.length; i++) {
    /* 「기타」 뒤에 괄호가 열리면 **괄호 짝을 세어** 닫는 자리까지 건너뜁니다.
       ★ 정규식으로 「다음 쉼표까지」 끊으면 **괄호 안의 「, 이메일」** 에 걸립니다 —
         「고용24,기타(▣전화(010-…), 이메일 등)」 가 그 꼴입니다. 그래서 셉니다 */
    if (t.startsWith('기타', i)) {
      let j = i + 2;
      while (j < t.length && /\s/.test(t[j])) j++;
      if (t[j] === '(' || t[j] === '（') {
        let 깊이 = 0;
        for (; j < t.length; j++) {
          if (t[j] === '(' || t[j] === '（') 깊이++;
          else if (t[j] === ')' || t[j] === '）') { 깊이--; if (깊이 === 0) { j++; break; } }
        }
        낸것 += '기타';
        i = j - 1;
        continue;
      }
    }
    낸것 += t[i];
  }
  return 낸것.replace(/,\s*,/g, ',').replace(/,\s*$/, '').trim();
};
