/* 뺀 곳 (2026-11-18) — 창원한마음병원: 메모가 「기간 두 날짜 · 상시채용은 날짜 하나일 수 있어
   single=deadline 은 보수적으로」 — 날짜 하나가 마감이라는 근거가 아니라 짐작이고, 상시 공고의
   날짜 하나는 시작일일 수 있습니다(안동형). 그래서 그 날짜를 게시일로 봅니다. */

const 점날 = (s) => String(s || '').replace(/-/g, '.');

/**
 * 목록 줄 하나를 받아, 설정이 증명하지 못한 「목록 날짜 = 마감」을 거둡니다.
 * @param r     hospParseHtml 이 낸 줄 { title, url, from, to, posted }
 * @param s     사이트 설정 (name · single)
 * @param 오늘  'YYYY-MM-DD' 또는 'YYYY.MM.DD' (한국 날짜)
 * @returns 바뀌지 않으면 r 그대로 · 바뀌면 새 객체 { ...r, to:'', posted, 목록날짜, 목록날짜뜻 }
 */
export function 목록날짜고르기(r, s, 오늘) {
  if (!r || !s || s.single !== 'deadline') return r;
  /* hospParseHtml 의 「날짜 하나 → 마감」 꼴만 봅니다 (from·posted 가 비고 to 만 참) */
  if (!r.to || r.from || r.posted) return r;
  if (목록마감믿는곳.has(s.name)) return r;
  const d = 점날(r.to);
  const 오늘점 = 점날(오늘);
  const 지난날인가 = /^20\d{2}\.\d{2}\.\d{2}$/.test(d) && 오늘점 && d <= 오늘점;
  return {
    ...r,
    to: '',
    posted: 지난날인가 ? d : '',
    목록날짜: d,
    목록날짜뜻: 지난날인가
      ? '목록 날짜 하나 · 마감 칸이라는 근거 없음 → 게시일로'
      : '목록 날짜 하나 · 마감 칸이라는 근거 없음 · 앞날이라 게시일로도 안 씀',
  };
}
