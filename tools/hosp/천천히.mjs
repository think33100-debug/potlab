/* 천천히 받는 곳 — **하루 두 번만** (세중님 2026-11-09 새벽)
 *
 *   「이렇게 좀 무리하게 긁는 곳은 그냥 하루에 딱 2번만 긁자 —
 *     오전 9시~12시에 랜덤으로 한 번, 오후 1시~6시 사이로 랜덤으로 한 번.」
 *
 * robots.txt 가 막는데도 세중님 결정으로 긁는 곳(현황판/robots예외.csv —
 * 리크루터 채용관 · 울산 중앙병원)에 사이트 설정 `"천천히": true` 를 붙입니다.
 * 수집기(collect-hosp.mjs ①)는 그 곳을 **오늘의 두 창** 안에서 곳마다 정한
 * 시각이 지났고 그 창에서 아직 못 받았을 때만 받습니다.
 *
 * ── 왜 해시인가 ─────────────────────────────────────────────
 * 크론은 하루 여러 바퀴 돕니다. 바퀴마다 진짜 난수를 뽑으면 어느 바퀴도 「지금이
 * 그 시각」이 아니라 아예 안 걸리거나, 거꾸로 두 바퀴가 다 걸립니다. 그래서
 * **날짜 + 기관 이름 + 창 이름의 해시**로 정합니다 — 같은 날 어느 바퀴가 돌아도
 * 같은 시각이 나오고, 날마다·곳마다 다릅니다.
 *
 * ── 시간대 ──────────────────────────────────────────────────
 * 서버가 UTC 일 수 있어 **한국시간으로** 셉니다 — `Date.now() + 9*3600e3` 꼴
 * (collect-nara.mjs:153 · collect-youth.mjs:249 와 같은 꼴). 서버 시간대와 무관합니다.
 *
 * ── 기록 ────────────────────────────────────────────────────
 *   { "<이름>": { "날짜": "2026-11-09", "오전": "09:47", "오후": null } }
 * 파일은 수집기가 `POTJOB_SLOW_STATE || ~/천천히기록.json` 에 둡니다(저장소 밖 ·
 * 수집기멈춤경보의 ~/경보기록.json 과 같은 결). **받기에 성공한 때만** 적습니다.
 * 날짜가 다르면 그 곳 기록은 없는 것으로 봅니다(날이 바뀌면 초기화).
 *
 * 이 파일은 **순수 함수만** 둡니다 — 네트워크·파일 쓰기 0. 자기점검은
 * `node tools/hosp/천천히_자기점검.mjs` 입니다.
 */

const 한국 = 9 * 3600e3;

/* 두 창 — 분 단위 · 끝은 열린 구간(12:00 은 오전 창 밖) */
export const 창들 = [
  { 이름: '오전', 시작: 9 * 60, 끝: 12 * 60 },
  { 이름: '오후', 시작: 13 * 60, 끝: 18 * 60 },
];

/* 한국 날짜 「2026-11-09」 */
export function 한국날짜(지금ms) {
  return new Date(지금ms + 한국).toISOString().slice(0, 10);
}
/* 한국시간 0시부터 몇 분 지났나 */
export function 한국분(지금ms) {
  const d = new Date(지금ms + 한국);
  return d.getUTCHours() * 60 + d.getUTCMinutes();
}
const 두자리 = (n) => ('0' + n).slice(-2);
export const 분을시각으로 = (분) => 두자리(Math.floor(분 / 60)) + ':' + 두자리(분 % 60);
export const 시각을분으로 = (s) => {
  const m = String(s || '').match(/^(\d{1,2}):(\d{2})$/);
  return m ? Number(m[1]) * 60 + Number(m[2]) : null;
};

/* FNV-1a 32비트 — 글자가 조금만 달라도 값이 크게 바뀌어 창 안에서 고르게 퍼집니다.
   공고ID 의 `해시()`(collect-hosp.mjs) 와는 **다른 자리**입니다 — 저쪽은 gas 와 같아야
   하는 번호 규칙이고, 이쪽은 시각을 고르는 데만 씁니다. */
export function 해시32(s) {
  let h = 0x811c9dc5;
  const t = String(s || '');
  for (let i = 0; i < t.length; i++) {
    h ^= t.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/* 오늘 이 곳의 두 시각 — { 날짜, 오전: '09:47', 오후: '15:12' }
   같은 날·같은 이름이면 언제 불러도 같은 값입니다. */
export function 오늘창(이름, 지금ms) {
  const 날짜 = 한국날짜(지금ms);
  const out = { 날짜 };
  for (const 창 of 창들) {
    const 폭 = 창.끝 - 창.시작;
    const 분 = 창.시작 + (해시32(날짜 + '|' + 이름 + '|' + 창.이름) % 폭);
    out[창.이름] = 분을시각으로(분);
  }
  return out;
}

/* 오늘 기록만 — 날짜가 다르면 빈 것으로 */
function 오늘기록(기록, 이름, 날짜) {
  const r = 기록 && 기록[이름];
  return (r && r.날짜 === 날짜) ? r : {};
}

/* 지금 받아야 하나 — null | '오전' | '오후'
   창 안이고 · 정한 시각이 지났고 · 그 창에서 아직 안 받았을 때만 창 이름을 줍니다. */
export function 받을차례(기록, 이름, 지금ms) {
  const t = 오늘창(이름, 지금ms);
  const 분 = 한국분(지금ms);
  const r = 오늘기록(기록, 이름, t.날짜);
  for (const 창 of 창들) {
    if (분 < 창.시작 || 분 >= 창.끝) continue;
    if (분 < 시각을분으로(t[창.이름])) continue;
    if (r[창.이름]) continue;
    return 창.이름;
  }
  return null;
}

/* 받기에 **성공한 뒤** 부릅니다 — 기록을 고쳐서 돌려줍니다(같은 객체) */
export function 받음표시(기록, 이름, 창이름, 지금ms) {
  const 날짜 = 한국날짜(지금ms);
  const 전 = 오늘기록(기록, 이름, 날짜);
  기록[이름] = { 날짜, 오전: 전.오전 || null, 오후: 전.오후 || null };
  기록[이름][창이름] = 분을시각으로(한국분(지금ms));
  return 기록;
}

/* 건너뛸 때 로그에 찍는 말 — 「천천히 · 다음 09:47」 꼴 */
export function 건너뜀말(기록, 이름, 지금ms) {
  const t = 오늘창(이름, 지금ms);
  const 분 = 한국분(지금ms);
  const r = 오늘기록(기록, 이름, t.날짜);
  for (const 창 of 창들) {
    if (r[창.이름]) continue;                       // 이 창은 이미 받았습니다
    if (분 >= 창.끝) continue;                      // 이 창은 지났습니다
    return '천천히 · 다음 ' + t[창.이름];          // 아직 안 받은 가장 이른 창의 시각
  }
  const 받은수 = 창들.filter((창) => r[창.이름]).length;
  return 받은수 === 창들.length ? '천천히 · 오늘 두 번 다 받음'
    : 받은수 ? '천천히 · 오늘 한 번 받음 · 남은 창 지남'
      : '천천히 · 오늘 창 다 지남(한 번도 못 받음)';
}
