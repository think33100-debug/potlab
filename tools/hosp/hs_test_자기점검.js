/* stripTags 자기점검 — node tools/hosp/hs_test_자기점검.js
 *
 * 2026-10-18 에 `stripTags` 를 「진짜 태그만 걷기」로 고쳤습니다.
 * 설정 295개가 이 함수를 지나가므로, **기존 꼴이 그대로인지**가 더 중요합니다.
 * 사이트를 두드리지 않습니다. */
const { stripTags } = require('./hs_test.js');

const 짝 = [
  /* ── 전에도 되던 것 — 그대로여야 합니다 ───────────────── */
  ['<a href="/x?a=1&amp;b=2">물리치료사 채용</a>', '물리치료사 채용', '링크 안 제목'],
  ['<td class="sj">작업치료사 채용(신규, 경력)</td>', '작업치료사 채용(신규, 경력)', 'td'],
  ['줄<br>바꿈', '줄 바꿈', 'br'],
  ['<br/>자체닫기<BR />', '자체닫기', 'br 자체닫기·대문자'],
  ['<img src="a.gif" alt="파일" />제목', '제목', 'img'],
  ['<span style="color:#00f;">[채용중]</span> 작업치료사 채용', '[채용중] 작업치료사 채용', 'span + 스타일'],
  ['<!-- 숨긴 글 -->보이는 글', '보이는 글', 'HTML 주석'],
  ['<!DOCTYPE html>제목', '제목', 'DOCTYPE'],
  ['A&nbsp;B', 'A B', 'nbsp'],
  ['&lt;꺾쇠&gt; 글', '<꺾쇠> 글', '글자값으로 적힌 꺾쇠'],
  ['<p>  빈칸   많음  </p>', '빈칸 많음', '빈칸 줄이기'],
  ['<a\n href="/x"\n class="t">여러 줄 태그</a>', '여러 줄 태그', '태그가 여러 줄'],
  /* 속성 값 안의 `>` 는 **옛 정규식도** 태그 끝으로 봤습니다 — 고친 뒤에도 같습니다.
     HTML 로는 틀린 읽기지만 바꾸지 않습니다. 이번 고침의 범위가 아니고,
     295개 설정이 지금 동작에 맞춰져 있습니다 */
  ['<td data-x="a>b">값', 'b">값', '속성 안의 꺾쇠 — 전과 같음'],

  /* ── 이번에 고친 것 — 꺾쇠로 싸인 제목이 **살아야** 합니다 ─ */
  ['<a href="/x"><물리치료사 충원공고></a>', '<물리치료사 충원공고>', '광주씨티병원 실제 원문'],
  ['<2026년 한가위 정담장터>', '<2026년 한가위 정담장터>', '지침 5절의 그 보기'],
  ['<작업치료사> 모집', '<작업치료사> 모집', '꺾쇠 + 뒤에 글'],
  ['제목 <1차 합격자>', '제목 <1차 합격자>', '숫자로 시작하는 꺾쇠'],
  ['<td><긴급> 물리치료사</td>', '<긴급> 물리치료사', '태그와 꺾쇠가 섞임'],
];

const 어긴것 = [];
for (const [들어온것, 나올것, 이름] of 짝) {
  const 실제 = stripTags(들어온것);
  if (실제 !== 나올것) 어긴것.push(이름 + '\n      바란 것 「' + 나올것 + '」\n      나온 것 「' + 실제 + '」');
}

/* 빈 값 */
if (stripTags(null) !== '' || stripTags(undefined) !== '' || stripTags('') !== '') 어긴것.push('빈 값');

if (어긴것.length) {
  console.error('✗ stripTags 자기점검 실패 ' + 어긴것.length + '가지');
  for (const x of 어긴것) console.error('   · ' + x);
  process.exit(1);
}
console.log('○ stripTags 자기점검 통과 — ' + (짝.length + 1) + '가지 (사이트를 두드리지 않았습니다)');
