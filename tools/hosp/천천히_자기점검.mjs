/* 천천히(하루 2번) 자기점검 — node tools/hosp/천천히_자기점검.mjs
 *
 * 사이트를 두드리지 않고 파일도 안 씁니다. 합성 시각으로 `천천히.mjs` 의 규칙만 봅니다 —
 * 창 전 · 창 안 아직 안 받음 · 창 안 이미 받음 · 창 사이 · 오후 창 · 날짜 바뀌면 초기화 ·
 * 해시가 날마다·곳마다 다름 · 같은 날은 같은 값 · 한국시간(서버가 UTC 여도).
 * 어긴 것이 있으면 exit 1.
 */
import { 창들, 오늘창, 받을차례, 받음표시, 건너뜀말, 한국날짜, 한국분, 시각을분으로 } from './천천히.mjs';

const 어긴것 = [];
const 봐 = (말, 참) => { if (!참) 어긴것.push(말); };

/* 한국시간 「2026-11-09 09:30」 → ms (UTC 로는 9시간 전) */
const 때 = (날짜, 시각) => {
  const [y, m, d] = 날짜.split('-').map(Number);
  const [hh, mm] = 시각.split(':').map(Number);
  return Date.UTC(y, m - 1, d, hh, mm) - 9 * 3600e3;
};
const 이름 = '전남대학교병원';
const 날 = '2026-11-09';
const t = 오늘창(이름, 때(날, '08:00'));

/* ⓪ 바탕 — 날짜와 분이 한국시간으로 나오나 (서버가 UTC 여도 같은 값) */
봐('한국날짜 — 00:30 KST 는 전날 UTC 지만 오늘로', 한국날짜(때(날, '00:30')) === 날);
봐('한국분 — 09:30 은 570', 한국분(때(날, '09:30')) === 570);
봐('오늘창 날짜', t.날짜 === 날);

/* ① 정한 시각이 창 안에 있나 — 여러 곳 · 여러 날 */
{
  let 밖 = 0;
  for (const n of ['전남대학교병원', '아주대학교병원', '의료법인 정안의료재단 중앙병원', '삼육서울병원']) {
    for (let i = 0; i < 40; i++) {
      const x = 오늘창(n, 때(날, '08:00') + i * 86400e3);
      const 오전 = 시각을분으로(x.오전), 오후 = 시각을분으로(x.오후);
      if (!(오전 >= 9 * 60 && 오전 < 12 * 60)) 밖++;
      if (!(오후 >= 13 * 60 && 오후 < 18 * 60)) 밖++;
    }
  }
  봐('정한 시각이 창(09~12 · 13~18) 안 — 밖 ' + 밖, 밖 === 0);
}

/* ② 창 전(08:30) — 안 받음 · 다음은 오전 시각 */
봐('08:30 → null', 받을차례({}, 이름, 때(날, '08:30')) === null);
봐('08:30 말 — 다음 ' + t.오전, 건너뜀말({}, 이름, 때(날, '08:30')) === '천천히 · 다음 ' + t.오전);

/* ③ 오전 창 안인데 정한 시각 전 → 아직 */
{
  const 전1분 = 시각을분으로(t.오전) - 1;
  if (전1분 >= 9 * 60) {
    const ms = 때(날, '09:00') + (전1분 - 9 * 60) * 60e3;
    봐('오전 정한 시각 1분 전 → null', 받을차례({}, 이름, ms) === null);
  }
}

/* ④ 오전 창 안 · 정한 시각 지남 · 아직 안 받음 → '오전' */
const 오전뒤 = 때(날, t.오전) + 60e3;              // 정한 시각 1분 뒤
봐('오전 시각 지남 → 오전', 받을차례({}, 이름, 오전뒤) === '오전');
봐('정한 시각 딱 그 분에도 → 오전', 받을차례({}, 이름, 때(날, t.오전)) === '오전');

/* ⑤ 오전에 이미 받음 → 같은 창에서 다시 안 받음 */
const 기록 = 받음표시({}, 이름, '오전', 오전뒤);
봐('받음표시 — 날짜·오전 적힘', 기록[이름].날짜 === 날 && 기록[이름].오전 === 분꼴(오전뒤) && 기록[이름].오후 === null);
봐('오전 받은 뒤 같은 창 → null', 받을차례(기록, 이름, 오전뒤 + 10 * 60e3) === null);
봐('오전 받은 뒤 말 — 다음 ' + t.오후, 건너뜀말(기록, 이름, 오전뒤 + 10 * 60e3) === '천천히 · 다음 ' + t.오후);

/* ⑥ 창 사이(12:30) → 안 받음 */
봐('12:30 → null (안 받았어도)', 받을차례({}, 이름, 때(날, '12:30')) === null);
봐('12:30 → null (오전 받았어도)', 받을차례(기록, 이름, 때(날, '12:30')) === null);
봐('12:30 말 — 다음 오후', 건너뜀말({}, 이름, 때(날, '12:30')) === '천천히 · 다음 ' + t.오후);

/* ⑦ 오후 창 — 정한 시각 지남 → '오후' (오전 받았든 아니든) · 받으면 끝 */
const 오후뒤 = 때(날, t.오후) + 60e3;
봐('오후 시각 지남(오전 받음) → 오후', 받을차례(기록, 이름, 오후뒤) === '오후');
봐('오후 시각 지남(오전 못 받음) → 오후', 받을차례({}, 이름, 오후뒤) === '오후');
받음표시(기록, 이름, '오후', 오후뒤);
봐('오후 받은 뒤 → null', 받을차례(기록, 이름, 오후뒤 + 60e3) === null);
봐('오전 그대로 · 오후 적힘', 기록[이름].오전 === 분꼴(오전뒤) && 기록[이름].오후 === 분꼴(오후뒤));
봐('둘 다 받은 뒤 말', 건너뜀말(기록, 이름, 오후뒤 + 60e3) === '천천히 · 오늘 두 번 다 받음');
봐('18:30 → null', 받을차례({}, 이름, 때(날, '18:30')) === null);
봐('18:30 말(한 번도 못 받음)', 건너뜀말({}, 이름, 때(날, '18:30')) === '천천히 · 오늘 창 다 지남(한 번도 못 받음)');

/* ⑧ 날짜가 바뀌면 초기화 — 어제 둘 다 받았어도 오늘 오전 창에서 다시 받음 */
{
  const 내일 = '2026-11-10';
  const t2 = 오늘창(이름, 때(내일, '08:00'));
  const ms = 때(내일, t2.오전) + 60e3;
  봐('어제 기록은 오늘 안 침 → 오전', 받을차례(기록, 이름, ms) === '오전');
  받음표시(기록, 이름, '오전', ms);
  봐('새 날짜로 갈아씀 · 오후 비움', 기록[이름].날짜 === 내일 && 기록[이름].오후 === null);
}

/* ⑨ 해시 — 날마다 다르고, 곳마다 다르고, 같은 날은 같다 */
{
  const 날들 = Array.from({ length: 10 }, (_, i) => 오늘창(이름, 때(날, '10:00') + i * 86400e3));
  const 오전들 = new Set(날들.map((x) => x.오전)), 오후들 = new Set(날들.map((x) => x.오후));
  봐('열흘 가운데 오전 시각이 다른 날이 있다 (' + 오전들.size + '가지)', 오전들.size >= 5);
  봐('열흘 가운데 오후 시각이 다른 날이 있다 (' + 오후들.size + '가지)', 오후들.size >= 5);
  const 곳들 = ['전남대학교병원', '화순전남대학교병원', '빛고을전남대학교병원', '아주대학교병원', '삼육서울병원']
    .map((n) => 오늘창(n, 때(날, '10:00')).오전);
  봐('같은 날 곳마다 다르다 (' + new Set(곳들).size + '/5)', new Set(곳들).size >= 3);
  const a = 오늘창(이름, 때(날, '00:01')), b = 오늘창(이름, 때(날, '23:59'));
  봐('같은 날 아침·밤 같은 값', a.오전 === b.오전 && a.오후 === b.오후 && a.날짜 === b.날짜);
  봐('같은 입력 두 번 같은 값', JSON.stringify(오늘창('아주대학교병원', 때(날, '15:00'))) === JSON.stringify(오늘창('아주대학교병원', 때(날, '15:00'))));
}

/* ⑩ 기록 꼴이 어긋나도 죽지 않는다 */
봐('기록 null 이어도 돈다', 받을차례(null, 이름, 오전뒤) === '오전');
봐('기록 이름 없어도 돈다', 받을차례({ 딴곳: { 날짜: 날, 오전: '09:10', 오후: null } }, 이름, 오전뒤) === '오전');
봐('창 둘', 창들.length === 2 && 창들[0].이름 === '오전' && 창들[1].이름 === '오후');

function 분꼴(ms) { const 분 = 한국분(ms); return ('0' + Math.floor(분 / 60)).slice(-2) + ':' + ('0' + (분 % 60)).slice(-2); }

console.log('천천히 자기점검 — 견본 ' + 이름 + ' ' + 날 + ' 오전 ' + t.오전 + ' · 오후 ' + t.오후);
if (어긴것.length) {
  console.log('★ 어긴 것 ' + 어긴것.length);
  어긴것.forEach((x) => console.log('   ✗ ' + x));
  process.exit(1);
}
console.log('○ 다 맞습니다 (' + 어긴것.length + ' 어김)');
