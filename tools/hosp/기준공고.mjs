/* ── 열쇠 ── */
function 해시(s) {
  let h = 0;
  const t = String(s || '');
  for (let i = 0; i < t.length; i++) { h = ((h << 5) - h) + t.charCodeAt(i); h |= 0; }
  return (h >>> 0).toString(36);
}
/* 같은 글인데 바뀌는 물음표 칸 — 세션 · 쪽 번호 · 찾기 칸 */
const 버릴칸 = /^(phpsessid|jsessionid|sessionid|session_id|sid|page|cpage|pageindex|pageno|page_no|currentpage|startpage|nowpage|listpage|searchword|searchkeyword|keyword|search_item|search_order|sfl|stx|sca|sst|sod|spt)$/i;
/** 주소 → 열쇠 글. 못 만들면 null */
export function 주소꼴(u) {
  const t = String(u || '').trim();
  if (!t) return null;
  try {
    const x = new URL(t);
    const 집 = x.hostname.replace(/^www\./i, '').toLowerCase();
    const 포트 = x.port && x.port !== '80' && x.port !== '443' ? ':' + x.port : '';
    const 길 = x.pathname.replace(/;jsessionid=[^/?#]*/i, '').replace(/\/+$/, '');
    const 칸 = [...x.searchParams.entries()].filter(([k, v]) => v !== '' && !버릴칸.test(k))
      .map(([k, v]) => k + '=' + v).sort();
    return 집 + 포트 + 길 + (칸.length ? '?' + 칸.join('&') : '') + (x.hash && x.hash.length > 1 ? x.hash : '');
  } catch {
    return t.replace(/^https?:\/\//i, '').replace(/^www\./i, '').replace(/\/+$/, '').toLowerCase() || null;
  }
}
const 딱지 = /[\[(【<〈]\s*(접수\s*마감|모집\s*마감|채용\s*마감|마감|종료|완료|채용\s*완료|접수\s*중|모집\s*중|진행\s*중|접수\s*예정|예정|연장|new|공지)\s*[\])】>〉]/gi;
/** 제목 → 열쇠 글. 4자 못 되면 null */
export function 제목꼴(t) {
  const k = String(t || '').replace(딱지, '').toLowerCase().replace(/\s+/g, '').replace(/[^가-힣a-z0-9]/g, '');
  return k.length >= 4 ? k : null;
}
/** 쪽의 줄들 → [[주소열쇠|null, 제목열쇠|null], …] (그 쪽에서 하나뿐인 열쇠만) */
export function 쪽열쇠(줄들) {
  const 날 = (줄들 || []).map((r) => [주소꼴(r && r.url), 제목꼴(r && r.title)]);
  const 셈 = (i) => { const m = new Map(); for (const x of 날) if (x[i]) m.set(x[i], (m.get(x[i]) || 0) + 1); return m; };
  const 주셈 = 셈(0), 제셈 = 셈(1);
  return 날.map(([주, 제]) => [주 && 주셈.get(주) === 1 ? 해시(주) : null, 제 && 제셈.get(제) === 1 ? 해시(제) : null]);
}
const 같은글 = (a, b) => !!(a && b && ((a[0] && a[0] === b[0]) || (a[1] && a[1] === b[1])));
const 있나 = (열쇠, 쪽) => 쪽.some((x) => 같은글(열쇠, x));

/* ── 날짜 ── */
const 한국날 = (ms) => new Date(ms + 한국).toISOString().slice(0, 10);
const 날꼴 = (v) => {
  const m = String(v || '').match(/(20\d{2})[.\-/]\s?(\d{1,2})[.\-/]\s?(\d{1,2})/);
  return m ? m[1] + '-' + ('0' + m[2]).slice(-2) + '-' + ('0' + m[3]).slice(-2) : null;
};
const 두자리 = (n) => ('0' + n).slice(-2);
export function 때말(ms) {
  if (!Number.isFinite(ms)) return '?';
  const d = new Date(ms + 한국);
  return (d.getUTCMonth() + 1) + '/' + d.getUTCDate() + ' ' + 두자리(d.getUTCHours()) + ':' + 두자리(d.getUTCMinutes());
}

/* ── 고르기 ── */
/** 후보 쪽(예전)과 지금 쪽 → 고른 줄 번호 또는 -1. 열쇠는 두 쪽에서 다 맞은 것만 남깁니다 */
function 고를것(s, 줄들, 지금열쇠, 예전쪽, 오늘) {
  const 후보 = [];
  지금열쇠.forEach((k, i) => {
    const 주 = k[0] && 예전쪽.some((x) => x[0] === k[0]) ? k[0] : null;
    const 제 = k[1] && 예전쪽.some((x) => x[1] === k[1]) ? k[1] : null;
    if (주 || 제) 후보.push({ i, 열쇠: [주, 제] });
  });
  if (!후보.length) return null;
  if (열린것만.includes(s && s.type)) {
    const 마감 = (c) => 날꼴(줄들[c.i] && 줄들[c.i].to);
    const 상시 = 후보.find((c) => !마감(c));
    if (상시) return 상시;
    const 산것 = 후보.filter((c) => 마감(c) >= 오늘).sort((a, b) => (마감(b) > 마감(a) ? 1 : 마감(b) < 마감(a) ? -1 : a.i - b.i));
    return 산것[0] || null;
  }
  /* 줄 게시판 — 맨 위 글. 아래에 글이 있는 것을 먼저 (맨 끝 줄은 「밀림」과 「놓침」을 못 가립니다) */
  return 후보.find((c) => c.i < 줄들.length - 1) || 후보[0];
}

function 이웃적기(기준, 지금열쇠, i, n) {
  기준.앞 = 지금열쇠.slice(Math.max(0, i - 이웃수), i);
  기준.뒤 = 지금열쇠.slice(i + 1, i + 1 + 이웃수);
  기준.쪽수 = n;
}

function 고르기(곳, s, 줄들, 지금열쇠, 지금ms, 오늘) {
  if (!곳.쪽 || !Array.isArray(곳.쪽.줄)) { 곳.쪽 = { 때: 지금ms, 줄: 지금열쇠.slice(0, 쪽최대) }; return null; }
  if (지금ms - 곳.쪽.때 < 다시본시간 * 시간) return null;
  const c = 고를것(s, 줄들, 지금열쇠, 곳.쪽.줄, 오늘);
  if (!c) {
    /* 하루 넘게 이어진 글이 없음 — 쪽을 새로 적고 다음에 다시 */
    곳.쪽 = { 때: 지금ms, 줄: 지금열쇠.slice(0, 쪽최대) };
    return null;
  }
  const r = 줄들[c.i] || {};
  const 기준 = { 열쇠: c.열쇠, 제목: String(r.title || '').trim().slice(0, 60), 마감: 날꼴(r.to), 고른때: 지금ms, 찾은때: 지금ms };
  이웃적기(기준, 지금열쇠, c.i, 줄들.length);
  곳.기준 = 기준;
  곳.놓침 = null;
  return 기준;
}

/** 못 찾은 첫 바퀴 — { 밀림: 까닭 } 이면 새로 고르고, { 놓침: 까닭 } 이면 규칙 의심으로 적습니다 */
export function 못찾음가르기(s, 기준, 지금열쇠, 오늘) {
  if (열린것만.includes(s && s.type)) {
    if (기준.마감 && 기준.마감 < 오늘) return { 밀림: '마감 지나 목록에서 빠짐' };
    return { 놓침: 기준.마감 ? '마감 전인데 목록에서 빠짐' : '상시 공고가 목록에서 빠짐' };
  }
  const 앞 = Array.isArray(기준.앞) ? 기준.앞 : [];
  const 뒤 = Array.isArray(기준.뒤) ? 기준.뒤 : [];
  const 뒤남음 = 뒤.filter((k) => 있나(k, 지금열쇠)).length;
  const 앞남음 = 앞.filter((k) => 있나(k, 지금열쇠)).length;
  const 새글 = 지금열쇠.filter((k) => !있나(k, 앞) && !있나(k, 뒤)).length;
  if (뒤남음 > 0) return { 놓침: '아래 글은 남았는데 이 글만 없음' };
  /* 글이 하나뿐인 쪽(상무병원·영광종합병원 고정본 꼴) — 병원이 글을 바꿔 단 것일 수도 있어 까닭을 따로 적습니다 */
  if (!앞.length && !뒤.length) return { 놓침: '글 하나뿐인 쪽에서 글이 바뀜(병원이 바꿔 달았을 수 있음)' };
  if (앞남음 === 0) return { 놓침: '쪽 글이 전부 바뀜' };
  if (새글 === 0) return { 놓침: '새 글 없이 이 글이 없어짐' };
  return { 밀림: 뒤.length ? '새 글에 밀려 첫 쪽에서 빠짐' : '맨 끝 줄이 새 글에 밀림' };
}

/**
 * 받은 곳 하나 — 기록.기준[이름] 을 고칩니다. 던지지 않습니다.
 * @param 기록 게시판 건강 기록 (같은 객체를 고칩니다)
 * @param s 사이트 설정 (name · type)
 * @param g 사이트줄() 결과 — 실패(err)·줄 0 이면 아무것도 안 합니다
 * @returns {{ 일: string, 까닭?: string } | null}  일 = 고름 · 찾음 · 놓침 · 밀림 · 판정찾음 · 판정못찾음 · 견주지않음 · 기다림
 */
export function 기준보기(기록, s, g, 지금ms) {
  try {
    if (!기록 || typeof 기록 !== 'object' || !s || !s.name) return null;
    if (!g || g.err || !Array.isArray(g.rows) || !g.rows.length) return null;
    if (!기록.기준 || typeof 기록.기준 !== 'object' || Array.isArray(기록.기준)) 기록.기준 = {};
    const 이름 = String(s.name);
    const 곳 = 기록.기준[이름] && typeof 기록.기준[이름] === 'object' ? 기록.기준[이름] : {};
    기록.기준[이름] = 곳;
    곳.본때 = 지금ms;
    const 오늘 = 한국날(지금ms);
    const 줄들 = g.rows;
    const 지금열쇠 = 쪽열쇠(줄들);
    /* 후보 쪽은 40시간마다 새로 (고를 때만 씁니다) */
    const 쪽묵음 = !곳.쪽 || !(지금ms - Number(곳.쪽.때) < 쪽새로시간 * 시간);

    let 일 = null;
    if (!곳.기준 || !Array.isArray(곳.기준.열쇠)) {
      const 고른 = 고르기(곳, s, 줄들, 지금열쇠, 지금ms, 오늘);
      if (고른 && !Number.isFinite(곳.시작)) 곳.시작 = 지금ms;
      return 고른 ? { 일: '고름' } : { 일: '기다림' };
    }
    if (쪽묵음) 곳.쪽 = { 때: 지금ms, 줄: 지금열쇠.slice(0, 쪽최대) };

    const 기준 = 곳.기준;
    /* 덜 받은 쪽이면 견주지 않습니다 */
    const 견줄만 = 줄들.length * 2 >= Number(기준.쪽수 || 0);
    const i = 지금열쇠.findIndex((k) => 같은글(기준.열쇠, k));
    if (i >= 0) {
      기준.찾은때 = 지금ms;
      이웃적기(기준, 지금열쇠, i, 줄들.length);
      곳.놓침 = null;
      일 = { 일: '찾음' };
    } else if (!견줄만) {
      일 = { 일: '견주지않음' };
    } else if (!곳.놓침) {
      const 가름 = 못찾음가르기(s, 기준, 지금열쇠, 오늘);
      if (가름.밀림) {
        /* 판정 날짜는 그대로 둡니다 — 자주 밀리는 곳도 주 1회 판정을 받게 (새 기준으로) */
        곳.바꿈 = { 때: 지금ms, 까닭: 가름.밀림, 수: Number((곳.바꿈 && 곳.바꿈.수) || 0) + 1, 전제목: 기준.제목 };
        곳.기준 = null;
        const 고른 = 고르기(곳, s, 줄들, 지금열쇠, 지금ms, 오늘);
        return { 일: '밀림', 까닭: 가름.밀림 + (고른 ? ' · 새로 고름' : '') };
      }
      곳.놓침 = { 때: 지금ms, 까닭: 가름.놓침 };
      일 = { 일: '놓침', 까닭: 가름.놓침 };
    } else {
      일 = { 일: '놓침', 까닭: 곳.놓침.까닭 };
    }

    /* 주 1회 판정 — 견줄 만한 바퀴에서만 */
    const 기점 = 곳.판정 && Number.isFinite(곳.판정.때) ? 곳.판정.때
      : (Number.isFinite(곳.시작) ? 곳.시작 : 기준.고른때);
    if (견줄만 && 지금ms - 기점 >= 판정날수 * 하루) {
      if (!곳.놓침) {
        곳.판정 = { 때: 지금ms, 결과: '찾음', 연속: 0, 제목: 기준.제목 };
        return { 일: '판정찾음' };
      }
      const 연속 = Number((곳.판정 && 곳.판정.결과 === '못찾음' && 곳.판정.연속) || 0) + 1;
      곳.판정 = { 때: 지금ms, 결과: '못찾음', 연속, 까닭: 곳.놓침.까닭, 놓친때: 곳.놓침.때, 제목: 기준.제목 };
      if (연속 >= 연속바꿈) {
        /* 두 주 연속 — 그 글은 놓고 새로 고릅니다. 판정 줄은 다음 판정까지 남습니다 */
        곳.바꿈 = { 때: 지금ms, 까닭: 연속 + '주 연속 못 찾음', 수: Number((곳.바꿈 && 곳.바꿈.수) || 0) + 1, 전제목: 기준.제목 };
        곳.기준 = null;
        곳.놓침 = null;
      }
      return { 일: '판정못찾음', 까닭: 곳.판정.까닭 };
    }
    return 일;
  } catch {
    return null;
  }
}

/** 오래 안 받은 곳을 뺍니다 (바퀴 끝에 한 번). 뺀 수 */
export function 기준정리(기록, 지금ms) {
  if (!기록 || !기록.기준 || typeof 기록.기준 !== 'object') return 0;
  let n = 0;
  for (const [이름, 곳] of Object.entries(기록.기준)) {
    if (!곳 || !(Number(곳.본때) >= 지금ms - 버릴날수 * 하루)) { delete 기록.기준[이름]; n++; }
  }
  return n;
}

/**
 * 아침 메일용 — 기록 → { 곳수, 기준있음, 고르는중, 찾음, 못찾음:[{이름,제목,까닭,놓친때,연속}], 첫판정때 }
 * 판정은 곳마다 마지막 주 1회 판정. 아직 판정 전인 곳은 「찾음·못찾음」 어디에도 안 셉니다.
 */
export function 기준가르기(기록, 지금ms) {
  const 표 = 기록 && 기록.기준 && typeof 기록.기준 === 'object' && !Array.isArray(기록.기준) ? 기록.기준 : {};
  const out = { 곳수: 0, 기준있음: 0, 고르는중: 0, 판정전: 0, 찾음: 0, 못찾음: [], 첫판정때: null };
  for (const [이름, 곳] of Object.entries(표).sort((a, b) => a[0].localeCompare(b[0]))) {
    if (!곳 || typeof 곳 !== 'object') continue;
    out.곳수++;
    const 기준 = 곳.기준 && Array.isArray(곳.기준.열쇠) ? 곳.기준 : null;
    if (기준) out.기준있음++;
    /* 넷은 겹치지 않습니다 — 못 찾음 > 찾음 > 판정 전(기준 있음) > 고르는 중 */
    const 판 = 곳.판정;
    if (판 && 판.결과 === '못찾음') {
      out.못찾음.push({ 이름, 제목: 판.제목 || '', 까닭: 판.까닭 || '', 놓친때: 판.놓친때 ?? null, 연속: Number(판.연속 || 1) });
    } else if (판 && 판.결과 === '찾음') {
      out.찾음++;
    } else if (기준) {
      out.판정전++;
      const 때 = (Number.isFinite(곳.시작) ? 곳.시작 : Number(기준.고른때)) + 판정날수 * 하루;
      if (Number.isFinite(때) && (out.첫판정때 == null || 때 < out.첫판정때)) out.첫판정때 = 때;
    } else {
      out.고르는중++;
    }
  }
  return out;
}

/** 아침 메일 줄들 (게시판건강 아침줄 아래에 붙습니다) */
export function 기준줄(가름) {
  if (!가름 || !가름.곳수) return ['   기준 공고(주 1회) — 아직 고른 곳 없음 (하루 넘게 두 번 본 글에서 고릅니다)'];
  const 줄 = ['   기준 공고(주 1회) — 찾음 ' + 가름.찾음 + ' · 못 찾음 ' + 가름.못찾음.length
    + ' · 판정 전 ' + 가름.판정전 + ' · 고르는 중 ' + 가름.고르는중
    + (가름.판정전 && 가름.첫판정때 ? ' (첫 판정 ' + 때말(가름.첫판정때).split(' ')[0] + '부터)' : '')];
  for (const x of 가름.못찾음.slice(0, 10)) {
    줄.push('     ? ' + x.이름.slice(0, 20) + ' 「' + x.제목.slice(0, 28) + '」 · ' + x.까닭
      + (x.놓친때 ? ' · ' + 때말(x.놓친때) + '부터' : '') + (x.연속 >= 2 ? ' · ' + x.연속 + '주 연속(새로 고름)' : ''));
  }
  if (가름.못찾음.length > 10) 줄.push('     … 그리고 ' + (가름.못찾음.length - 10) + '곳 더');
  if (가름.못찾음.length) 줄.push('     (못 찾음 = 규칙 의심 · 원문 게시판에 그 글이 아직 있는지 먼저 보십시오)');
  return 줄;
}
